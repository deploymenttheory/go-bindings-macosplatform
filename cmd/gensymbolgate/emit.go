package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
)

// emit writes the data-driven symbol-resolution test. The table is generated;
// the two test functions are fixed. dlsym/objc_getClass have no side effects and
// never call into the resolved code, so the gate is safe to run unconditionally.
func emit(path string, entries []entry, baseline map[string]bool) error {
	var b bytes.Buffer
	b.WriteString("// Code generated by cmd/gensymbolgate. DO NOT EDIT.\n\n")
	b.WriteString("//go:build darwin\n\n")
	// Its own package: it resolves symbols by NAME string via dlsym/objc_getClass
	// and imports no framework packages, so it compiles and runs independently of
	// the acceptance package's framework imports (and their pre-existing cycles) —
	// covering even the frameworks those cycles would otherwise exclude.
	b.WriteString("package symbolgate\n\n")
	b.WriteString("import (\n\t\"testing\"\n\n")
	b.WriteString("\t\"github.com/deploymenttheory/go-bindings-macosplatform/bindings/runtime/purego\"\n)\n\n")

	b.WriteString("type symbolGateEntry struct {\n\tframework string\n\tdylib     string\n\tfuncs     []string\n\texterns   []string\n\tclasses   []string\n}\n\n")

	b.WriteString("var symbolGateTable = []symbolGateEntry{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t{\n\t\tframework: %q,\n\t\tdylib:     %q,\n", e.framework, e.dylib)
		writeStrings(&b, "funcs", e.funcs)
		writeStrings(&b, "externs", e.externs)
		writeStrings(&b, "classes", e.classes)
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")

	// The baseline of known-unresolved symbols (keyed "kind|framework|name"),
	// baked in so the test is self-contained. A failure IN the baseline is
	// tolerated (logged); a failure NOT in it fails the PR.
	keys := make([]string, 0, len(baseline))
	for k := range baseline {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	b.WriteString("var symbolGateBaseline = map[string]bool{\n")
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%q: true,\n", k)
	}
	b.WriteString("}\n\n")

	b.WriteString(symbolGateBody)

	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("format %s: %w", path, err)
	}
	return os.WriteFile(path, src, 0o644)
}

func writeStrings(b *bytes.Buffer, field string, vals []string) {
	if len(vals) == 0 {
		return
	}
	fmt.Fprintf(b, "\t\t%s: []string{", field)
	for i, v := range vals {
		if i > 0 {
			b.WriteString(", ")
		}
		b.WriteString(strconv.Quote(v))
	}
	b.WriteString("},\n")
}

// symbolGateBody is the fixed test logic. TestSymbolResolution dlopens each
// framework's dylib and dlsyms every bound function and extern symbol against it
// (exactly how the generated bindings resolve them at runtime). TestClassResolution
// dlopens the dylib so its classes register, then objc_getClass each one. Neither
// calls the resolved code, so both are crash-free.
const symbolGateBody = `
// baselined reports whether an unresolved (kind, framework, name) is a known,
// tolerated failure. A failure not in the baseline fails the test.
func baselined(kind, framework, name string) bool {
	return symbolGateBaseline[kind+"|"+framework+"|"+name]
}

func TestSymbolResolution(t *testing.T) {
	for _, e := range symbolGateTable {
		h, err := purego.Dlopen(e.dylib, purego.RTLD_LAZY|purego.RTLD_GLOBAL)
		if err != nil {
			if !baselined("dlopen", e.framework, e.dylib) {
				t.Errorf("%s: dlopen %s failed (not in baseline): %v", e.framework, e.dylib, err)
			}
			continue
		}
		for _, s := range e.funcs {
			if _, err := purego.Dlsym(h, s); err != nil && !baselined("function", e.framework, s) {
				t.Errorf("%s: unresolved function symbol %q (not in baseline — a binding to a nonexistent symbol)", e.framework, s)
			}
		}
		for _, s := range e.externs {
			if _, err := purego.Dlsym(h, s); err != nil && !baselined("extern", e.framework, s) {
				t.Errorf("%s: unresolved extern symbol %q (not in baseline)", e.framework, s)
			}
		}
	}
}

func TestClassResolution(t *testing.T) {
	for _, e := range symbolGateTable {
		if _, err := purego.Dlopen(e.dylib, purego.RTLD_LAZY|purego.RTLD_GLOBAL); err != nil {
			continue // the dlopen failure is reported by TestSymbolResolution
		}
		for _, name := range e.classes {
			if purego.GetClass(name) == 0 && !baselined("class", e.framework, name) {
				t.Errorf("%s: ObjC class %q not found (not in baseline)", e.framework, name)
			}
		}
	}
}
`
