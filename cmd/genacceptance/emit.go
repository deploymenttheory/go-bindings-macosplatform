//go:build darwin

package main

import (
	"fmt"
	"io"
	"sort"
	"strings"
	"time"
)

// emitTestFile writes the complete Go acceptance test file to w.
func emitTestFile(w io.Writer, records []FuncRecord, seed int64, modulePrefix string) error {
	// Collect unique import paths.
	importPaths := map[string]bool{"testing": true}
	for _, r := range records {
		importPaths[r.GoImportPath] = true
	}

	fmt.Fprintf(w, "// Code generated by cmd/genacceptance. DO NOT EDIT.\n")
	fmt.Fprintf(w, "// Seed: 0x%x  Generated: %s\n", seed, time.Now().UTC().Format(time.RFC3339))
	fmt.Fprintf(w, "//go:build darwin\n\n")
	fmt.Fprintf(w, "package acceptance_test\n\n")

	// Write sorted import block.
	paths := make([]string, 0, len(importPaths))
	for p := range importPaths {
		paths = append(paths, p)
	}
	sort.Strings(paths)
	fmt.Fprintf(w, "import (\n")
	for _, p := range paths {
		fmt.Fprintf(w, "\t%q\n", p)
	}
	fmt.Fprintf(w, ")\n\n")

	// Prevent "declared and not used" for the testing package when all sampled
	// functions return void (their test bodies have no assignment).
	fmt.Fprintf(w, "// Ensure the testing import is used even when all sampled functions return void.\n")
	fmt.Fprintf(w, "var _ *testing.T\n\n")

	for _, r := range records {
		if err := emitTest(w, r); err != nil {
			return err
		}
	}
	return nil
}

// emitTest writes a single test function.
func emitTest(w io.Writer, r FuncRecord) error {
	fmt.Fprintf(w, "// %s\n", r.TestName)
	fmt.Fprintf(w, "// %s\n", r.ID)
	fmt.Fprintf(w, "func %s(t *testing.T) {\n", r.TestName)
	fmt.Fprintf(w, "\trunIsolated(t, %q, func(t *testing.T) {\n", r.ID)

	body := buildBody(r)
	for _, line := range strings.Split(body, "\n") {
		if line == "" {
			fmt.Fprintln(w)
		} else {
			fmt.Fprintf(w, "\t\t%s\n", line)
		}
	}

	fmt.Fprintf(w, "\t})\n")
	fmt.Fprintf(w, "}\n\n")
	return nil
}

// buildBody returns the Go statements for the test body (no outer indentation).
func buildBody(r FuncRecord) string {
	call := r.GoPackage + "." + r.GoFuncName + "()"

	// Some C declarations have no dylib export (header-inline functions,
	// symbols dropped in newer macOS releases). Calling their wrapper would
	// dereference a nil function variable — skip instead.
	if r.IsCFunction {
		guard := fmt.Sprintf(
			"if !%s.SymbolAvailable(%q) {\n\tt.Skip(%q)\n}\n",
			r.GoPackage, r.Selector, r.ID+": symbol not exported by the dylib on this system",
		)
		return guard + buildCallBody(r, call)
	}
	return buildCallBody(r, call)
}

// buildCallBody returns the call-and-assert statements for the test body.
func buildCallBody(r FuncRecord, call string) string {

	switch r.Category {
	case CatZeroArgFactory:
		if r.RetKind == RetPointer {
			return fmt.Sprintf(
				"result := %s\nif result == nil {\n\tt.Error(%q)\n}",
				call, r.ID+": expected non-nil return",
			)
		}
		return callStatement(r.RetKind, call)

	case CatSingleton:
		if r.RetKind == RetPointer {
			return fmt.Sprintf(
				"result := %s\nif result == nil {\n\tt.Skip(%q)\n}",
				call, r.ID+": returned nil — environment may not provide this singleton",
			)
		}
		return callStatement(r.RetKind, call)

	case CatZeroArgScalar:
		return callStatement(r.RetKind, call)
	}
	return callStatement(r.RetKind, call)
}

// callStatement produces the right Go statement for a non-nil-checked call:
// void functions become a plain statement; scalar/pointer get "_ = call".
func callStatement(retKind RetKind, call string) string {
	if retKind == RetVoid {
		return call
	}
	return fmt.Sprintf("_ = %s", call)
}
