// Package emit generates Go source files from parsed Swift framework metadata.
package emit

import (
	"bytes"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"

	"github.com/deploymenttheory/go-bindings-macosplatform/internal/swift/meta"
)

const generatedHeader = "// Code generated by go-bindings-codegen. DO NOT EDIT.\n\n//go:build darwin\n\n"

// Emit writes Swift-derived Go type files into outDir.
// It produces up to three files (empty sections are skipped):
//   - {fw}_enums.go   — typed constants for Swift enums
//   - {fw}_errors.go  — error types for Swift error structs
//   - {fw}_structs.go — value types for Swift structs
func Emit(framework *meta.FrameworkMeta, outDir, pkgName string) error {
	packageName := strings.ToLower(framework.Framework)

	sections := []struct {
		suffix     string
		fn         func(*meta.FrameworkMeta, string) ([]byte, error)
		hasContent func(*meta.FrameworkMeta) bool
	}{
		{"_enums", emitEnums, func(f *meta.FrameworkMeta) bool { return len(f.Enums) > 0 }},
		{"_errors", emitErrors, func(f *meta.FrameworkMeta) bool { return len(f.ErrorStructs) > 0 }},
		{"_structs", emitStructs, func(f *meta.FrameworkMeta) bool { return len(f.Structs) > 0 }},
	}

	for _, s := range sections {
		if !s.hasContent(framework) {
			continue
		}
		data, err := s.fn(framework, pkgName)
		if err != nil {
			return fmt.Errorf("emit %s%s: %w", packageName, s.suffix, err)
		}
		name := filepath.Join(outDir, packageName+s.suffix+".go")
		if err := os.WriteFile(name, data, 0o644); err != nil {
			return fmt.Errorf("write %s: %w", name, err)
		}
	}
	return nil
}

// emitEnums generates the *_enums.go file.
func emitEnums(framework *meta.FrameworkMeta, pkgName string) ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "%spackage %s\n", generatedHeader, pkgName)

	enums := make([]*meta.Enum, len(framework.Enums))
	copy(enums, framework.Enums)
	sort.Slice(enums, func(i, j int) bool { return enums[i].Name < enums[j].Name })

	seen := make(map[string]bool)
	for _, e := range enums {
		if len(e.Cases) == 0 || seen[e.Name] {
			continue
		}
		seen[e.Name] = true
		buf.WriteByte('\n')
		writeAvailComment(&buf, e.Availability, "")
		goType := e.RawGoType
		if goType == "" {
			goType = "int"
		}
		fmt.Fprintf(&buf, "type %s %s\n", e.Name, goType)
		fmt.Fprintf(&buf, "const (\n")
		for i, c := range e.Cases {
			writeAvailComment(&buf, c.Availability, "\t")
			constName := e.Name + toPascalCase(c.Name)
			if e.RawGoType == "" {
				// Plain enum: use iota
				if i == 0 {
					fmt.Fprintf(&buf, "\t%s %s = iota\n", constName, e.Name)
				} else {
					fmt.Fprintf(&buf, "\t%s\n", constName)
				}
			} else {
				// Raw-value enum: use explicit value, or derive a default.
				val := c.RawValue
				if val == "" {
					if e.RawGoType == "string" {
						// Swift convention: implicit string raw value = case name
						val = `"` + c.Name + `"`
					} else {
						val = fmt.Sprintf("%d", i)
					}
				}
				fmt.Fprintf(&buf, "\t%s %s = %s\n", constName, e.Name, val)
			}
		}
		fmt.Fprintf(&buf, ")\n")
	}
	return buf.Bytes(), nil
}

// emitErrors generates the *_errors.go file.
func emitErrors(framework *meta.FrameworkMeta, pkgName string) ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "%spackage %s\n\nimport \"fmt\"\n", generatedHeader, pkgName)

	errStructs := make([]*meta.ErrorStruct, len(framework.ErrorStructs))
	copy(errStructs, framework.ErrorStructs)
	sort.Slice(errStructs, func(i, j int) bool { return errStructs[i].Name < errStructs[j].Name })

	seenErr := make(map[string]bool)
	for _, e := range errStructs {
		if seenErr[e.Name] {
			continue
		}
		seenErr[e.Name] = true
		buf.WriteByte('\n')
		writeAvailComment(&buf, e.Availability, "")
		fmt.Fprintf(&buf, "type %s struct{ code int }\n\n", e.Name)

		if len(e.StaticCodes) > 0 {
			fmt.Fprintf(&buf, "// %s sentinel values.\n", e.Name)
			fmt.Fprintf(&buf, "//nolint:gochecknoglobals\n")
			fmt.Fprintf(&buf, "var (\n")
			for i, sc := range e.StaticCodes {
				writeAvailComment(&buf, sc.Availability, "\t")
				fmt.Fprintf(&buf, "\t%s%s = %s{code: %d}\n",
					e.Name, toPascalCase(sc.Name), e.Name, i)
			}
			fmt.Fprintf(&buf, ")\n\n")
		}

		fmt.Fprintf(&buf, "func (e %s) Error() string {\n", e.Name)
		fmt.Fprintf(&buf, "\tswitch e.code {\n")
		for i, sc := range e.StaticCodes {
			fmt.Fprintf(&buf, "\tcase %d:\n\t\treturn \"%s: %s\"\n",
				i, pkgName, toErrorMessage(sc.Name))
		}
		fmt.Fprintf(&buf, "\tdefault:\n\t\treturn fmt.Sprintf(\"%s: error code %%d\", e.code)\n", pkgName)
		fmt.Fprintf(&buf, "\t}\n}\n")
	}
	return buf.Bytes(), nil
}

// emitStructs generates the *_structs.go file.
func emitStructs(framework *meta.FrameworkMeta, pkgName string) ([]byte, error) {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "%spackage %s\n", generatedHeader, pkgName)

	structs := make([]*meta.Struct, len(framework.Structs))
	copy(structs, framework.Structs)
	sort.Slice(structs, func(i, j int) bool { return structs[i].Name < structs[j].Name })

	seenStruct := make(map[string]bool)
	for _, s := range structs {
		if seenStruct[s.Name] {
			continue
		}
		seenStruct[s.Name] = true
		buf.WriteByte('\n')
		writeAvailComment(&buf, s.Availability, "")
		if s.IsValueEnum {
			writeValueEnum(&buf, s, pkgName)
		} else {
			writeRegularStruct(&buf, s)
		}
	}
	return buf.Bytes(), nil
}

func writeValueEnum(w io.Writer, s *meta.Struct, pkgName string) {
	fmt.Fprintf(w, "type %s struct{ value int }\n\n", s.Name)
	if len(s.StaticValues) > 0 {
		fmt.Fprintf(w, "// %s named values.\n", s.Name)
		fmt.Fprintf(w, "//nolint:gochecknoglobals\n")
		fmt.Fprintf(w, "var (\n")
		for i, sv := range s.StaticValues {
			writeAvailComment(w, sv.Availability, "\t")
			fmt.Fprintf(w, "\t%s%s = %s{value: %d}\n",
				s.Name, toPascalCase(sv.Name), s.Name, i)
		}
		fmt.Fprintf(w, ")\n")
	}
}

func writeRegularStruct(w io.Writer, s *meta.Struct) {
	fmt.Fprintf(w, "type %s struct {\n", s.Name)
	for _, f := range s.Fields {
		writeAvailComment(w, f.Availability, "\t")
		fmt.Fprintf(w, "\t%s %s\n", toPascalCase(f.Name), f.GoType)
	}
	fmt.Fprintf(w, "}\n")
}

// writeAvailComment emits a "// Introduced: macOS X.Y" comment if availability is set.
func writeAvailComment(w io.Writer, av meta.Availability, prefix string) {
	if av.MacOSIntroduced != "" {
		fmt.Fprintf(w, "%s// Introduced: macOS %s\n", prefix, av.MacOSIntroduced)
	}
}

// toPascalCase uppercases the first letter of a camelCase Swift name.
// "installed" → "Installed", "highFidelity" → "HighFidelity"
func toPascalCase(s string) string {
	if s == "" {
		return ""
	}
	runes := []rune(s)
	runes[0] = unicode.ToUpper(runes[0])
	return string(runes)
}

// toErrorMessage converts a camelCase Swift name to a space-separated error message.
// "unsupportedSourceLanguage" → "unsupported source language"
func toErrorMessage(name string) string {
	var words []string
	var current strings.Builder
	for _, r := range name {
		if unicode.IsUpper(r) && current.Len() > 0 {
			words = append(words, current.String())
			current.Reset()
		}
		current.WriteRune(unicode.ToLower(r))
	}
	if current.Len() > 0 {
		words = append(words, current.String())
	}
	return strings.Join(words, " ")
}
