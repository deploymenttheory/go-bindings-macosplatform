package pipeline

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/deploymenttheory/go-bindings-macosplatform/internal/macosplatformmetadata"
)

// EmitObjCClassHierarchy reads all .gometa.json files in metadataPaths, derives
// the canonical superclass and owning framework for every ObjC class, and writes
// the result to outputPath as a committed Go source file containing
// ObjCClassSuperclassIndex and ObjCClassFrameworkIndex.
//
// Canonical ownership is determined by "fewest non-zero methods wins" — the
// same heuristic used by LoadAll. The output carries no darwin build constraint
// and is the authoritative ObjC class hierarchy for the code generator's
// inherited-method filter and foreign-extension resolution.
func EmitObjCClassHierarchy(metadataPaths []string, outputPath string) error {
	resolved, err := resolvePaths(metadataPaths)
	if err != nil {
		return err
	}

	// Load all frameworks, deduplicating by name (first-write-wins on sorted
	// path order, which places top-level frameworks before sub-frameworks).
	type frameworkEntry struct {
		name    string
		classes map[string]macosplatformmetadata.Class
	}
	seen := make(map[string]bool)
	var frameworks []frameworkEntry
	for _, p := range resolved {
		framework, err := macosplatformmetadata.Read(p)
		if err != nil {
			return fmt.Errorf("load %s: %w", p, err)
		}
		if seen[framework.Framework] || len(framework.Classes) == 0 {
			continue
		}
		seen[framework.Framework] = true
		frameworks = append(frameworks, frameworkEntry{framework.Framework, framework.Classes})
	}

	// Collect every (className, framework) candidate across all loaded frameworks.
	type candidate struct {
		framework string
		score     int // len(Methods) + len(Properties) — used for ownership resolution
		super     string
	}
	allCandidates := make(map[string][]candidate)
	for _, framework := range frameworks {
		for className, class := range framework.classes {
			allCandidates[className] = append(allCandidates[className], candidate{
				framework: framework.name,
				score:     len(class.Methods) + len(class.Properties),
				super:     class.Super,
			})
		}
	}

	classToSuperclass := make(map[string]string, len(allCandidates))
	classToFramework := make(map[string]string, len(allCandidates))

	for className, candidates := range allCandidates {
		// Prefer non-ghost entries (score > 0); fall back to ghosts when all are zero.
		var nonGhost []candidate
		for _, c := range candidates {
			if c.score > 0 {
				nonGhost = append(nonGhost, c)
			}
		}
		pool := nonGhost
		if len(pool) == 0 {
			pool = candidates
		}
		// Fewest methods = most canonical definition; break ties alphabetically.
		winner := pool[0]
		for _, c := range pool[1:] {
			if c.score < winner.score || (c.score == winner.score && c.framework < winner.framework) {
				winner = c
			}
		}
		classToSuperclass[className] = winner.super
		classToFramework[className] = winner.framework
	}

	return writeObjCClassHierarchyFile(outputPath, classToSuperclass, classToFramework)
}

func writeObjCClassHierarchyFile(outputPath string, classToSuperclass, classToFramework map[string]string) error {
	classNames := make([]string, 0, len(classToSuperclass))
	for name := range classToSuperclass {
		classNames = append(classNames, name)
	}
	sort.Strings(classNames)

	var sb strings.Builder
	sb.WriteString("// Code generated by go-bindings-codegen. DO NOT EDIT.\n")
	sb.WriteString("// Regenerate with: go run ./cmd/generate/ class-hierarchy\n\n")
	sb.WriteString("package objcclasshierarchy\n\n")

	sb.WriteString("// ObjCClassSuperclassIndex maps each ObjC class name to its canonical superclass name.\n")
	sb.WriteString("// The empty string denotes a root class (no superclass, e.g. NSObject).\n")
	sb.WriteString("// Generated from committed .gometa.json files; regenerate after SDK upgrades.\n")
	sb.WriteString("var ObjCClassSuperclassIndex = map[string]string{\n")
	for _, name := range classNames {
		sb.WriteString(fmt.Sprintf("\t%q: %q,\n", name, classToSuperclass[name]))
	}
	sb.WriteString("}\n\n")

	sb.WriteString("// ObjCClassFrameworkIndex maps each ObjC class name to its canonical owning framework.\n")
	sb.WriteString("// Used by the loader to resolve cross-framework ObjC class inheritance chains.\n")
	sb.WriteString("var ObjCClassFrameworkIndex = map[string]string{\n")
	for _, name := range classNames {
		sb.WriteString(fmt.Sprintf("\t%q: %q,\n", name, classToFramework[name]))
	}
	sb.WriteString("}\n")

	formatted, err := format.Source([]byte(sb.String()))
	if err != nil {
		return fmt.Errorf("formatting ObjC class hierarchy: %w", err)
	}

	if err := os.MkdirAll(filepath.Dir(outputPath), 0o755); err != nil {
		return fmt.Errorf("mkdir for %s: %w", outputPath, err)
	}
	return os.WriteFile(outputPath, formatted, 0o644)
}
