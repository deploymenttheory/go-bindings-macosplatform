func buildMinimalRegistry(frameworkName string, cls map[string]macosplatformmetadata.Class) *Registry {
	framework := &macosplatformmetadata.FrameworkMeta{
		Framework: frameworkName,
		Classes:   cls,
	}
	reg := &Registry{
		Frameworks:     []*macosplatformmetadata.FrameworkMeta{framework},
		ClassNameIndex: make(map[string]bool),
		GenericClasses: make(map[string]bool),
		OwnerIndex:     make(map[string]string),
		ClassIndex:     make(map[string]macosplatformmetadata.Class),
		ModulePrefix:   "github.com/example/fw",
	}
	for name := range cls {
		reg.ClassNameIndex[name] = true
		reg.OwnerIndex[name] = frameworkName
		reg.ClassIndex[name] = cls[name]
	}
	return reg
}

// makeBindingsCfg returns a BindingsConfig writing to a temporary frameworks dir.
func makeBindingsCfg(t *testing.T, reg *Registry, frameworksOutDir string) BindingsConfig {
	t.Helper()
	return BindingsConfig{
		Registry:         reg,
		FrameworksOutDir: frameworksOutDir,
	}
}

// TestGenerateFrameworkCleansStaleFiles verifies that generating into a directory
// that already contains .go files removes them before writing new ones.
// TestWriteFileErrorFromFn verifies writeFile propagates an error returned by fn.
func TestWriteFileErrorFromFn(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "test.go")
	sentinelErr := fmt.Errorf("sentinel error")
	err := writeFile(path, func(buf *bytes.Buffer) error {
		return sentinelErr
	})
	if err == nil {
		t.Error("writeFile should propagate fn error")
	}
	if _, statErr := os.Stat(path); statErr == nil {
		t.Error("writeFile should not create file when fn errors")
	}
}

// TestResolvePathsNonJSONFile verifies resolvePaths rejects non-.gometa.json file paths.
func TestResolvePathsNonJSONFile(t *testing.T) {
	dir := t.TempDir()
	badFile := filepath.Join(dir, "something.txt")
	if err := os.WriteFile(badFile, []byte("x"), 0o644); err != nil {
		t.Fatal(err)
	}
	_, err := resolvePaths([]string{badFile})
	if err == nil {
		t.Error("resolvePaths should reject non-.gometa.json file")
	}
}

// TestResolvePathsNonexistent verifies resolvePaths returns error for missing path.
func TestResolvePathsNonexistent(t *testing.T) {
	_, err := resolvePaths([]string{"/nonexistent/path/does/not/exist"})
	if err == nil {
		t.Error("resolvePaths should return error for nonexistent path")
	}
}
