// writeGoHeader / writeGoHeaderRuntime / writeGoHeaderCGO
// --------------------------------------------------------------------------

func TestWriteGoHeaderBasic(t *testing.T) {
	var buf bytes.Buffer
	writeGoHeader(&buf, "foundation", false)
	out := buf.String()
	if !strings.Contains(out, "Code generated by go-bindings-codegen") {
		t.Errorf("missing generated marker; got:\n%s", out)
	}
	if !strings.Contains(out, "//go:build darwin") {
		t.Errorf("missing build tag; got:\n%s", out)
	}
	if !strings.Contains(out, "package foundation") {
		t.Errorf("missing package declaration; got:\n%s", out)
	}
	if strings.Contains(out, "unsafe") {
		t.Errorf("no-unsafe header should not import unsafe; got:\n%s", out)
	}
}

func TestWriteGoHeaderWithUnsafe(t *testing.T) {
	var buf bytes.Buffer
	writeGoHeader(&buf, "foundation", true)
	if !strings.Contains(buf.String(), "unsafe") {
		t.Error("needsUnsafe=true should import unsafe")
	}
}

func TestWriteGoHeaderRuntime(t *testing.T) {
	var buf bytes.Buffer
	writeGoHeaderRuntime(&buf, "foundation")
	out := buf.String()
	if !strings.Contains(out, "cgo") {
		t.Errorf("runtime header should import objc package; got:\n%s", out)
	}
	if !strings.Contains(out, "unsafe") {
		t.Errorf("runtime header should import unsafe; got:\n%s", out)
	}
}

func TestWriteGoHeaderCGO(t *testing.T) {
	var buf bytes.Buffer
	writeGoHeaderCGO(&buf, "foundation", "foundation")
	out := buf.String()
	if !strings.Contains(out, "import \"C\"") {
		t.Errorf("CGO header should have import \"C\"; got:\n%s", out)
	}
	if !strings.Contains(out, "foundation_bridge.h") {
		t.Errorf("CGO header should include bridge header; got:\n%s", out)
	}
}

