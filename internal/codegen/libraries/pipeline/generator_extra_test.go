// singleLibraryRegistry builds a one-entry registry for the named C library.
// A non-empty LinkLib is what marks a meta as a library — the only kind of meta
// this pipeline emits.
func singleLibraryRegistry(meta *macosplatformmetadata.FrameworkMeta) *Registry {
	return &Registry{
		Frameworks:     []*macosplatformmetadata.FrameworkMeta{meta},
		ClassNameIndex: make(map[string]bool),
		GenericClasses: make(map[string]bool),
		OwnerIndex:     make(map[string]string),
		ClassIndex:     make(map[string]macosplatformmetadata.Class),
		ModulePrefix:   "github.com/example/bindings/internal/raw/libraries",
	}
}

// useCommittedCLibraries points the scanner's library registry at the committed
// metadata/clibraries.json, so CLibraryBackend reports the real per-library
// backend instead of the built-in fallback map's empty one.
func useCommittedCLibraries(t *testing.T) {
	t.Helper()
	found, err := scanner.LoadCLibrariesFile(
		filepath.Join("..", "..", "..", "..", "metadata", "clibraries.json"),
	)
	if err != nil {
		t.Fatalf("LoadCLibrariesFile: %v", err)
	}
	if !found {
		t.Skip("metadata/clibraries.json not found")
	}
}

// sandboxCwd moves the test into a scratch working directory. GenerateBindings
// writes the shared bsd support package to a repo-relative path (defaultBsdDir),
// so a test that runs it from the package directory would litter the source
// tree. Call after any helper that reads a repo-relative file.
func sandboxCwd(t *testing.T) {
	t.Helper()
	t.Chdir(t.TempDir())
}

// TestGenerateLibraryEmitsPuregoPackage runs the whole pipeline over a minimal
// library meta and checks the file set: a doc.go, the emitted declarations, and
// the purego runtime file that dlopens the dylib. No bridge, no import "C".
func TestGenerateLibraryEmitsPuregoPackage(t *testing.T) {
	useCommittedCLibraries(t)
	sandboxCwd(t)

	meta := &macosplatformmetadata.FrameworkMeta{
		Framework: "bsm",
		LinkLib:   "bsm",
		Enums: map[string]macosplatformmetadata.Enum{
			"au_event_t": {
				GoType:  "uint16",
				Members: []macosplatformmetadata.EnumMember{{Name: "AUE_NULL", Value: "0"}},
			},
		},
		Functions: []macosplatformmetadata.Function{
			{Name: "au_open", Return: macosplatformmetadata.ReturnType{ObjCType: "int"}},
		},
	}
	outDir := t.TempDir()
	if err := GenerateBindings(BindingsConfig{
		Registry:        singleLibraryRegistry(meta),
		LibrariesOutDir: outDir,
	}); err != nil {
		t.Fatalf("GenerateBindings: %v", err)
	}

	pkgDir := filepath.Join(outDir, "bsm")
	for _, name := range []string{"doc.go", "bsm_enums.go", "bsm_functions.go", "bsm_runtime.go"} {
		if _, err := os.Stat(filepath.Join(pkgDir, name)); err != nil {
			t.Errorf("expected %s to be generated: %v", name, err)
		}
	}

	runtimeSrc, err := os.ReadFile(filepath.Join(pkgDir, "bsm_runtime.go"))
	if err != nil {
		t.Fatalf("reading runtime file: %v", err)
	}
	if !strings.Contains(string(runtimeSrc), "/usr/lib/libbsm.dylib") {
		t.Errorf("runtime file should dlopen the dylib; got:\n%s", runtimeSrc)
	}

	entries, err := os.ReadDir(pkgDir)
	if err != nil {
		t.Fatalf("reading package dir: %v", err)
	}
	for _, e := range entries {
		if strings.HasSuffix(e.Name(), ".m") || strings.HasSuffix(e.Name(), ".h") || e.Name() == "bridge" {
			t.Errorf("purego package must contain no ObjC bridge artefacts; found %s", e.Name())
		}
		if !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		src, readErr := os.ReadFile(filepath.Join(pkgDir, e.Name()))
		if readErr != nil {
			t.Fatalf("reading %s: %v", e.Name(), readErr)
		}
		if strings.Contains(string(src), "import \"C\"") {
			t.Errorf("%s must not use cgo", e.Name())
		}
	}
}

// TestGenerateSkipsObjCFrameworks verifies that a meta with no LinkLib — an ObjC
// framework, owned by the purego frameworks pipeline — produces nothing here.
func TestGenerateSkipsObjCFrameworks(t *testing.T) {
	sandboxCwd(t)
	outDir := t.TempDir()
	if err := GenerateBindings(BindingsConfig{
		Registry: singleLibraryRegistry(&macosplatformmetadata.FrameworkMeta{
			Framework: "Foundation",
			Enums: map[string]macosplatformmetadata.Enum{
				"NSComparisonResult": {GoType: "int"},
			},
		}),
		LibrariesOutDir: outDir,
	}); err != nil {
		t.Fatalf("GenerateBindings: %v", err)
	}
	if _, err := os.Stat(filepath.Join(outDir, "foundation")); !os.IsNotExist(err) {
		t.Errorf("ObjC framework meta should not be emitted by the libraries pipeline (stat err: %v)", err)
	}
}

// TestGenerateRejectsCgoBackend locks the guard left behind when the cgo
// emitters were retired: a library that is not on the purego backend must fail
// loudly rather than be mis-emitted as purego.
func TestGenerateRejectsCgoBackend(t *testing.T) {
	sandboxCwd(t)
	err := GenerateBindings(BindingsConfig{
		Registry: singleLibraryRegistry(&macosplatformmetadata.FrameworkMeta{
			Framework: "NotARegisteredLibrary",
			LinkLib:   "notaregisteredlibrary",
		}),
		LibrariesOutDir: t.TempDir(),
	})
	if err == nil {
		t.Fatal("a library off the purego backend must be rejected")
	}
	if !strings.Contains(err.Error(), "cgo backend retired") {
		t.Errorf("unexpected error: %v", err)
	}
}

// TestWriteFileErrorFromFn verifies writeFile propagates an error returned by fn.
func TestWriteFileErrorFromFn(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "test.go")
	sentinelErr := fmt.Errorf("sentinel error")
	err := writeFile(path, func(buf *bytes.Buffer) error {
		return sentinelErr
	})
	if err == nil {
		t.Error("writeFile should propagate fn error")
	}
	if _, statErr := os.Stat(path); statErr == nil {
		t.Error("writeFile should not create file when fn errors")
	}
}

// TestResolvePathsNonJSONFile verifies resolvePaths rejects non-.gometa.json file paths.
func TestResolvePathsNonJSONFile(t *testing.T) {
	dir := t.TempDir()
	badFile := filepath.Join(dir, "something.txt")
	if err := os.WriteFile(badFile, []byte("x"), 0o644); err != nil {
		t.Fatal(err)
	}
	_, err := resolvePaths([]string{badFile})
	if err == nil {
		t.Error("resolvePaths should reject non-.gometa.json file")
	}
}

