func TestWriteGoHeaderStructsFullBare(t *testing.T) {
	var buf bytes.Buffer
	writeGoHeaderStructsFull(&buf, "bsm", false, nil)
	out := buf.String()
	for _, want := range []string{
		"Code generated by go-bindings-codegen",
		"//go:build darwin",
		"package bsm",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("missing %q; got:\n%s", want, out)
		}
	}
	if strings.Contains(out, "import") {
		t.Errorf("header with no imports should emit no import block; got:\n%s", out)
	}
}

