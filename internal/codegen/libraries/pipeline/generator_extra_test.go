func TestHasBridgeableFunctionsNone(t *testing.T) {
	framework := &macosplatformmetadata.FrameworkMeta{Framework: "Foundation"}
	if hasBridgeableFunctions(framework) {
		t.Error("empty function list: hasBridgeableFunctions should be false")
	}
}

func TestHasBridgeableFunctionsNormal(t *testing.T) {
	framework := &macosplatformmetadata.FrameworkMeta{
		Framework: "Foundation",
		Functions: []macosplatformmetadata.Function{
			{Name: "NSLog", Params: []macosplatformmetadata.Param{{Name: "format", ObjCType: "NSString *"}}},
		},
	}
	if !hasBridgeableFunctions(framework) {
		t.Error("normal function: hasBridgeableFunctions should be true")
	}
}

