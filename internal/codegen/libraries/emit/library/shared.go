// completionHandlerIndex returns the index of the completion-handler block arg,
// or -1 if no arg matches the pattern (IsBlock == true, void return, single NSError* param).
// Blocks with multiple parameters like "(VZFoo *, NSError *)" are excluded — those
// are value-returning callbacks that require hand-crafted wrappers.
func completionHandlerIndex(args []macosplatformmetadata.Param) int {
	for i, arg := range args {
		if !arg.IsBlock {
			continue
		}
		t := arg.ObjCType
		if strings.Contains(t, "void (^") && strings.Contains(t, "NSError *") && !strings.Contains(t, ", NSError") {
			return i
		}
	}
	return -1
}

// removeCompletionSuffix removes "CompletionHandler" (and a preceding "With") from
// the end of a Go method name. Returns "" if the method doesn't match.
func removeCompletionSuffix(goMethodName string) string {
	s := strings.TrimSuffix(goMethodName, "CompletionHandler")
	if s == goMethodName {
		return ""
	}
	s = strings.TrimSuffix(s, "With")
	if s == "" {
		return goMethodName // safety fallback
	}
	return s
}

// extractNSArrayElementType extracts the element class name from an ObjC type
// of the form NSArray<ClassName *> * or NSMutableArray<ClassName *> *.
// Returns ("", false) for non-array or id-typed arrays.
func extractNSArrayElementType(objcType string) (string, bool) {
	s := strings.TrimSpace(objcType)
	// Block types (e.g. NSArray<Foo *> *(^_Nullable)(void)) contain "(^".
	// They are not plain array properties and must not be treated as such.
	if strings.Contains(s, "(^") {
		return "", false
	}
	for _, suffix := range []string{" _Nonnull", " _Nullable", " *"} {
		s = strings.TrimSuffix(s, suffix)
	}
	s = strings.TrimSpace(s)
	for _, prefix := range []string{"NSMutableArray<", "NSArray<"} {
		if !strings.HasPrefix(s, prefix) {
			continue
		}
		inner := s[len(prefix):]
		end := strings.LastIndexByte(inner, '>')
		if end < 0 {
			return "", false
		}
		elem := strings.TrimSpace(inner[:end])
		elem = strings.TrimSuffix(elem, " *")
		elem = strings.TrimSuffix(elem, " _Nonnull")
		elem = strings.TrimSuffix(elem, " _Nullable")
		elem = strings.TrimSpace(elem)
		if elem == "" || elem == "id" {
			return "", false
		}
		return elem, true
	}
	return "", false
}

// propertyGoName capitalises the first letter of an ObjC property name.
func propertyGoName(name string) string {
	if len(name) == 0 {
		return name
	}
	return strings.ToUpper(name[:1]) + name[1:]
}

// classHasValidateMethod reports whether the class has a validateWithError: method.
func classHasValidateMethod(cls macosplatformmetadata.Class) bool {
	for _, m := range cls.Methods {
		if m.Selector == "validateWithError:" && !m.Availability.IsUnavailable {
			return true
		}
	}
	return false
}

// classHasInstanceSetter reports whether cls has a non-class setter for propName.
// The expected selector is setFoo: (first letter uppercased).
func classHasInstanceSetter(cls macosplatformmetadata.Class, propName string) bool {
	if len(propName) == 0 {
		return false
	}
	setterSel := "set" + strings.ToUpper(propName[:1]) + propName[1:] + ":"
	for _, m := range cls.Methods {
		if !m.IsClassMethod && m.Selector == setterSel {
			return true
		}
	}
	return false
}

// classGetterIsClassMethod reports whether the getter for propName is a class method.
// getterSel is prop.Getter when set, otherwise prop.Name.
func classGetterIsClassMethod(cls macosplatformmetadata.Class, getterSel string) bool {
	for _, m := range cls.Methods {
		if m.IsClassMethod && m.Selector == getterSel {
			return true
		}
	}
	return false
}

// writeOpinionatedHeader emits the standard file header for a *_generated.go file
// in the opinionated layer.
func writeOpinionatedHeader(w io.Writer, pkgName, rawImportPath string, extraImports, usedImports map[string]string, needsObjc bool) {
	fmt.Fprintf(w, "// Code generated by go-bindings-codegen. DO NOT EDIT.\n\n")
	fmt.Fprintf(w, "//go:build darwin\n\n")
	fmt.Fprintf(w, "package %s\n\n", pkgName)

	all := map[string]string{
		"context": "context",
		"raw":     rawImportPath,
	}
	if needsObjc {
		all["cgo"] = "github.com/deploymenttheory/go-bindings-macosplatform/bindings/runtime/cgo"
	}
	for alias, path := range extraImports {
		all[alias] = path
	}
	for alias, path := range usedImports {
		if alias != "raw" {
			all[alias] = path
		}
	}

	type imp struct{ alias, path string }
	var imps []imp
	for alias, path := range all {
		imps = append(imps, imp{alias, path})
	}
	sort.Slice(imps, func(i, j int) bool { return imps[i].path < imps[j].path })

	fmt.Fprintf(w, "import (\n")
	for _, i := range imps {
		if strings.HasSuffix(i.path, "/"+i.alias) || i.alias == i.path {
			fmt.Fprintf(w, "\t%q\n", i.path)
		} else {
			fmt.Fprintf(w, "\t%s %q\n", i.alias, i.path)
		}
	}
	fmt.Fprintf(w, ")\n\n")
}

// extractObjCBaseTypeName strips pointer, nullability, and generic suffixes from an
// ObjC type string to return the bare type name (e.g. "CGRect", "CMTime").
// Used to look up types in the struct/enum registries.
func extractObjCBaseTypeName(objcType string) string {
	s := strings.TrimSpace(objcType)
	for _, sfx := range []string{" _Nullable", " _Nonnull", " *", " __kindof"} {
		s = strings.TrimSuffix(s, sfx)
	}
	s = strings.TrimPrefix(s, "const ")
	s = strings.TrimPrefix(s, "__kindof ")
	s = strings.TrimSpace(s)
	if idx := strings.IndexByte(s, '<'); idx >= 0 {
		s = s[:idx]
	}
	return strings.TrimSpace(s)
}

