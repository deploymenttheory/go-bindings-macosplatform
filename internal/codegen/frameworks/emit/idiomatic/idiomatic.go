// rawParamGoType resolves a raw method/function parameter type exactly as the
// raw emitter does: block params go through the shared adapter model in
// package emit so the idiomatic layer's closures keep matching the raw
// signatures; everything else uses the type mapper directly.
func rawParamGoType(
	objcType string,
	ctx typemap.Context,
	m *typemap.Mapper,
	impSet typemap.ImportSet,
) string {
	if _, isBlock := m.ResolveBlockSignature(objcType); isBlock {
		return emit.BlockGoFuncType(objcType, ctx, m, impSet, m.OwnerIndex)
	}
	resolved := m.GoType(objcType, ctx, impSet)
	if resolved == "" {
		resolved = "unsafe.Pointer"
	}
	return resolved
}

// ── ObjC pattern detection ─────────────────────────────────────────────────────

func isAsyncCompletion(m meta.Method) bool {
	if strings.TrimSpace(m.Return.ObjCType) != "void" || len(m.Params) == 0 {
		return false
	}
	last := m.Params[len(m.Params)-1]
	if !last.IsBlock {
		return false
	}
	t := strings.TrimSpace(last.ObjCType)
	return strings.HasPrefix(t, "void (^") && !strings.Contains(t, "BOOL *")
}

func parseBlockObjCParams(blockObjCType string) []string {
	idx := strings.Index(blockObjCType, ")(")
	if idx < 0 {
		return nil
	}
	after := blockObjCType[idx+2:]
	end := strings.LastIndex(after, ")")
	if end < 0 {
		return nil
	}
	inner := strings.TrimSpace(after[:end])
	if inner == "" || inner == "void" {
		return nil
	}
	var parts []string
	depth, start := 0, 0
	for i, r := range inner {
		switch r {
		case '<':
			depth++
		case '>':
			depth--
		case ',':
			if depth == 0 {
				parts = append(parts, strings.TrimSpace(inner[start:i]))
				start = i + 1
			}
		}
	}
	if tail := strings.TrimSpace(inner[start:]); tail != "" {
		parts = append(parts, tail)
	}
	return parts
}

func looksLikeNSArray(objcType string) bool {
	if strings.Contains(objcType, "(^") {
		return false
	}
	t := normaliseObjC(objcType)
	return strings.HasPrefix(t, "NSArray") || strings.HasPrefix(t, "NSMutableArray")
}

func extractNSArrayElem(objcType string) string {
	_, after, ok := strings.Cut(objcType, "<")
	if !ok {
		return ""
	}
	end := strings.LastIndex(after, ">")
	if end < 0 {
		return ""
	}
	return strings.TrimSpace(after[:end])
}

func isNSErrorType(objcType string) bool {
	t := normaliseObjC(objcType)
	return strings.HasPrefix(t, "NSError") && strings.Contains(t, "*")
}

func isNSURLType(objcType string) bool {
	if strings.Contains(objcType, "(^") || strings.Contains(objcType, "(*") {
		return false // block or C function pointer returning NSURL, not an NSURL value
	}
	t := normaliseObjC(objcType)
	return t == "NSURL *" || strings.HasPrefix(t, "NSURL *") || t == "NSURL"
}

func isNSStringType(objcType string) bool {
	if strings.Contains(objcType, "(^") || strings.Contains(objcType, "(*") {
		return false // block or C function pointer returning NSString, not an NSString value
	}
	t := normaliseObjC(objcType)
	rest, ok := strings.CutPrefix(t, "NSString")
	if !ok {
		return false
	}
	// Require a type boundary after "NSString" so longer identifiers such as
	// NSStringEncoding (a uint out-param) or NSStringDrawingContext are not
	// mistaken for an NSString and converted to a Go string.
	if rest != "" && isIdentByte(rest[0], false) {
		return false
	}
	return strings.Contains(t, "*")
}

func normaliseObjC(t string) string {
	t = strings.TrimSpace(t)
	for _, q := range []string{
		"_Nullable ", "_Nonnull ", "_Null_unspecified ", "__kindof ",
		"__unsafe_unretained ", "__autoreleasing ", "__strong ", "__weak ",
	} {
		t = strings.TrimPrefix(t, q)
	}
	for _, q := range []string{" _Nullable", " _Nonnull", " _Null_unspecified"} {
		t = strings.TrimSuffix(t, q)
	}
	return strings.TrimSpace(t)
}

// ── Naming ─────────────────────────────────────────────────────────────────────

func detectClassPrefix(fw *meta.FrameworkMeta) string {
	names := sortedKeys(fw.Classes)
	if len(names) == 0 {
		return ""
	}
	prefix := names[0]
	for _, name := range names[1:] {
		i := 0
		for i < len(prefix) && i < len(name) && prefix[i] == name[i] {
			i++
		}
		prefix = prefix[:i]
		if prefix == "" {
			return ""
		}
	}
	trimAt := len(prefix)
	for i, r := range prefix {
		if r >= 'a' && r <= 'z' {
			trimAt = i
			break
		}
	}
	// When the common prefix was cut at a lowercase letter, the preceding
	// uppercase letter starts the first word of the class name proper
	// (e.g. "CHHaptic" → trim at 'a' gives "CHH"; the final 'H' belongs to
	// "Haptic"), so drop it from the prefix.
	if trimAt < len(prefix) && trimAt > 0 {
		trimAt--
	}
	prefix = prefix[:trimAt]
	if len(prefix) < 2 {
		return ""
	}
	return prefix
}

func trialTypeName(className, prefix string) string {
	if prefix != "" && strings.HasPrefix(className, prefix) {
		stripped := className[len(prefix):]
		// A stripped name starting with a digit is an invalid Go identifier,
		// and one starting lowercase would be unexported. Keep the full class
		// name in those cases (e.g. AVB17221ACMPInterface stays as-is).
		if len(stripped) > 0 &&
			(stripped[0] >= '0' && stripped[0] <= '9' || stripped[0] >= 'a' && stripped[0] <= 'z') {
			return className
		}
		return stripped
	}
	return className
}

func asyncGoMethodName(selector string) string {
	base := naming.MethodName(selector)
	if strings.HasSuffix(base, "WithCompletionHandler") {
		return base[:len(base)-len("WithCompletionHandler")]
	}
	if strings.HasSuffix(base, "CompletionHandler") {
		return base[:len(base)-len("CompletionHandler")]
	}
	return base
}

func boolNSErrorGoMethodName(selector string) string {
	base := naming.MethodName(selector)
	if strings.HasSuffix(base, "WithError") {
		return base[:len(base)-len("WithError")]
	}
	return base
}

// qualifyRaw rewrites a mapper-resolved Go type for use inside a trial package:
//   - package references to the current framework become the raw alias
//   - bare same-framework identifiers (classes, enums, structs, protocols) get
//     the raw alias prefix, wherever they appear (generic brackets, func types)
//   - leaked generic param names (e.g. ObjectType) become objc.ID, matching the
//     instantiation trial uses for generic raw classes
func qualifyRaw(
	goType string,
	fw *meta.FrameworkMeta,
	rawPkgAlias string,
	genericParams []string,
) string {
	fwPkg := strings.ToLower(fw.Framework)

	var sb strings.Builder
	for i := 0; i < len(goType); {
		if !isIdentByte(goType[i], true) {
			sb.WriteByte(goType[i])
			i++
			continue
		}
		j := i + 1
		for j < len(goType) && isIdentByte(goType[j], false) {
			j++
		}
		word := goType[i:j]
		prevIsDot := i > 0 && goType[i-1] == '.'
		nextIsDot := j < len(goType) && goType[j] == '.'
		switch {
		case nextIsDot && !prevIsDot && word == fwPkg:
			// The mapper qualified a type with the framework's own package
			// name — rewrite to the raw alias. Token-scoped so substring
			// packages (corefoundation vs foundation) are untouched.
			sb.WriteString(rawPkgAlias)
		case prevIsDot || nextIsDot:
			sb.WriteString(word)
		case identInList(word, genericParams):
			sb.WriteString("objc.ID")
		case isFrameworkOwnType(word, fw):
			sb.WriteString(rawPkgAlias)
			sb.WriteByte('.')
			sb.WriteString(word)
		default:
			sb.WriteString(word)
		}
		i = j
	}
	return sb.String()
}

func isIdentByte(c byte, start bool) bool {
	if c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c == '_' {
		return true
	}
	return !start && c >= '0' && c <= '9'
}

func identInList(word string, list []string) bool {
	return slices.Contains(list, word)
}

// isFrameworkOwnType reports whether name is a type the current framework's raw
// package defines (class, enum, struct, or protocol interface). Names are
// matched in the form the raw emitter exports them (e.g. struct vmpktdesc is
// emitted as Vmpktdesc, enum vmnet_return_t as Vmnet_return_t).
func isFrameworkOwnType(name string, fw *meta.FrameworkMeta) bool {
	return frameworkOwnTypeNames(fw)[name]
}

// ownTypeNameCache memoises the per-framework exported type-name set.
// Generation is sequential (GenerateIdiomatic loops frameworks one at a time)
// so a plain map is safe.
var ownTypeNameCache = map[*meta.FrameworkMeta]map[string]bool{}

// frameworkOwnTypeNames builds the set of Go type names the raw package
// exports for fw, in both their metadata and exported spellings.
func frameworkOwnTypeNames(fw *meta.FrameworkMeta) map[string]bool {
	if set, ok := ownTypeNameCache[fw]; ok {
		return set
	}
	set := make(map[string]bool)
	for className := range fw.Classes {
		set[className] = true
	}
	for enumName := range fw.Enums {
		set[enumName] = true
		set[naming.GoTypeName(enumName)] = true
	}
	// Protocols that share a name with a class are emitted with a "Protocol"
	// suffix (e.g. protocol NSObject → type NSObjectProtocol interface).
	for protocolName := range fw.Protocols {
		goName := naming.GoTypeName(protocolName)
		set[goName] = true
		set[goName+"Protocol"] = true
	}
	for structName := range fw.Structs {
		set[structName] = true
		set[naming.ExportedTypeName(structName)] = true
	}
	// Struct typedefs (e.g. NSRange → struct _NSRange) are emitted as Go type
	// aliases in the raw package.
	for typedefName, target := range fw.Typedefs {
		if !strings.HasPrefix(target, "struct ") {
			continue
		}
		bare := strings.TrimSpace(strings.TrimSuffix(strings.TrimPrefix(target, "struct "), "*"))
		if _, ok := fw.Structs[bare]; ok {
			set[naming.ExportedTypeName(typedefName)] = true
		}
	}
	ownTypeNameCache[fw] = set
	return set
}

// ── Enum localization ────────────────────────────────────────────────────────

// ownEnumNameCache memoises the per-framework exported enum Go-type-name set.
var ownEnumNameCache = map[*meta.FrameworkMeta]map[string]bool{}

// frameworkOwnEnumNames is the set of Go type names of fw's own enums, derived
// exactly like emitEnums' index (naming.GoTypeName on each exported, available,
// non-anon enum key). These are the enums the idiomatic package re-emits as
// concrete local types, so signatures can use the local spelling instead of the
// raw one.
func frameworkOwnEnumNames(fw *meta.FrameworkMeta) map[string]bool {
	if set, ok := ownEnumNameCache[fw]; ok {
		return set
	}
	set := make(map[string]bool)
	for key, e := range fw.Enums {
		if e.Availability.IsUnavailable || e.IsAnon {
			continue
		}
		goType := naming.GoTypeName(key)
		if !isExportedGoIdent(goType) {
			continue
		}
		// emitEnums only re-emits enums that have at least one available member
		// (it skips member-less ones). Localizing a name the enums file won't
		// define would dangle, so mirror that filter here.
		if !enumHasAvailableMember(e) {
			continue
		}
		set[goType] = true
	}
	ownEnumNameCache[fw] = set
	return set
}

// enumHasAvailableMember reports whether e has at least one available member,
// matching the condition under which emitEnums emits a concrete local type.
func enumHasAvailableMember(e meta.Enum) bool {
	for _, m := range e.Members {
		if !m.Availability.IsUnavailable {
			return true
		}
	}
	return false
}

// referencedEnumsCache accumulates, per framework, the enum Go type names that
// localizeEnumType rewrote into a local signature. emitEnums emits concrete
// definitions for exactly this set (see enums.go). Generation is sequential per
// framework, so a plain map is safe.
var referencedEnumsCache = map[*meta.FrameworkMeta]map[string]bool{}

// referencedEnums returns (creating on first use) the per-framework set of
// locally-referenced enum names.
func referencedEnums(fw *meta.FrameworkMeta) map[string]bool {
	set, ok := referencedEnumsCache[fw]
	if !ok {
		set = make(map[string]bool)
		referencedEnumsCache[fw] = set
	}
	return set
}

// localizeEnumType rewrites a raw-qualified scalar enum type (rawPkgAlias.<E>,
// where <E> is one of fw's own enums) to the local idiomatic spelling <E>,
// recording it as referenced so emitEnums emits its concrete definition. It
// returns (localType, rawType, true); for anything else it returns the input
// unchanged with isEnum=false. Only the exact alias.<E> form matches, so
// pointer/slice/compound types keep their raw spelling.
func localizeEnumType(
	qualified string,
	fw *meta.FrameworkMeta,
	rawPkgAlias string,
) (sigType, rawType string, isEnum bool) {
	prefix := rawPkgAlias + "."
	if !strings.HasPrefix(qualified, prefix) {
		return qualified, "", false
	}
	name := qualified[len(prefix):]
	if !frameworkOwnEnumNames(fw)[name] {
		return qualified, "", false
	}
	referencedEnums(fw)[name] = true
	return deprefixEnumName(name, frameworkPrefix(fw)), qualified, true
}

// classPrefixCache memoises the per-framework class-name prefix.
var classPrefixCache = map[*meta.FrameworkMeta]string{}

// frameworkPrefix returns the framework's common type-name prefix (e.g. "VZ",
// "NS", "CF"), used to shorten enum type and member names.
func frameworkPrefix(fw *meta.FrameworkMeta) string {
	if p, ok := classPrefixCache[fw]; ok {
		return p
	}
	p := detectClassPrefix(fw)
	classPrefixCache[fw] = p
	return p
}

// deprefixEnumName removes the framework prefix from an enum type or member name
// (VZVirtualMachineState -> VirtualMachineState), so the idiomatic names read
// without the framework's letters repeated. It keeps the original name when
// stripping would leave an invalid or lower-case identifier.
func deprefixEnumName(name, prefix string) string {
	if prefix == "" || !strings.HasPrefix(name, prefix) {
		return name
	}
	stripped := name[len(prefix):]
	if stripped == "" || stripped[0] < 'A' || stripped[0] > 'Z' {
		return name
	}
	return stripped
}

// ── File utilities ─────────────────────────────────────────────────────────────

func sortedKeys(m map[string]meta.Class) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// importLines returns the import statements (each `"path"` or `alias "path"`)
// for the alias→path map, sorted by path then alias (the same path can be
// imported under two aliases, e.g. raw and foundation in the trial foundation
// package).
func importLines(imports map[string]string) []string {
	type imp struct{ alias, path string }
	list := make([]imp, 0, len(imports))
	for alias, path := range imports {
		list = append(list, imp{alias, path})
	}
	sort.Slice(list, func(i, j int) bool {
		if list[i].path != list[j].path {
			return list[i].path < list[j].path
		}
		return list[i].alias < list[j].alias
	})
	lines := make([]string, 0, len(list))
	for _, i := range list {
		segs := strings.Split(i.path, "/")
		defaultAlias := segs[len(segs)-1]
		if i.alias == defaultAlias || i.alias == i.path {
			lines = append(lines, fmt.Sprintf("%q", i.path))
		} else {
			lines = append(lines, fmt.Sprintf("%s %q", i.alias, i.path))
		}
	}
	return lines
}

// fileView is the template data for file.tmpl.
type fileView struct {
	Header      string
	BuildTag    string
	PkgName     string
	ImportLines []string
	Body        string
}

// assembleFile renders a complete generated file — the scaffold (header, build
// tag, package clause, import block) plus the already-rendered body — through
// file.tmpl.
func assembleFile(pkgName string, imports map[string]string, body []byte) []byte {
	var buf bytes.Buffer
	renderTemplate(&buf, "file", fileView{
		Header:      strings.TrimRight(generatedHeader, "\n"),
		BuildTag:    strings.TrimRight(buildTag, "\n"),
		PkgName:     pkgName,
		ImportLines: importLines(imports),
		Body:        string(body),
	})
	return buf.Bytes()
}

