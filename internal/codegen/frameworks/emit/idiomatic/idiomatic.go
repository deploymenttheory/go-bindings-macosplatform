// EmitFrameworkWrappers generates one *_generated.go file per ObjC class in fw.
func EmitFrameworkWrappers(
	outDir, pkgName, rawPkgAlias, rawPkgPath string,
	fw *meta.FrameworkMeta,
	m *typemap.Mapper,
) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("mkdir %s: %w", outDir, err)
	}

	prefix := detectClassPrefix(fw)
	// Build the set of trial type names so we can use them in params.
	trialNames := buildTrialNameMap(fw, prefix)
	// Build abstract base index for provider interface generation.
	abstractBases := buildAbstractBaseIndex(fw, prefix)

	// Scan hand-authored (non-generated) files in this package so the generator
	// never emits a method or constructor that a human has already written — the
	// hand-crafted refinement always wins.
	handMethods, handFuncs, err := scanHandAuthored(outDir)
	if err != nil {
		return fmt.Errorf("scan hand-authored files: %w", err)
	}

	// Clear previously generated files so a regeneration never leaves stale
	// output behind — e.g. when a function moves from one emitted file to
	// another (the generic C-function pass stops emitting a function this CF
	// pass now claims) or a class leaves the metadata.
	if err := removeGeneratedFiles(outDir); err != nil {
		return fmt.Errorf("clean generated files: %w", err)
	}

	// Emit the code that loads this package's macOS framework and looks up
	// Objective-C classes by name, which the constructors and class-level
	// functions call. Written after the clean step because it is itself a
	// _generated.go file.
	if err := emitRuntimeBootstrap(outDir, pkgName, fw); err != nil {
		return fmt.Errorf("emit runtime bootstrap: %w", err)
	}

	for _, className := range sortedKeys(fw.Classes) {
		cls := fw.Classes[className]
		if cls.Availability.IsUnavailable {
			continue
		}
		goTypeName := trialTypeName(className, prefix)

		var buf bytes.Buffer
		if err := emitClassFile(&buf, pkgName, rawPkgAlias, rawPkgPath,
			className, goTypeName, cls, fw, m, trialNames, prefix, abstractBases,
			handFuncs, handMethods[goTypeName]); err != nil {
			return fmt.Errorf("emit %s: %w", className, err)
		}
		if buf.Len() == 0 {
			continue
		}

		fname := className + "_generated.go"
		if err := emit.WriteGoFile(filepath.Join(outDir, fname), buf.Bytes()); err != nil {
			return err
		}
	}
	if err := emitProvidersFile(
		outDir,
		pkgName,
		rawPkgAlias,
		rawPkgPath,
		abstractBases,
		fw,
		m,
	); err != nil {
		return fmt.Errorf("emit providers: %w", err)
	}
	cfErrorWrapperNames, err := emitFunctionWrappers(
		outDir,
		pkgName,
		rawPkgAlias,
		rawPkgPath,
		fw,
		m,
		trialNames,
	)
	if err != nil {
		return fmt.Errorf("emit function wrappers: %w", err)
	}
	takenNames := buildTakenNames(fw, trialNames, abstractBases, cfErrorWrapperNames)
	// Reserve the de-prefixed names of every enum so a package-level function
	// (a class method or C function) never claims a name an enum type uses; the
	// enum keeps the short name and the function is qualified or omitted instead.
	for key, e := range fw.Enums {
		if e.Availability.IsUnavailable || e.IsAnon {
			continue
		}
		goType := naming.GoTypeName(key)
		if isExportedGoIdent(goType) {
			takenNames[deprefixEnumName(goType, frameworkPrefix(fw))] = true
		}
	}
	if err := emitClassMethodFunctions(
		outDir,
		pkgName,
		rawPkgAlias,
		rawPkgPath,
		fw,
		m,
		trialNames,
		handFuncs,
		takenNames,
		abstractBases,
	); err != nil {
		return fmt.Errorf("emit class method functions: %w", err)
	}
	if err := emitConstants(
		outDir, pkgName, rawPkgAlias, rawPkgPath, fw, m, handFuncs, takenNames,
	); err != nil {
		return fmt.Errorf("emit constants: %w", err)
	}
	if err := emitCFFunctionWrappers(
		outDir, pkgName, rawPkgAlias, rawPkgPath, fw, m, trialNames, takenNames,
	); err != nil {
		return fmt.Errorf("emit CF function wrappers: %w", err)
	}
	if err := emitGenericFunctionWrappers(
		outDir, pkgName, rawPkgAlias, rawPkgPath, fw, m, trialNames, takenNames,
	); err != nil {
		return fmt.Errorf("emit generic function wrappers: %w", err)
	}
	// Re-export raw enum types/constants referenced by the generated package so
	// callers never need the raw import to name an enum or use its constants.
	// Runs last: it scans the files written above.
	if err := emitEnums(
		outDir, pkgName, rawPkgAlias, rawPkgPath, fw, takenNames,
	); err != nil {
		return fmt.Errorf("emit enums: %w", err)
	}
	// Re-export the framework's own value-type structs (CGSize, CGRect, …) as
	// idiomatic Go type aliases so callers never need the raw import to name them.
	// Runs after emitEnums so takenNames is complete.
	if err := emitStructTypeAliases(
		outDir, pkgName, rawPkgAlias, rawPkgPath, fw, m, takenNames,
	); err != nil {
		return fmt.Errorf("emit struct type aliases: %w", err)
	}
	// Named error values for errors.Is, derived from the framework's error-code
	// enum and matching error domain.
	if err := emitErrorSentinels(outDir, pkgName, fw, takenNames); err != nil {
		return fmt.Errorf("emit error sentinels: %w", err)
	}
	if err := emitDocGo(outDir, pkgName, fw); err != nil {
		return err
	}
	// Enforce the core guarantee: the generated idiomatic package must not depend
	// on the raw bindings. A violation is a generation failure, not a build-time
	// surprise.
	return verifyHermetic(outDir)
}

// buildTakenNames collects the package-level identifiers already produced in
// the idiomatic package so generic C-function wrapper names cannot collide:
// trial type names and their New* constructors, provider interfaces, and the
// CFError wrapper functions.
func buildTakenNames(
	fw *meta.FrameworkMeta,
	trialNames trialNameMap,
	abstractBases abstractBaseIndex,
	cfErrorWrapperNames map[string]bool,
) map[string]bool {
	taken := make(map[string]bool, len(trialNames)*2+len(cfErrorWrapperNames))
	for _, trialName := range trialNames {
		taken[trialName] = true
		taken["New"+trialName] = true
	}
	for _, goTypeName := range abstractBases {
		taken[providerInterfaceName(goTypeName)] = true
	}
	for name := range cfErrorWrapperNames {
		taken[name] = true
	}
	return taken
}

// trialNameMap maps raw ObjC class names to their trial Go type names.
// Used to substitute trial types for raw types in method signatures.
type trialNameMap map[string]string // rawClassName → trialTypeName

func buildTrialNameMap(fw *meta.FrameworkMeta, prefix string) trialNameMap {
	m := make(trialNameMap, len(fw.Classes))
	for className := range fw.Classes {
		m[className] = trialTypeName(className, prefix)
	}
	return m
}

// abstractBaseIndex maps ObjC raw class names (that have at least one direct subclass
// in the same framework) to their trial Go type name.
type abstractBaseIndex map[string]string // rawClassName → trialGoTypeName

// buildAbstractBaseIndex returns a map from ObjC class name to trial Go type name for
// every class in fw that has at least one direct subclass also in fw.
func buildAbstractBaseIndex(fw *meta.FrameworkMeta, prefix string) abstractBaseIndex {
	bases := make(abstractBaseIndex)
	for _, cls := range fw.Classes {
		if cls.Availability.IsUnavailable || cls.Super == "" {
			continue
		}
		if superCls, ok := fw.Classes[cls.Super]; ok && !superCls.Availability.IsUnavailable {
			bases[cls.Super] = trialTypeName(cls.Super, prefix)
		}
	}
	return bases
}

// providerInterfaceName returns the provider interface name for a trial Go type, e.g.
// "BootLoader" → "BootLoaderProvider".
func providerInterfaceName(trialGoTypeName string) string {
	return trialGoTypeName + "Provider"
}

// providerMethodEntry describes a provider method to be emitted on a trial wrapper type.
type providerMethodEntry struct {
	methodName string
	rawType    string
	bodyExpr   string
}

