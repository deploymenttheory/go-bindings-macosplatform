// EmitFrameworkWrappers generates one *_generated.go file per ObjC class in fw.
func EmitFrameworkWrappers(
	outDir, pkgName, rawPkgAlias, rawPkgPath string,
	fw *meta.FrameworkMeta,
	m *typemap.Mapper,
) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("mkdir %s: %w", outDir, err)
	}

	prefix := detectClassPrefix(fw)
	// Build the set of trial type names so we can use them in params.
	trialNames := buildTrialNameMap(fw, prefix)
	// Build abstract base index for provider interface generation.
	abstractBases := buildAbstractBaseIndex(fw, prefix)

	// Scan hand-authored (non-generated) files in this package so the generator
	// never emits a method or constructor that a human has already written — the
	// hand-crafted refinement always wins.
	handMethods, handFuncs, err := scanHandAuthored(outDir)
	if err != nil {
		return fmt.Errorf("scan hand-authored files: %w", err)
	}

	// Clear previously generated files so a regeneration never leaves stale
	// output behind — e.g. when a function moves from one emitted file to
	// another (the generic C-function pass stops emitting a function this CF
	// pass now claims) or a class leaves the metadata.
	if err := removeGeneratedFiles(outDir); err != nil {
		return fmt.Errorf("clean generated files: %w", err)
	}

	for _, className := range sortedKeys(fw.Classes) {
		cls := fw.Classes[className]
		if cls.Availability.IsUnavailable {
			continue
		}
		goTypeName := trialTypeName(className, prefix)

		var buf bytes.Buffer
		if err := emitClassFile(&buf, pkgName, rawPkgAlias, rawPkgPath,
			className, goTypeName, cls, fw, m, trialNames, prefix, abstractBases,
			handFuncs, handMethods[goTypeName]); err != nil {
			return fmt.Errorf("emit %s: %w", className, err)
		}
		if buf.Len() == 0 {
			continue
		}

		fname := className + "_generated.go"
		if err := emit.WriteGoFile(filepath.Join(outDir, fname), buf.Bytes()); err != nil {
			return err
		}
	}
	if err := emitProvidersFile(
		outDir,
		pkgName,
		rawPkgAlias,
		rawPkgPath,
		abstractBases,
		fw,
		m,
	); err != nil {
		return fmt.Errorf("emit providers: %w", err)
	}
	cfErrorWrapperNames, err := emitFunctionWrappers(
		outDir,
		pkgName,
		rawPkgAlias,
		rawPkgPath,
		fw,
		m,
	)
	if err != nil {
		return fmt.Errorf("emit function wrappers: %w", err)
	}
	takenNames := buildTakenNames(fw, trialNames, abstractBases, cfErrorWrapperNames)
	if err := emitClassMethodFunctions(
		outDir,
		pkgName,
		rawPkgAlias,
		rawPkgPath,
		fw,
		m,
		trialNames,
		handFuncs,
		takenNames,
		abstractBases,
	); err != nil {
		return fmt.Errorf("emit class method functions: %w", err)
	}
	if err := emitConstants(
		outDir, pkgName, rawPkgAlias, rawPkgPath, fw, m, handFuncs, takenNames,
	); err != nil {
		return fmt.Errorf("emit constants: %w", err)
	}
	if err := emitCFFunctionWrappers(
		outDir, pkgName, rawPkgAlias, rawPkgPath, fw, m, takenNames,
	); err != nil {
		return fmt.Errorf("emit CF function wrappers: %w", err)
	}
	if err := emitGenericFunctionWrappers(
		outDir, pkgName, rawPkgAlias, rawPkgPath, fw, m, takenNames,
	); err != nil {
		return fmt.Errorf("emit generic function wrappers: %w", err)
	}
	// Re-export raw enum types/constants referenced by the generated package so
	// callers never need the raw import to name an enum or use its constants.
	// Runs last: it scans the files written above.
	if err := emitEnums(
		outDir, pkgName, rawPkgAlias, rawPkgPath, fw, takenNames,
	); err != nil {
		return fmt.Errorf("emit enums: %w", err)
	}
	return emitDocGo(outDir, pkgName, fw)
}

// buildTakenNames collects the package-level identifiers already produced in
// the idiomatic package so generic C-function wrapper names cannot collide:
// trial type names and their New* constructors, provider interfaces, and the
// CFError wrapper functions.
func buildTakenNames(
	fw *meta.FrameworkMeta,
	trialNames trialNameMap,
	abstractBases abstractBaseIndex,
	cfErrorWrapperNames map[string]bool,
) map[string]bool {
	taken := make(map[string]bool, len(trialNames)*2+len(cfErrorWrapperNames))
	for _, trialName := range trialNames {
		taken[trialName] = true
		taken["New"+trialName] = true
	}
	for _, goTypeName := range abstractBases {
		taken[providerInterfaceName(goTypeName)] = true
	}
	for name := range cfErrorWrapperNames {
		taken[name] = true
	}
	return taken
}

// trialNameMap maps raw ObjC class names to their trial Go type names.
// Used to substitute trial types for raw types in method signatures.
type trialNameMap map[string]string // rawClassName → trialTypeName

func buildTrialNameMap(fw *meta.FrameworkMeta, prefix string) trialNameMap {
	m := make(trialNameMap, len(fw.Classes))
	for className := range fw.Classes {
		m[className] = trialTypeName(className, prefix)
	}
	return m
}

// abstractBaseIndex maps ObjC raw class names (that have at least one direct subclass
// in the same framework) to their trial Go type name.
type abstractBaseIndex map[string]string // rawClassName → trialGoTypeName

// buildAbstractBaseIndex returns a map from ObjC class name to trial Go type name for
// every class in fw that has at least one direct subclass also in fw.
func buildAbstractBaseIndex(fw *meta.FrameworkMeta, prefix string) abstractBaseIndex {
	bases := make(abstractBaseIndex)
	for _, cls := range fw.Classes {
		if cls.Availability.IsUnavailable || cls.Super == "" {
			continue
		}
		if superCls, ok := fw.Classes[cls.Super]; ok && !superCls.Availability.IsUnavailable {
			bases[cls.Super] = trialTypeName(cls.Super, prefix)
		}
	}
	return bases
}

// ancestorEmbedChain returns the sequence of embedded field names required to access
// targetBase from startClass's inner raw type. E.g.:
//
//	("VZLinuxBootLoader", "VZBootLoader") → ["VZBootLoader"]
//	("VZLinuxRosettaUnixSocketCachingOptions", "VZLinuxRosettaCachingOptions")
//	    → ["VZLinuxRosettaAbstractSocketCachingOptions", "VZLinuxRosettaCachingOptions"]
//
// Returns nil if startClass == targetBase or the chain cannot be found.
func ancestorEmbedChain(startClass, targetBase string, fw *meta.FrameworkMeta) []string {
	if startClass == targetBase {
		return nil
	}
	var chain []string
	current := startClass
	for {
		cls, ok := fw.Classes[current]
		if !ok || cls.Super == "" {
			return nil
		}
		chain = append(chain, cls.Super)
		if cls.Super == targetBase {
			return chain
		}
		current = cls.Super
	}
}

// allAbstractBaseAncestors returns all ObjC class names that are abstract bases
// (present in abstractBases) and are proper ancestors of className.
func allAbstractBaseAncestors(
	className string,
	fw *meta.FrameworkMeta,
	abstractBases abstractBaseIndex,
) []string {
	var bases []string
	seen := map[string]bool{}
	current := className
	for {
		cls, ok := fw.Classes[current]
		if !ok || cls.Super == "" {
			break
		}
		if _, isBase := abstractBases[cls.Super]; isBase && !seen[cls.Super] {
			bases = append(bases, cls.Super)
			seen[cls.Super] = true
		}
		current = cls.Super
	}
	return bases
}

// providerInterfaceName returns the provider interface name for a trial Go type, e.g.
// "BootLoader" → "BootLoaderProvider".
func providerInterfaceName(trialGoTypeName string) string {
	return trialGoTypeName + "Provider"
}

// providerMethodName returns the package-private provider method name for a trial Go type, e.g.
// "BootLoader" → "asBootLoader".
func providerMethodName(trialGoTypeName string) string {
	return "as" + trialGoTypeName
}

// providerMethodEntry describes a provider method to be emitted on a trial wrapper type.
type providerMethodEntry struct {
	methodName string // e.g. "asBootLoader"
	rawType    string // e.g. "*raw.VZBootLoader" (full pointer type, owner-qualified)
	bodyExpr   string // e.g. "x.inner" or "&x.inner.VZBootLoader"
}

// providerRawType resolves the Go pointer type of a base class as embedded in the
// raw bindings, qualified by its owning package (which may differ from the current
// framework for umbrella sub-frameworks, e.g. MPSKernel lives in mpscore). Returns
// "" when the class does not resolve to a usable pointer type.
func providerRawType(
	baseClassName string,
	fw *meta.FrameworkMeta,
	m *typemap.Mapper,
	rawPkgAlias string,
	imports typemap.ImportSet,
) string {
	ctx := typemap.Context{Framework: fw.Framework}
	resolved := m.GoType(baseClassName+" *", ctx, imports)
	if !strings.HasPrefix(resolved, "*") {
		return ""
	}
	return qualifyRaw(resolved, fw, rawPkgAlias, nil)
}

// ── File emission ──────────────────────────────────────────────────────────────

// scanHandAuthored parses every non-generated .go file already present in the
// package directory and returns the methods (keyed by receiver type name) and
// the package-level function names a human has written by hand. The emitter
// uses these to avoid colliding with hand-crafted refinements.
func scanHandAuthored(outDir string) (map[string]map[string]bool, map[string]bool, error) {
	methods := map[string]map[string]bool{}
	funcs := map[string]bool{}
	entries, err := os.ReadDir(outDir)
	if err != nil {
		if os.IsNotExist(err) {
			return methods, funcs, nil
		}
		return nil, nil, err
	}
	fset := token.NewFileSet()
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") ||
			strings.HasSuffix(name, "_generated.go") {
			continue
		}
		f, perr := parser.ParseFile(
			fset,
			filepath.Join(outDir, name),
			nil,
			parser.SkipObjectResolution,
		)
		if perr != nil {
			// A stale or half-written file must not abort generation; skip it.
			continue
		}
		for _, decl := range f.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok {
				continue
			}
			if fn.Recv == nil {
				funcs[fn.Name.Name] = true
				continue
			}
			recv := receiverTypeName(fn.Recv)
			if recv == "" {
				continue
			}
			if methods[recv] == nil {
				methods[recv] = map[string]bool{}
			}
			methods[recv][fn.Name.Name] = true
		}
	}
	return methods, funcs, nil
}

// removeGeneratedFiles deletes the package's previously generated *_generated.go
// files so a regeneration never leaves stale output behind. Hand-authored files
// (which never carry the _generated.go suffix) and doc.go are kept; doc.go is
// rewritten in place by the emitter.
func removeGeneratedFiles(outDir string) error {
	entries, err := os.ReadDir(outDir)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), "_generated.go") {
			continue
		}
		if err := os.Remove(filepath.Join(outDir, e.Name())); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	return nil
}

func receiverTypeName(recv *ast.FieldList) string {
	if recv == nil || len(recv.List) == 0 {
		return ""
	}
	t := recv.List[0].Type
	if star, ok := t.(*ast.StarExpr); ok {
		t = star.X
	}
	if id, ok := t.(*ast.Ident); ok {
		return id.Name
	}
	return ""
}

// providerMethodItem / providerMethodView are the template data for
// provider_method.tmpl.
type providerMethodItem struct {
	MethodName string
	RawType    string
	BodyExpr   string
}

type providerMethodView struct {
	GoTypeName string
	Items      []providerMethodItem
}

// commentBlock renders documentation prose as a Go // comment block, one
// "// "-prefixed line per source line, with blank lines preserved as "//".
// Returns "" for empty docs. The result ends in a newline when non-empty, so a
// template can follow it with a "//" separator before the generated summary.
func commentBlock(doc string) string {
	doc = strings.TrimSpace(doc)
	if doc == "" {
		return ""
	}
	var sb strings.Builder
	for line := range strings.SplitSeq(doc, "\n") {
		line = strings.TrimRight(line, " ")
		if line == "" {
			sb.WriteString("//\n")
			continue
		}
		sb.WriteString("// ")
		sb.WriteString(line)
		sb.WriteString("\n")
	}
	return sb.String()
}

// classHeaderView is the template data for class_header.tmpl.
type classHeaderView struct {
	DocComment  string
	GoTypeName  string
	RawAlias    string
	ClassName   string
	RawType     string
	EmitID      bool
	EmitFromID  bool
	GenericArgs string
}

func emitClassFile(
	w io.Writer,
	pkgName, rawPkgAlias, rawPkgPath string,
	className, goTypeName string,
	cls meta.Class,
	fw *meta.FrameworkMeta,
	m *typemap.Mapper,
	trialNames trialNameMap,
	prefix string,
	abstractBases abstractBaseIndex,
	handFuncs map[string]bool,
	handMethods map[string]bool,
) error {
	ctx := typemap.Context{
		ClassName:     className,
		Framework:     fw.Framework,
		GenericParams: cls.GenericParams,
	}

	ctors := buildConstructors(
		cls,
		className,
		goTypeName,
		fw,
		ctx,
		m,
		rawPkgAlias,
		trialNames,
		abstractBases,
	)
	withMethods := buildWithSetters(
		cls,
		goTypeName,
		fw,
		ctx,
		m,
		rawPkgAlias,
		trialNames,
		prefix,
		abstractBases,
	)
	methods := buildMethods(cls, fw, ctx, m, rawPkgAlias, trialNames, abstractBases)
	providerMethods, providerImports := buildProviderMethods(
		cls, className, goTypeName, fw, m, rawPkgAlias, abstractBases)

	// Flatten inherited With* setters onto the subclass wrapper. A wrapper is
	// otherwise built from only its own class's properties, so anything configured
	// through an inherited setter (e.g. VZNetworkDeviceConfiguration.attachment on
	// a VZVirtio… subclass) is missing — the gap that forced consumers back to the
	// raw bindings. Walk the superclass chain within this framework and re-emit the
	// base classes' fluent setters on the subclass; they dispatch through x.inner,
	// which has the underlying setter via raw struct embedding. Subclass-own and
	// nearer-ancestor setters win on name collision. Only setters are flattened:
	// flattening arbitrary methods reintroduces base/override arity clashes through
	// embedding and out-of-package return types.
	withMethods = append(
		withMethods,
		buildInheritedSetters(
			cls,
			className,
			fw,
			m,
			rawPkgAlias,
			trialNames,
			prefix,
			abstractBases,
			withMethods,
		)...)

	// Drop anything a hand-authored file in this package already declares, so the
	// human's version wins (no duplicate-method compile error).
	if len(handFuncs) > 0 {
		ctors = slices.DeleteFunc(ctors, func(c ctorEntry) bool { return handFuncs[c.goName] })
	}
	if len(handMethods) > 0 {
		withMethods = slices.DeleteFunc(
			withMethods,
			func(e withEntry) bool { return handMethods[e.goName] },
		)
		methods = slices.DeleteFunc(
			methods,
			func(e methodEntry) bool { return handMethods[e.goName] },
		)
		providerMethods = slices.DeleteFunc(
			providerMethods,
			func(e providerMethodEntry) bool { return handMethods[e.methodName] },
		)
	}

	// Ensure a +new constructor exists for provider-only classes (no other content).
	if len(ctors) == 0 && len(providerMethods) > 0 {
		ctors = []ctorEntry{buildNewConstructor(className, goTypeName, rawPkgAlias)}
	}

	// Skip classes that have nothing useful to emit. When a hand-authored file
	// declares methods on this type, still emit the wrapper struct so those files
	// have a type to hang from.
	if len(ctors) == 0 && len(withMethods) == 0 && len(methods) == 0 &&
		len(providerMethods) == 0 && len(handMethods) == 0 {
		return nil
	}

	// ── Render body, then derive imports from what the code actually uses ──────

	var body bytes.Buffer

	rawType := rawPkgAlias + "." + className
	if len(cls.GenericParams) > 0 {
		rawType += genericInstantiation(len(cls.GenericParams))
	}

	// Wrapper struct + Unwrap, plus ID (unless a generated method claims the
	// name) and <Type>FromID (unless hand-authored). ID lets the wrapper reach C
	// APIs taking an object/CFTypeRef pointer without the raw import; FromID
	// mirrors the raw FromID (releasing finalizer, no retain).
	renderTemplate(&body, "class_header", classHeaderView{
		DocComment:  commentBlock(cls.Doc),
		GoTypeName:  goTypeName,
		RawAlias:    rawPkgAlias,
		ClassName:   className,
		RawType:     rawType,
		EmitID:      !methodNameClaimed("ID", withMethods, methods, handMethods),
		EmitFromID:  !handFuncs[goTypeName+"FromID"],
		GenericArgs: genericInstantiation(len(cls.GenericParams)),
	})

	for _, c := range ctors {
		writeConstructor(
			&body,
			goTypeName,
			rawPkgAlias,
			className,
			genericInstantiation(len(cls.GenericParams)),
			c,
		)
	}
	for _, we := range withMethods {
		writeWithMethod(&body, goTypeName, we)
	}
	for _, me := range methods {
		writeMethod(&body, goTypeName, me)
	}
	provItems := make([]providerMethodItem, len(providerMethods))
	for i, pm := range providerMethods {
		provItems[i] = providerMethodItem{
			MethodName: pm.methodName,
			RawType:    pm.rawType,
			BodyExpr:   pm.bodyExpr,
		}
	}
	renderTemplate(
		&body,
		"provider_method",
		providerMethodView{GoTypeName: goTypeName, Items: provItems},
	)

	emitDictionaryAugment(
		&body,
		className,
		goTypeName,
		rawPkgAlias,
		genericInstantiation(len(cls.GenericParams)),
	)

	// Mockable interface: lists Unwrap plus every generated exported method so
	// callers can accept the interface and supply test doubles. The compile-time
	// assertion guarantees the wrapper keeps satisfying it.
	writeMockInterface(&body, goTypeName, rawType, withMethods, methods)

	candidates := map[string]string{
		rawPkgAlias:  rawPkgPath,
		"context":    "context",
		"unsafe":     "unsafe",
		"purego":     pureobjcImportPath,
		"foundation": foundationImportPath,
		"objc":       objcImportPath,
	}
	for _, c := range ctors {
		maps.Copy(candidates, c.extraImports)
	}
	for _, we := range withMethods {
		maps.Copy(candidates, we.extraImports)
	}
	for _, me := range methods {
		maps.Copy(candidates, me.extraImports)
	}
	maps.Copy(candidates, providerImports)
	imports := usedImports(body.Bytes(), candidates)

	// ── Write output ───────────────────────────────────────────────────────────

	if _, err := w.Write(assembleFile(pkgName, imports, body.Bytes())); err != nil {
		return fmt.Errorf("write class body: %w", err)
	}

	return nil
}

// buildInheritedSetters walks cls's superclass chain within fw and returns the
// With* setters inherited from those base classes, so a subclass wrapper exposes
// them too (calling through x.inner, which has the underlying setter via raw
// struct embedding). Setters whose Go name already appears on the subclass
// (ownWith) or on a nearer ancestor are dropped, so subclass and nearer ancestor
// win. The walk stops at the first superclass not defined in fw (e.g. a
// cross-framework base such as NSObject).
func buildInheritedSetters(
	cls meta.Class,
	className string,
	fw *meta.FrameworkMeta,
	m *typemap.Mapper,
	rawPkgAlias string,
	trialNames trialNameMap,
	prefix string,
	abstractBases abstractBaseIndex,
	ownWith []withEntry,
) []withEntry {
	seen := make(map[string]bool, len(ownWith))
	for _, we := range ownWith {
		seen[we.goName] = true
	}

	var inherited []withEntry
	for super := cls.Super; super != ""; {
		anc, ok := fw.Classes[super]
		if !ok || anc.Availability.IsUnavailable {
			break
		}
		// Dispatch through the explicit embedded-base path (e.g. x.inner.NSView)
		// rather than relying on Go's promotion of x.inner's methods, which is
		// ambiguous when an intermediate class redeclares the setter's Go name.
		chain := ancestorEmbedChain(className, super, fw)
		innerExpr := "x.inner"
		if len(chain) > 0 {
			innerExpr += "." + strings.Join(chain, ".")
		}
		ancCtx := typemap.Context{
			ClassName:     super,
			Framework:     fw.Framework,
			GenericParams: anc.GenericParams,
		}
		for _, we := range buildWithSetters(anc, "", fw, ancCtx, m, rawPkgAlias, trialNames, prefix, abstractBases) {
			if seen[we.goName] {
				continue
			}
			seen[we.goName] = true
			we.innerExpr = innerExpr
			inherited = append(inherited, we)
		}
		super = anc.Super
	}
	return inherited
}

// buildConstructors assembles the constructor entries for a class: one per
// parameterised init, plus a plain +new constructor when appropriate.
func buildConstructors(
	cls meta.Class,
	className, goTypeName string,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
	trialNames trialNameMap,
	abstractBases abstractBaseIndex,
) []ctorEntry {
	var ctors []ctorEntry
	hasExplicitParamInit := false

	for _, method := range cls.Methods {
		if method.Availability.IsUnavailable || method.IsClassMethod || !method.IsInit {
			continue
		}
		if len(method.Params) == 0 {
			continue // plain init handled below as +new fallback
		}
		e := buildParamConstructor(
			method,
			goTypeName,
			cls,
			fw,
			ctx,
			m,
			rawPkgAlias,
			trialNames,
			abstractBases,
		)
		if e != nil {
			e.doc = method.Doc
			ctors = append(ctors, *e)
			hasExplicitParamInit = true
		}
	}

	// Every class gets a plain +new constructor unless it has a param-init that
	// already covers the no-arg case.
	if !hasExplicitParamInit {
		return append(
			[]ctorEntry{buildNewConstructor(className, goTypeName, rawPkgAlias)},
			ctors...)
	}
	// Still provide a plain constructor if there is a class-specific plain init too.
	for _, method := range cls.Methods {
		if method.IsInit && len(method.Params) == 0 && !method.Availability.IsUnavailable {
			return append(
				[]ctorEntry{buildNewConstructor(className, goTypeName, rawPkgAlias)},
				ctors...)
		}
	}
	return ctors
}

// buildWithSetters assembles the fluent With* setter entries for a class's
// settable properties, deduplicated by Go method name.
func buildWithSetters(
	cls meta.Class,
	goTypeName string,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
	trialNames trialNameMap,
	prefix string,
	abstractBases abstractBaseIndex,
) []withEntry {
	var withMethods []withEntry
	seenWithName := map[string]bool{}
	for _, prop := range cls.Properties {
		if prop.IsReadOnly || prop.Availability.IsUnavailable {
			continue
		}
		we := buildWithSetter(
			prop,
			goTypeName,
			cls,
			fw,
			ctx,
			m,
			rawPkgAlias,
			trialNames,
			prefix,
			abstractBases,
		)
		if we == nil || seenWithName[we.goName] {
			continue
		}
		we.doc = prop.Doc
		seenWithName[we.goName] = true
		withMethods = append(withMethods, *we)
	}
	return withMethods
}

// buildMethods assembles the instance method entries for a class: the special
// shapes (async, slice getters, BoolNSError) plus a plain pass-through wrapper
// for every other bridgeable instance method (including property accessors,
// which Clang synthesises into cls.Methods). Deduplicated by Go method name.
func buildMethods(
	cls meta.Class,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
	trialNames trialNameMap,
	abstractBases abstractBaseIndex,
) []methodEntry {
	rawNames := instanceRawMethodNames(cls)
	var methods []methodEntry
	seenMethod := map[string]bool{}
	for _, method := range cls.Methods {
		if method.IsClassMethod || method.IsInit || !instanceBridgeable(method) {
			continue
		}
		rawGoName := rawNames[method.Selector]
		if rawGoName == "" {
			rawGoName = naming.MethodName(method.Selector)
		}
		e := buildMethod(method, rawGoName, cls, fw, ctx, m, rawPkgAlias, trialNames, abstractBases)
		if e == nil || seenMethod[e.goName] {
			continue
		}
		e.doc = method.Doc
		seenMethod[e.goName] = true
		methods = append(methods, *e)
	}
	return methods
}

// instanceBridgeable mirrors the raw emitter's isMethodBridgeable for instance
// methods: skip unavailable methods and non-format variadics (which the raw
// layer does not emit, so a wrapper calling them would not compile).
func instanceBridgeable(method meta.Method) bool {
	if method.Availability.IsUnavailable {
		return false
	}
	if method.IsVariadic && !isSelectorFormatVariadic(method.Selector) {
		return false
	}
	return true
}

func isSelectorFormatVariadic(selector string) bool {
	for part := range strings.SplitSeq(selector, ":") {
		if strings.Contains(strings.ToLower(part), "format") {
			return true
		}
	}
	return false
}

// instanceRawMethodNames computes, per instance-method selector, the exact Go
// method name the raw emitter produced — including the numeric suffix the raw
// emitter appends to disambiguate colliding names (Foo, Foo2, …). The wrapper
// must call x.inner.<that name>. Class methods are name-prefixed by the raw
// emitter and never collide with instance names, so they are excluded here.
func instanceRawMethodNames(cls meta.Class) map[string]string {
	count := map[string]int{}
	for _, method := range cls.Methods {
		if method.IsClassMethod || !instanceBridgeable(method) {
			continue
		}
		count[naming.MethodName(method.Selector)]++
	}
	seen := map[string]int{}
	selSeen := map[string]bool{}
	out := make(map[string]string, len(count))
	for _, method := range cls.Methods {
		if method.IsClassMethod || !instanceBridgeable(method) {
			continue
		}
		if selSeen[method.Selector] {
			continue
		}
		selSeen[method.Selector] = true
		name := naming.MethodName(method.Selector)
		seen[name]++
		if count[name] > 1 && seen[name] > 1 {
			name = fmt.Sprintf("%s%d", name, seen[name])
		}
		out[method.Selector] = name
	}
	return out
}

// buildProviderMethods assembles the provider interface implementations for a
// class: one for itself when it is an abstract base, and one per abstract base
// ancestor (returning the embedded raw superclass field).
func buildProviderMethods(
	cls meta.Class,
	className, goTypeName string,
	fw *meta.FrameworkMeta,
	m *typemap.Mapper,
	rawPkgAlias string,
	abstractBases abstractBaseIndex,
) ([]providerMethodEntry, typemap.ImportSet) {
	var providerMethods []providerMethodEntry
	providerImports := make(typemap.ImportSet)

	// Self-provider: this class is an abstract base, so it implements its own
	// interface. Skip when the class is owned by a different package (umbrella
	// sub-frameworks): x.inner is the local duplicate type, not the owner's, and
	// the owner's own trial package provides the interface implementation.
	if _, isBase := abstractBases[className]; isBase {
		rawType := providerRawType(className, fw, m, rawPkgAlias, providerImports)
		localType := "*" + rawPkgAlias + "." + className + genericInstantiation(
			len(cls.GenericParams),
		)
		if rawType == localType {
			providerMethods = append(providerMethods, providerMethodEntry{
				methodName: providerMethodName(goTypeName),
				rawType:    rawType,
				bodyExpr:   "x.inner",
			})
		}
	}
	// Ancestor providers: implement provider interface for each abstract base ancestor.
	for _, baseClassName := range allAbstractBaseAncestors(className, fw, abstractBases) {
		baseGoTypeName := abstractBases[baseClassName]
		chain := ancestorEmbedChain(className, baseClassName, fw)
		if len(chain) == 0 {
			continue
		}
		rawType := providerRawType(baseClassName, fw, m, rawPkgAlias, providerImports)
		if rawType == "" {
			continue
		}
		providerMethods = append(providerMethods, providerMethodEntry{
			methodName: providerMethodName(baseGoTypeName),
			rawType:    rawType,
			bodyExpr:   "&x.inner." + strings.Join(chain, "."),
		})
	}
	return providerMethods, providerImports
}

// usedImports filters candidates down to the aliases the rendered body actually
// references as a package qualifier ("<alias>." preceded by a non-identifier byte).
// Comment lines are stripped first: doc prose frequently contains words like
// "context." or "...the foundation." that would otherwise be mistaken for a
// package qualifier and pull in an unused import.
func usedImports(body []byte, candidates map[string]string) map[string]string {
	code := stripCommentLines(body)
	imports := map[string]string{}
	for alias, path := range candidates {
		// A qualifier counts when it begins a token: at the start of input, after
		// a non-identifier/non-dot byte, or right after a variadic "..." ellipsis
		// (e.g. `...purego.IDer`). The lone-dot exclusion still rejects genuine
		// selectors like `x.purego.Bar`, where the alias is a field, not a package.
		pattern := regexp.MustCompile(`(^|\.\.\.|[^A-Za-z0-9_.])` + regexp.QuoteMeta(alias) + `\.`)
		if pattern.Match(code) {
			imports[alias] = path
		}
	}
	return imports
}

// stripCommentLines removes whole-line // comments so import detection scans
// only code. Doc comment blocks are always emitted as full-line comments, so
// dropping comment-only lines removes the prose without touching real code.
func stripCommentLines(body []byte) []byte {
	lines := bytes.Split(body, []byte("\n"))
	kept := lines[:0]
	for _, line := range lines {
		if bytes.HasPrefix(bytes.TrimSpace(line), []byte("//")) {
			continue
		}
		kept = append(kept, line)
	}
	return bytes.Join(kept, []byte("\n"))
}

// genericInstantiation returns the type-argument list used to instantiate a
// generic raw class in trial code, e.g. "[objc.ID]" or "[objc.ID, objc.ID]".
// objc.ID matches the raw emitter's own degradation default for generics.
func genericInstantiation(n int) string {
	if n == 0 {
		return ""
	}
	args := make([]string, n)
	for i := range args {
		args[i] = "objc.ID"
	}
	return "[" + strings.Join(args, ", ") + "]"
}

// methodNameClaimed reports whether a generated With-setter, method, or
// hand-authored method already uses name on this wrapper type (so the emitter
// does not add a colliding helper such as ID).
func methodNameClaimed(
	name string,
	withMethods []withEntry,
	methods []methodEntry,
	handMethods map[string]bool,
) bool {
	if handMethods[name] {
		return true
	}
	for _, we := range withMethods {
		if we.goName == name {
			return true
		}
	}
	for _, me := range methods {
		if me.goName == name {
			return true
		}
	}
	return false
}

// emitDictionaryAugment adds an object-pointer builder to the generated
// NSMutableDictionary wrapper. The generated setObject:forKey: types the key as
// the NSCopying interface, which a bare objc.ID (e.g. the CFStringRef constant
// security.KSecClass()) does not satisfy, so building such a dictionary
// otherwise still needs a manual message send. Set takes objc.ID key and value
// directly. (Reading a dictionary result back is covered by the generic
// <Type>FromID constructor plus ObjectForKey.)
func emitDictionaryAugment(w io.Writer, className, goTypeName, _, _ string) {
	if className != "NSMutableDictionary" {
		return
	}
	renderTemplate(w, "dict_augment", struct{ GoTypeName string }{GoTypeName: goTypeName})
}

// ── Constructor generation ─────────────────────────────────────────────────────

type ctorEntry struct {
	goName          string
	doc             string // Apple/header documentation for the underlying init
	rawInitGoName   string // "" = use +new
	rawInitSelector string // ObjC selector, e.g. "initWithURL:readOnly:error:"
	params          []ctorParam
	hasNSError      bool
	needsFoundation bool
	extraImports    map[string]string
	// preamble is rendered verbatim at the top of the constructor body, before
	// alloc/init — used to build a raw NSArray from a variadic ergonomic param.
	preamble string
}

type ctorParam struct {
	goName   string
	goType   string
	rawExpr  string // expression passed to the raw init method
	isObject bool   // true when the param is an ObjC object (send .Ptr())
}

// buildNewConstructor generates a plain +new constructor: New<Type>() *Type.
func buildNewConstructor(_, goTypeName, _ string) ctorEntry {
	return ctorEntry{
		goName:        "New" + goTypeName,
		rawInitGoName: "", // signals +new
	}
}

// buildParamConstructor generates a constructor from an init method with parameters.
func buildParamConstructor(
	method meta.Method,
	goTypeName string,
	_ meta.Class,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
	_ trialNameMap,
	abstractBases abstractBaseIndex,
) *ctorEntry {
	rawInit := naming.MethodName(method.Selector)
	needsFoundation := false
	extraImports := map[string]string{}
	preamble := ""

	var params []ctorParam
	for i, p := range method.Params {
		pName := naming.ParamName(p.Name)
		if pName == "" {
			pName = fmt.Sprintf("arg%d", i)
		}
		norm := normaliseObjC(p.ObjCType)

		switch {
		case isNSURLType(norm):
			needsFoundation = true
			params = append(params, ctorParam{
				goName: pName,
				goType: "string",
				rawExpr: fmt.Sprintf(
					"foundation.NSURLFileURLWithPath(foundation.NSStringStringWithUTF8String(%s))",
					pName,
				),
				isObject: true,
			})
		case isNSStringType(norm):
			needsFoundation = true
			params = append(params, ctorParam{
				goName:   pName,
				goType:   "string",
				rawExpr:  fmt.Sprintf("foundation.NSStringStringWithUTF8String(%s)", pName),
				isObject: true,
			})
		default:
			impSet := make(typemap.ImportSet)
			resolved := rawParamGoType(p.ObjCType, ctx, m, impSet)
			goType := qualifyRaw(resolved, fw, rawPkgAlias, ctx.GenericParams)
			maps.Copy(extraImports, impSet)
			// A trailing *NSArray[...] param becomes a variadic ergonomic so
			// callers never name the raw element type (only the last param may
			// be variadic per Go's rules).
			if i == len(method.Params)-1 {
				if av := arrayVariadicSpec(goType, rawPkgAlias, abstractBases); av != nil {
					argLocal := fmt.Sprintf("_arg%d", i)
					extraImports["objc"] = objcImportPath
					extraImports["unsafe"] = "unsafe"
					needsFoundation = true
					if strings.HasPrefix(av.elemSig, "purego.") {
						extraImports["purego"] = pureobjcImportPath
					}
					preamble += arrayVariadicPreamble(argLocal, pName, av)
					params = append(params, ctorParam{
						goName:   pName,
						goType:   "..." + av.elemSig,
						rawExpr:  argLocal,
						isObject: true,
					})
					continue
				}
			}
			sigType, rawExpr := localizeParam(pName, goType, fw, rawPkgAlias)
			params = append(params, ctorParam{
				goName:   pName,
				goType:   sigType,
				rawExpr:  rawExpr,
				isObject: isObjectPointerType(sigType, m),
			})
		}
	}

	return &ctorEntry{
		goName:          "New" + goTypeName + strings.TrimPrefix(rawInit, "Init"),
		rawInitGoName:   rawInit,
		rawInitSelector: method.Selector,
		params:          params,
		hasNSError:      method.IsNSError,
		needsFoundation: needsFoundation,
		extraImports:    extraImports,
		preamble:        preamble,
	}
}

func writeConstructor(
	w io.Writer,
	goTypeName, rawPkgAlias, className, genericArgs string,
	c ctorEntry,
) {
	fromIDFn := rawPkgAlias + "." + className + "FromID" + genericArgs

	paramParts := make([]string, 0, len(c.params))
	for _, p := range c.params {
		paramParts = append(paramParts, p.goName+" "+p.goType)
	}

	retStr := "*" + goTypeName
	if c.hasNSError {
		retStr = "(*" + goTypeName + ", error)"
	}

	view := constructorView{
		DocComment: commentBlock(c.doc),
		GoName:     c.goName,
		GoTypeName: goTypeName,
		ParamStr:   strings.Join(paramParts, ", "),
		RetStr:     retStr,
		ClassName:  className,
		FromIDFn:   fromIDFn,
		Preamble:   c.preamble,
		IsPlainNew: c.rawInitGoName == "",
		HasNSError: c.hasNSError,
	}
	if !view.IsPlainNew {
		// alloc + send the init selector directly via objc.Send[objc.ID],
		// bypassing the raw init method's return type (objc.ID or *T).
		sendArgs := make([]string, 0, len(c.params))
		for _, p := range c.params {
			sendArgs = append(sendArgs, ctorParamSendExpr(p))
		}
		allArgs := append(
			[]string{"_alloc", fmt.Sprintf("objc.RegisterName(%q)", c.rawInitSelector)},
			sendArgs...,
		)
		if c.hasNSError {
			allArgs = append(allArgs, "unsafe.Pointer(&_nsErr)")
		}
		view.SendAllArgs = strings.Join(allArgs, ", ")
	}

	renderTemplate(w, "constructor", view)
}

// constructorView is the template data for constructor.tmpl.
type constructorView struct {
	DocComment  string
	GoName      string
	GoTypeName  string
	ParamStr    string
	RetStr      string
	ClassName   string
	FromIDFn    string
	Preamble    string
	IsPlainNew  bool
	HasNSError  bool
	SendAllArgs string // alloc-init path: `_alloc, objc.RegisterName("sel"), …`
}

// ctorParamSendExpr returns the expression for passing a constructor parameter to
// objc.Send[objc.ID]. ObjC object types need .Ptr() to extract the raw objc.ID;
// primitives, plain C pointers, and struct pointers are passed directly.
func ctorParamSendExpr(p ctorParam) string {
	if p.isObject {
		return p.rawExpr + ".Ptr()"
	}
	return p.rawExpr
}

// isObjectPointerType reports whether a resolved Go type is a single pointer to
// an ObjC class (and therefore has a Ptr() method). Pointers to primitives or C
// structs (e.g. *uint8, *raw.IOUSBHostCIMessage) are not objects.
func isObjectPointerType(goType string, m *typemap.Mapper) bool {
	if !strings.HasPrefix(goType, "*") {
		return false
	}
	base := strings.TrimPrefix(goType, "*")
	if strings.HasPrefix(base, "*") {
		return false // double pointer (out-param)
	}
	if idx := strings.IndexByte(base, '['); idx >= 0 {
		base = base[:idx]
	}
	if idx := strings.LastIndexByte(base, '.'); idx >= 0 {
		base = base[idx+1:]
	}
	_, ok := m.OwnerIndex[base]
	return ok
}

// ── Fluent With* setter generation ────────────────────────────────────────────

type withEntry struct {
	goName             string // e.g. "WithVariableStore"
	doc                string // Apple/header documentation for the underlying property
	rawSetterGoName    string // e.g. "SetVariableStore"
	param              withParam
	isNSArray          bool   // true: variadic slice → NSArray
	sliceElemType      string // parameter elem type (interface for provider, raw ptr otherwise)
	arrayFromID        string // FromID call matching the raw setter param, e.g. "foundation.NSArrayFromID[objc.ID]"
	arrayClass         string // ObjC class to instantiate: "NSArray" or "NSMutableArray"
	providerMethodName string // non-empty when elem is an abstract base; e.g. "asNetworkDeviceConfiguration"
	innerExpr          string // receiver expression for the raw setter ("" = "x.inner"); a flattened
	//                            inherited setter uses the explicit embed path, e.g. "x.inner.NSView".
	extraImports map[string]string
}

type withParam struct {
	goName  string // variable name in the generated func
	goType  string // Go type (string for NSURL/NSString, *raw.T or ProviderIface for objects, uint64 etc.)
	rawExpr string // expression passed to the raw setter (may differ from param name)
}

func buildWithSetter(
	prop meta.Property,
	_ string,
	cls meta.Class,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
	trialNames trialNameMap,
	_ string,
	abstractBases abstractBaseIndex,
) *withEntry {
	// Derive the raw setter Go method name from the selector.
	setterSel := prop.Setter
	if setterSel == "" {
		if len(prop.Name) == 0 {
			return nil
		}
		setterSel = "set" + strings.ToUpper(prop.Name[:1]) + prop.Name[1:] + ":"
	}
	rawSetterGoName := naming.MethodName(setterSel)

	// Verify the setter method actually exists in the raw bindings.
	setterExists := false
	for _, method := range cls.Methods {
		if method.Selector == setterSel && !method.IsClassMethod {
			setterExists = true
			break
		}
	}
	if !setterExists {
		return nil
	}

	// Derive With* Go name from the property name.
	goWithName := "With" + strings.ToUpper(prop.Name[:1]) + prop.Name[1:]

	norm := normaliseObjC(prop.ObjCType)

	extraImports := map[string]string{}

	// NSArray property → variadic With*(items ...*T).
	if looksLikeNSArray(prop.ObjCType) {
		elemObjC := extractNSArrayElem(prop.ObjCType)
		if elemObjC == "" {
			return nil
		}
		impSet := make(typemap.ImportSet)
		goElem := m.GoType(elemObjC, ctx, impSet)
		if goElem == "" || goElem == "unsafe.Pointer" {
			return nil
		}
		goElem = qualifyRaw(goElem, fw, rawPkgAlias, ctx.GenericParams)
		if !isObjectPointerType(goElem, m) {
			return nil
		}
		// Resolve the raw setter's actual param type — nested generics may have
		// been degraded there (e.g. NSArray[objc.ID]) — so the built array
		// matches it exactly.
		rawProp := qualifyRaw(
			m.GoType(prop.ObjCType, ctx, impSet),
			fw,
			rawPkgAlias,
			ctx.GenericParams,
		)
		alias, container, rawElem, ok := parseArrayGoType(rawProp)
		if !ok {
			return nil
		}
		arrayFromID := fmt.Sprintf("%s.%sFromID[%s]", alias, container, rawElem)
		maps.Copy(extraImports, impSet)
		// Check whether the element type is an abstract base class — use provider interface.
		rawElemClass := strings.TrimPrefix(strings.TrimPrefix(goElem, "*"), rawPkgAlias+".")
		if goTypeName, isBase := abstractBases[rawElemClass]; isBase {
			ifaceName := providerInterfaceName(goTypeName)
			methName := providerMethodName(goTypeName)
			return &withEntry{
				goName:             goWithName,
				rawSetterGoName:    rawSetterGoName,
				isNSArray:          true,
				sliceElemType:      ifaceName,
				arrayFromID:        arrayFromID,
				arrayClass:         container,
				providerMethodName: methName,
				extraImports:       extraImports,
			}
		}
		return &withEntry{
			goName:          goWithName,
			rawSetterGoName: rawSetterGoName,
			isNSArray:       true,
			sliceElemType:   goElem,
			arrayFromID:     arrayFromID,
			arrayClass:      container,
			extraImports:    extraImports,
		}
	}

	// NSURL → string.
	if isNSURLType(norm) {
		pName := naming.ParamName(prop.Name)
		return &withEntry{
			goName:          goWithName,
			rawSetterGoName: rawSetterGoName,
			param: withParam{
				goName: pName,
				goType: "string",
				rawExpr: fmt.Sprintf(
					"foundation.NSURLFileURLWithPath(foundation.NSStringStringWithUTF8String(%s))",
					pName,
				),
			},
			extraImports: extraImports,
		}
	}

	// NSString → string.
	if isNSStringType(norm) {
		pName := naming.ParamName(prop.Name)
		return &withEntry{
			goName:          goWithName,
			rawSetterGoName: rawSetterGoName,
			param: withParam{
				goName:  pName,
				goType:  "string",
				rawExpr: fmt.Sprintf("foundation.NSStringStringWithUTF8String(%s)", pName),
			},
			extraImports: extraImports,
		}
	}

	// All other types: resolve via typemap. Block-typed properties go through
	// the shared adapter model so the setter param matches the raw signature.
	impSet := make(typemap.ImportSet)
	resolved := rawParamGoType(prop.ObjCType, ctx, m, impSet)
	if resolved == "" || resolved == "unsafe.Pointer" {
		return nil
	}
	goType := qualifyRaw(resolved, fw, rawPkgAlias, ctx.GenericParams)
	// Skip protocol/interface types — setters that take protocols need delegate machinery.
	if strings.HasPrefix(goType, "interface {") ||
		strings.HasPrefix(strings.TrimPrefix(goType, "*"), "interface {") {
		return nil
	}
	maps.Copy(extraImports, impSet)

	pName := naming.ParamName(prop.Name)

	// Check whether the scalar type is an abstract base class — use provider interface.
	rawClass := strings.TrimPrefix(strings.TrimPrefix(goType, "*"), rawPkgAlias+".")
	if goTypeName, isBase := abstractBases[rawClass]; isBase {
		ifaceName := providerInterfaceName(goTypeName)
		methName := providerMethodName(goTypeName)
		return &withEntry{
			goName:          goWithName,
			rawSetterGoName: rawSetterGoName,
			param: withParam{
				goName:  pName,
				goType:  ifaceName,
				rawExpr: pName + "." + methName + "()",
			},
			extraImports: extraImports,
		}
	}

	// Concrete object property → accept the idiomatic wrapper and unwrap it for
	// the raw setter, so callers pass the wrapper rather than the raw type.
	// (Abstract bases already used the provider interface above.)
	if base, ok := trialWrapClass(goType, rawPkgAlias); ok {
		if tt, has := trialNames[base]; has {
			return &withEntry{
				goName:          goWithName,
				rawSetterGoName: rawSetterGoName,
				param: withParam{
					goName:  pName,
					goType:  "*" + tt,
					rawExpr: pName + ".Unwrap()",
				},
				extraImports: extraImports,
			}
		}
	}

	sigType, rawExpr := localizeParam(pName, goType, fw, rawPkgAlias)
	return &withEntry{
		goName:          goWithName,
		rawSetterGoName: rawSetterGoName,
		param: withParam{
			goName:  pName,
			goType:  sigType,
			rawExpr: rawExpr,
		},
		extraImports: extraImports,
	}
}

func writeWithMethod(w io.Writer, typeName string, we withEntry) {
	inner := we.innerExpr
	if inner == "" {
		inner = "x.inner"
	}
	view := withSetterView{
		DocComment:      commentBlock(we.doc),
		TypeName:        typeName,
		GoName:          we.goName,
		Inner:           inner,
		RawSetterGoName: we.rawSetterGoName,
		IsNSArray:       we.isNSArray,
	}
	if we.isNSArray {
		loopExpr := "_v.Ptr()"
		if we.providerMethodName != "" {
			loopExpr = "_v." + we.providerMethodName + "().Ptr()"
		}
		view.SliceElemType = we.sliceElemType
		view.ArrayClass = we.arrayClass
		view.ArrayFromID = we.arrayFromID
		view.LoopExpr = loopExpr
	} else {
		view.ParamName = we.param.goName
		view.ParamType = we.param.goType
		view.ParamRawExpr = we.param.rawExpr
	}

	renderTemplate(w, "with_setter", view)
}

// withSetterView is the template data for with_setter.tmpl.
type withSetterView struct {
	DocComment      string
	TypeName        string
	GoName          string
	Inner           string
	RawSetterGoName string
	IsNSArray       bool

	// NSArray collection setter:
	SliceElemType string
	ArrayClass    string
	ArrayFromID   string
	LoopExpr      string

	// Scalar/object setter:
	ParamName    string
	ParamType    string
	ParamRawExpr string
}

// ── Method generation (async, slice getters, BoolNSError) ─────────────────────

type methodKind int

const (
	kindAsync       methodKind = iota
	kindBoolNSError            // (bool, error) → error
	kindSlice                  // NSArray return → []T
	kindPlain                  // pass-through wrapper for any other instance method
)

// plainRetMode controls how a plain pass-through method converts the result of
// the underlying raw call at the Go boundary.
type plainRetMode int

const (
	plainRetVoid      plainRetMode = iota // no return value
	plainRetRaw                           // return the raw value unchanged
	plainRetString                        // *foundation.NSString → Go string
	plainRetTrialWrap                     // *raw.<Class> → *<Trial> (this package)
	plainRetEnumCast                      // raw.<Enum> → local <Enum> (this package)
)

// plainParam is one parameter of a plain pass-through method: the Go signature
// type the caller supplies, and the expression handed to the raw method.
type plainParam struct {
	goName  string
	goType  string
	rawExpr string
}

type methodEntry struct {
	kind         methodKind
	goName       string
	rawGoName    string
	doc          string // Apple/header documentation for the underlying method
	extraImports map[string]string

	blockObjCParams     []string
	blockGoParamTypes   []string // Go types of the raw completion block's params
	asyncNonBlockParams []asyncParam
	// Typed-result completion: when the block carries exactly one non-error
	// param, the wrapper returns (R, error) instead of plain error.
	asyncResultIdx    int          // index into blockGoParamTypes of the result param; -1 = error-only
	asyncResultGoType string       // wrapped Go return type R ("" = error-only)
	asyncResultMode   plainRetMode // plainRetRaw | plainRetString | plainRetTrialWrap
	asyncResultTrial  string       // trial type name for plainRetTrialWrap

	sliceElemGoType string
	sliceConvFmt    string // fmt template (one %s) converting an objc.ID element to sliceElemGoType
	sliceHasError   bool   // raw getter returns (NSArray, error)

	plainParams    []plainParam
	plainRetType   string // Go value return type ("" = void); error is added separately
	plainRetMode   plainRetMode
	plainTrialType string // trial type name for plainRetTrialWrap
	plainHasError  bool   // raw method returns a trailing error (IsNSError)

	// preamble is rendered verbatim at the top of the method body, before the
	// raw call — used to build a raw NSArray from a variadic ergonomic param.
	preamble string
}

type asyncParam struct {
	goName          string
	goType          string
	rawExpr         string
	needsFoundation bool
}

// buildAsyncMethod assembles the entry for a completion-handler method. When the
// block only reports an optional NSError the wrapper returns error; when it also
// carries exactly one non-error result the wrapper returns (R, error), where R is
// the same-package trial type (when one exists), a Go string (for NSString), or
// the raw pointer. The generated wrapper blocks on a channel until completion or
// ctx cancellation.
func buildAsyncMethod(
	method meta.Method,
	rawGoName string,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
	trialNames trialNameMap,
) *methodEntry {
	lastParam := method.Params[len(method.Params)-1]
	blockParams := parseBlockObjCParams(lastParam.ObjCType)
	// Resolve the block's Go signature exactly as the raw emitter did, so the
	// generated closure matches the raw method's parameter type. Degraded
	// blocks come back as objc.Block and are rejected below.
	blockImpSet := make(typemap.ImportSet)
	blockGoType := emit.BlockGoFuncType(lastParam.ObjCType, ctx, m, blockImpSet, m.OwnerIndex)
	if !strings.HasPrefix(blockGoType, "func(") || !strings.HasSuffix(blockGoType, ")") {
		return nil
	}
	var blockGoParamTypes []string
	if csv := strings.TrimSuffix(
		strings.TrimPrefix(blockGoType, "func("),
		")",
	); strings.TrimSpace(
		csv,
	) != "" {
		for t := range strings.SplitSeq(csv, ",") {
			blockGoParamTypes = append(
				blockGoParamTypes,
				qualifyRaw(strings.TrimSpace(t), fw, rawPkgAlias, ctx.GenericParams),
			)
		}
	}
	if len(blockGoParamTypes) != len(blockParams) {
		return nil
	}

	// Classify block params into error params and at most one result param.
	resultIdx := -1
	resultMode := plainRetVoid
	resultGoType := ""
	resultTrial := ""
	resultImports := map[string]string{}
	for i, bp := range blockParams {
		if isNSErrorType(normaliseObjC(bp)) {
			// The NSError param must be expressible as an objc.ID for conversion.
			t := blockGoParamTypes[i]
			if t != "unsafe.Pointer" && t != "objc.ID" && !strings.HasPrefix(t, "*") {
				return nil
			}
			continue
		}
		// A non-error param: we support exactly one, and only as a typed pointer
		// (the raw block adapter already retained + wrapped it). Anything else
		// (a second result, or an objc.ID/unsafe.Pointer degraded param) falls
		// through to the plain wrapper.
		if resultIdx >= 0 {
			return nil
		}
		t := blockGoParamTypes[i]
		if !strings.HasPrefix(t, "*") {
			return nil
		}
		resultIdx = i
		switch t {
		case "*foundation.NSString":
			resultImports["purego"] = pureobjcImportPath
			resultMode, resultGoType = plainRetString, "string"
		default:
			if base, ok := trialWrapClass(t, rawPkgAlias); ok {
				if tt, has := trialNames[base]; has {
					resultMode, resultGoType, resultTrial = plainRetTrialWrap, "*"+tt, tt
				}
			}
			if resultMode != plainRetTrialWrap {
				resultMode, resultGoType = plainRetRaw, t
			}
		}
	}

	var nonBlockParams []asyncParam
	needsFoundation := false
	extraImports := map[string]string{}
	for _, p := range method.Params[:len(method.Params)-1] {
		pName := naming.ParamName(p.Name)
		if pName == "" {
			pName = fmt.Sprintf("arg%d", len(nonBlockParams))
		}
		norm := normaliseObjC(p.ObjCType)
		switch {
		case isNSURLType(norm):
			needsFoundation = true
			nonBlockParams = append(nonBlockParams, asyncParam{
				goName: pName,
				goType: "string",
				rawExpr: fmt.Sprintf(
					"foundation.NSURLFileURLWithPath(foundation.NSStringStringWithUTF8String(%s))",
					pName,
				),
				needsFoundation: true,
			})
		case isNSStringType(norm):
			needsFoundation = true
			nonBlockParams = append(nonBlockParams, asyncParam{
				goName:          pName,
				goType:          "string",
				rawExpr:         fmt.Sprintf("foundation.NSStringStringWithUTF8String(%s)", pName),
				needsFoundation: true,
			})
		default:
			impSet := make(typemap.ImportSet)
			resolved := rawParamGoType(p.ObjCType, ctx, m, impSet)
			maps.Copy(extraImports, impSet)
			goType := qualifyRaw(resolved, fw, rawPkgAlias, ctx.GenericParams)
			sigType, rawExpr := localizeParam(pName, goType, fw, rawPkgAlias)
			nonBlockParams = append(nonBlockParams, asyncParam{
				goName:  pName,
				goType:  sigType,
				rawExpr: rawExpr,
			})
		}
	}
	if needsFoundation {
		extraImports["foundation"] = foundationImportPath
	}
	maps.Copy(extraImports, blockImpSet)
	maps.Copy(extraImports, resultImports)
	return &methodEntry{
		kind:                kindAsync,
		goName:              asyncGoMethodName(method.Selector),
		rawGoName:           rawGoName,
		blockObjCParams:     blockParams,
		blockGoParamTypes:   blockGoParamTypes,
		asyncNonBlockParams: nonBlockParams,
		asyncResultIdx:      resultIdx,
		asyncResultGoType:   resultGoType,
		asyncResultMode:     resultMode,
		asyncResultTrial:    resultTrial,
		extraImports:        extraImports,
	}
}

func buildMethod(
	method meta.Method,
	rawGoName string,
	_ meta.Class,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
	trialNames trialNameMap,
	abstractBases abstractBaseIndex,
) *methodEntry {
	// Async completion → (ctx) error. Fall through to a plain wrapper when the
	// block shape can't be expressed idiomatically (non-NSError result params).
	if isAsyncCompletion(method) {
		if e := buildAsyncMethod(method, rawGoName, fw, ctx, m, rawPkgAlias, trialNames); e != nil {
			return e
		}
	}

	// BoolNSError — only when no explicit non-error params.
	if method.IsNSError && strings.TrimSpace(method.Return.ObjCType) == "BOOL" &&
		len(method.Params) == 0 {
		return &methodEntry{
			kind:      kindBoolNSError,
			goName:    boolNSErrorGoMethodName(method.Selector),
			rawGoName: rawGoName,
		}
	}

	// NSArray → slice (no params, getter only). Fall through to a plain wrapper
	// when the element type can't be resolved.
	if looksLikeNSArray(method.Return.ObjCType) && len(method.Params) == 0 {
		if e := buildSliceMethod(method, rawGoName, fw, ctx, m, rawPkgAlias, trialNames); e != nil {
			return e
		}
	}

	// Everything else: a plain pass-through wrapper so the method is callable on
	// the idiomatic type without dropping to .Unwrap().
	return buildPlainMethod(method, rawGoName, fw, ctx, m, rawPkgAlias, trialNames, abstractBases)
}

// buildSliceMethod builds an NSArray-getter → []T entry, or nil when the element
// type can't be resolved to a typed pointer.
func buildSliceMethod(
	method meta.Method,
	rawGoName string,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
	trialNames trialNameMap,
) *methodEntry {
	elemObjC := extractNSArrayElem(method.Return.ObjCType)
	if elemObjC == "" {
		return nil
	}

	extraImports := map[string]string{}
	var elemGoType, convFmt string
	if isNSStringType(normaliseObjC(elemObjC)) {
		// NSString elements → Go string, read directly from the element id.
		elemGoType, convFmt = "string", "purego.GoString(%s)"
	} else {
		impSet := make(typemap.ImportSet)
		goElem := m.GoType(elemObjC, ctx, impSet)
		if goElem == "" || goElem == "unsafe.Pointer" {
			return nil
		}
		goElem = qualifyRaw(goElem, fw, rawPkgAlias, ctx.GenericParams)
		if !isPointerType(goElem) || strings.Contains(goElem, "[") {
			// Only flat typed-pointer elements; nested generics fall through to
			// the plain wrapper (which hands back the raw NSArray unchanged).
			return nil
		}
		fromID := fromIDCallPrefix(goElem)
		if fromID == "" {
			return nil
		}
		// Elements are +0 inside the array; retain so the wrapper's finalizer
		// owns its own reference (FromID installs the finalizer but does not
		// retain). Mirrors the hand-written iteration consumers used to write.
		maps.Copy(extraImports, impSet)
		elemGoType, convFmt = goElem, fromID+"(purego.Retain(%s))"
		// When the element is a class in this framework that has an idiomatic
		// wrapper, hand back the wrapper ([]*Trial) rather than the raw pointer,
		// so callers iterating the slice stay on the idiomatic layer.
		if base, ok := trialWrapClass(goElem, rawPkgAlias); ok {
			if tt, has := trialNames[base]; has {
				elemGoType = "*" + tt
				convFmt = "&" + tt + "{inner: " + fromID + "(purego.Retain(%s))}"
			}
		}
	}
	// The conversion closure reads objc.ID elements via the purego collections
	// helper, which sidesteps the ABI-unsafe typed-NSArray element accessor.
	extraImports["purego"] = pureobjcImportPath
	extraImports["objc"] = objcImportPath

	goName := rawGoName
	if method.IsNSError {
		goName = strings.TrimSuffix(goName, "AndReturnError")
	}
	return &methodEntry{
		kind:            kindSlice,
		goName:          goName,
		rawGoName:       rawGoName,
		sliceElemGoType: elemGoType,
		sliceConvFmt:    convFmt,
		sliceHasError:   method.IsNSError,
		extraImports:    extraImports,
	}
}

// buildPlainMethod builds a pass-through wrapper for an instance method: it
// converts NSString/NSURL parameters to Go string at the boundary, forwards
// everything else as the raw type, and converts the result back to a Go string
// or a same-package trial type where possible (raw type otherwise). The wrapper
// inherits memory/dispatch correctness from the raw method it calls.
func buildPlainMethod(
	method meta.Method,
	rawGoName string,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
	trialNames trialNameMap,
	abstractBases abstractBaseIndex,
) *methodEntry {
	extraImports := map[string]string{}
	params := make([]plainParam, 0, len(method.Params))
	preamble := ""
	usedParamNames := map[string]int{}
	for i, p := range method.Params {
		pName := naming.ParamName(p.Name)
		if pName == "" {
			pName = fmt.Sprintf("arg%d", i)
		}
		if pName == "x" { // collides with the receiver variable
			pName = "x_"
		}
		// Disambiguate duplicate parameter names (e.g. two "recordId" labels),
		// matching the raw emitter: first keeps the name, later ones get a suffix.
		usedParamNames[pName]++
		if usedParamNames[pName] > 1 {
			pName = fmt.Sprintf("%s%d", pName, usedParamNames[pName])
		}
		norm := normaliseObjC(p.ObjCType)
		switch {
		case isNSStringType(norm):
			extraImports["foundation"] = foundationImportPath
			params = append(params, plainParam{
				goName:  pName,
				goType:  "string",
				rawExpr: fmt.Sprintf("foundation.NSStringStringWithUTF8String(%s)", pName),
			})
		case isNSURLType(norm):
			extraImports["foundation"] = foundationImportPath
			params = append(params, plainParam{
				goName: pName,
				goType: "string",
				rawExpr: fmt.Sprintf(
					"foundation.NSURLFileURLWithPath(foundation.NSStringStringWithUTF8String(%s))",
					pName,
				),
			})
		default:
			impSet := make(typemap.ImportSet)
			resolved := rawParamGoType(p.ObjCType, ctx, m, impSet)
			goType := qualifyRaw(resolved, fw, rawPkgAlias, ctx.GenericParams)
			if goType == "" {
				return nil
			}
			maps.Copy(extraImports, impSet)
			// A trailing *NSArray[...] param becomes a variadic ergonomic so
			// callers never name the raw element type (only the last param may
			// be variadic per Go's rules).
			if i == len(method.Params)-1 {
				if av := arrayVariadicSpec(goType, rawPkgAlias, abstractBases); av != nil {
					argLocal := fmt.Sprintf("_arg%d", i)
					extraImports["objc"] = objcImportPath
					extraImports["unsafe"] = "unsafe"
					extraImports["foundation"] = foundationImportPath
					if strings.HasPrefix(av.elemSig, "purego.") {
						extraImports["purego"] = pureobjcImportPath
					}
					preamble += arrayVariadicPreamble(argLocal, pName, av)
					params = append(
						params,
						plainParam{goName: pName, goType: "..." + av.elemSig, rawExpr: argLocal},
					)
					continue
				}
			}
			sigType, rawExpr := localizeParam(pName, goType, fw, rawPkgAlias)
			params = append(params, plainParam{goName: pName, goType: sigType, rawExpr: rawExpr})
		}
	}

	retMode := plainRetVoid
	retType := ""
	trialType := ""
	if retObjC := strings.TrimSpace(method.Return.ObjCType); retObjC != "" && retObjC != "void" {
		// Block-typed returns (literal blocks and block typedefs like
		// NSComparator) are degraded to objc.Block by the raw emitter — it can't
		// hand back a typed Go closure — so match that exactly. Arrays that merely
		// contain blocks are not blocks themselves and fall through below.
		if _, isBlock := m.ResolveBlockSignature(retObjC); isBlock {
			extraImports["objc"] = objcImportPath
			return &methodEntry{
				kind:          kindPlain,
				goName:        rawGoName,
				rawGoName:     rawGoName,
				extraImports:  extraImports,
				plainParams:   params,
				plainRetType:  "objc.Block",
				plainRetMode:  plainRetRaw,
				plainHasError: method.IsNSError,
				preamble:      preamble,
			}
		}
		impSet := make(typemap.ImportSet)
		rawRet := qualifyRaw(
			m.GoReturnType(method.Return.ObjCType, ctx, impSet),
			fw, rawPkgAlias, ctx.GenericParams,
		)
		if rawRet == "" {
			rawRet = "unsafe.Pointer"
		}
		switch rawRet {
		case "*foundation.NSString":
			extraImports["foundation"] = foundationImportPath
			extraImports["purego"] = pureobjcImportPath
			retMode, retType = plainRetString, "string"
		default:
			if base, ok := trialWrapClass(rawRet, rawPkgAlias); ok {
				if tt, has := trialNames[base]; has {
					retMode, retType, trialType = plainRetTrialWrap, "*"+tt, tt
				}
			}
			if retMode != plainRetTrialWrap {
				if sig, _, isEnum := localizeEnumType(rawRet, fw, rawPkgAlias); isEnum {
					retMode, retType = plainRetEnumCast, sig
				} else {
					maps.Copy(extraImports, impSet)
					retMode, retType = plainRetRaw, rawRet
				}
			}
		}
	}

	return &methodEntry{
		kind:           kindPlain,
		goName:         rawGoName,
		rawGoName:      rawGoName,
		extraImports:   extraImports,
		plainParams:    params,
		plainRetType:   retType,
		plainRetMode:   retMode,
		plainTrialType: trialType,
		plainHasError:  method.IsNSError,
		preamble:       preamble,
	}
}

// trialWrapClass reports the bare class name when rawRet is a non-generic single
// pointer into this package's raw alias (e.g. "*raw.NSWindow" → "NSWindow", ok).
// Generic instantiations, slices, double pointers and cross-package types return
// ("", false) so the wrapper keeps the raw return type.
func trialWrapClass(rawRet, rawPkgAlias string) (string, bool) {
	prefix := "*" + rawPkgAlias + "."
	if !strings.HasPrefix(rawRet, prefix) {
		return "", false
	}
	base := strings.TrimPrefix(rawRet, prefix)
	if strings.ContainsAny(base, "[].* ") {
		return "", false
	}
	return base, true
}

func writeMethod(w io.Writer, typeName string, me methodEntry) {
	writeMethodAs(w, fmt.Sprintf("(x *%s) ", typeName), "x.inner", me)
}

// writeClassFunc renders a class (static) method as a package-level function
// that forwards to the raw class function rawPkgAlias.<rawGoName>, applying the
// same idiomatic conversions as the instance-method writers.
func writeClassFunc(w io.Writer, rawPkgAlias string, me methodEntry) {
	writeMethodAs(w, "", rawPkgAlias, me)
}

// writeMethodAs renders a method entry either as an instance method (recv
// "(x *Type) ", target "x.inner") or a package-level function (recv "", target
// the raw package alias). Sharing one renderer keeps instance and class-method
// output byte-for-byte consistent.
func writeMethodAs(w io.Writer, recv, target string, me methodEntry) {
	switch me.kind {
	case kindAsync:
		writeAsyncMethod(w, recv, target, me)
	case kindBoolNSError:
		writeBoolNSErrorMethod(w, recv, target, me)
	case kindSlice:
		writeSliceMethod(w, recv, target, me)
	case kindPlain:
		writePlainMethod(w, recv, target, me)
	}
}

// writePlainMethod renders a pass-through wrapper that forwards to the raw
// method, converting NSString/NSURL params from Go strings and the result back
// to a Go string or same-package trial type where applicable.
func writePlainMethod(w io.Writer, recv, target string, me methodEntry) {
	paramParts := make([]string, 0, len(me.plainParams))
	rawArgs := make([]string, 0, len(me.plainParams))
	for _, p := range me.plainParams {
		paramParts = append(paramParts, p.goName+" "+p.goType)
		rawArgs = append(rawArgs, p.rawExpr)
	}
	renderTemplate(w, "plain_method", plainMethodView{
		DocComment: commentBlock(me.doc),
		Recv:       recv,
		GoName:     me.goName,
		RawGoName:  me.rawGoName,
		ParamStr:   strings.Join(paramParts, ", "),
		RetSig:     plainRetSig(me),
		Preamble:   me.preamble,
		Call:       fmt.Sprintf("%s.%s(%s)", target, me.rawGoName, strings.Join(rawArgs, ", ")),
		HasError:   me.plainHasError,
		RetMode:    plainRetModeName(me.plainRetMode),
		TrialType:  me.plainTrialType,
		EnumType:   me.plainRetType,
	})
}

// plainRetModeName maps a plainRetMode to the string the plain_method template
// switches on.
func plainRetModeName(m plainRetMode) string {
	switch m {
	case plainRetVoid:
		return "void"
	case plainRetRaw:
		return "raw"
	case plainRetString:
		return "string"
	case plainRetTrialWrap:
		return "trialwrap"
	case plainRetEnumCast:
		return "enumcast"
	}
	return ""
}

// plainMethodView is the template data for plain_method.tmpl.
type plainMethodView struct {
	DocComment string
	Recv       string
	GoName     string
	RawGoName  string
	ParamStr   string
	RetSig     string
	Preamble   string
	Call       string
	HasError   bool
	RetMode    string // "void" | "raw" | "string" | "trialwrap" | "enumcast"
	TrialType  string
	EnumType   string // local enum type for the enumcast return
}

// plainRetSig is the return clause for a plain method, shared by the writer and
// the mockable-interface builder so their signatures match exactly:
// " (value, error)" | " error" | " value" | "".
func plainRetSig(me methodEntry) string {
	switch {
	case me.plainHasError && me.plainRetType == "":
		return " error"
	case me.plainHasError:
		return " (" + me.plainRetType + ", error)"
	case me.plainRetType != "":
		return " " + me.plainRetType
	}
	return ""
}

// writeMockInterface emits an exported <Type>able interface listing Unwrap and
// every generated method, plus a compile-time assertion that the wrapper
// implements it. Consumers accept the interface for dependency injection/mocking.
func writeMockInterface(
	w io.Writer,
	typeName, rawType string,
	withMethods []withEntry,
	methods []methodEntry,
) {
	lines := make([]string, 0, len(withMethods)+len(methods))
	for _, we := range withMethods {
		lines = append(lines, interfaceWithLine(we, typeName))
	}
	for _, me := range methods {
		lines = append(lines, interfaceMethodLine(me))
	}
	renderTemplate(w, "mock_interface", mockInterfaceView{
		IfaceName: typeName + "able",
		TypeName:  typeName,
		RawType:   rawType,
		Lines:     lines,
	})
}

// mockInterfaceView is the template data for mock_interface.tmpl.
type mockInterfaceView struct {
	IfaceName string
	TypeName  string
	RawType   string
	Lines     []string
}

// interfaceWithLine renders the With-setter signature for the mockable interface.
func interfaceWithLine(we withEntry, typeName string) string {
	if we.isNSArray {
		return fmt.Sprintf("%s(items ...%s) *%s", we.goName, we.sliceElemType, typeName)
	}
	return fmt.Sprintf("%s(%s %s) *%s", we.goName, we.param.goName, we.param.goType, typeName)
}

// interfaceMethodLine renders the method signature for the mockable interface,
// mirroring the writeMethod variants exactly.
func interfaceMethodLine(me methodEntry) string {
	switch me.kind {
	case kindAsync:
		parts := []string{"ctx context.Context"}
		for _, p := range me.asyncNonBlockParams {
			parts = append(parts, p.goName+" "+p.goType)
		}
		if me.asyncResultGoType != "" {
			return fmt.Sprintf(
				"%s(%s) (%s, error)",
				me.goName,
				strings.Join(parts, ", "),
				me.asyncResultGoType,
			)
		}
		return fmt.Sprintf("%s(%s) error", me.goName, strings.Join(parts, ", "))
	case kindBoolNSError:
		return fmt.Sprintf("%s() error", me.goName)
	case kindSlice:
		if me.sliceHasError {
			return fmt.Sprintf("%s() ([]%s, error)", me.goName, me.sliceElemGoType)
		}
		return fmt.Sprintf("%s() []%s", me.goName, me.sliceElemGoType)
	case kindPlain:
		parts := make([]string, 0, len(me.plainParams))
		for _, p := range me.plainParams {
			parts = append(parts, p.goName+" "+p.goType)
		}
		return fmt.Sprintf("%s(%s)%s", me.goName, strings.Join(parts, ", "), plainRetSig(me))
	}
	return ""
}

func writeAsyncMethod(w io.Writer, recv, target string, me methodEntry) {
	paramParts := make([]string, 0, 1+len(me.asyncNonBlockParams))
	paramParts = append(paramParts, "ctx context.Context")
	for _, p := range me.asyncNonBlockParams {
		paramParts = append(paramParts, p.goName+" "+p.goType)
	}
	paramStr := strings.Join(paramParts, ", ")

	rawArgs := make([]string, 0, len(me.asyncNonBlockParams)+1)
	for _, p := range me.asyncNonBlockParams {
		rawArgs = append(rawArgs, p.rawExpr)
	}

	// The closure signature mirrors the raw method's block param exactly. The
	// first NSError param (if any) is converted to a Go error.
	closureParams := make([]string, 0, len(me.blockGoParamTypes))
	errIdx := -1
	errGoType := ""
	for i, goType := range me.blockGoParamTypes {
		closureParams = append(closureParams, fmt.Sprintf("_p%d %s", i, goType))
		if errIdx < 0 && isNSErrorType(normaliseObjC(me.blockObjCParams[i])) {
			errIdx = i
			errGoType = goType
		}
	}

	// errExpr renders the NSError-param → Go error conversion for the closure.
	errExpr := func(target string) string {
		switch {
		case errIdx < 0:
			return ""
		case errGoType == "unsafe.Pointer":
			return fmt.Sprintf("\t\tif uintptr(_p%d) != 0 {\n", errIdx) +
				fmt.Sprintf(
					"\t\t\t%s = purego.NSErrorToError(objc.ID(uintptr(_p%d)))\n",
					target,
					errIdx,
				) +
				"\t\t}\n"
		case errGoType == "objc.ID":
			return fmt.Sprintf("\t\tif _p%d != 0 {\n", errIdx) +
				fmt.Sprintf("\t\t\t%s = purego.NSErrorToError(_p%d)\n", target, errIdx) +
				"\t\t}\n"
		default: // *foundation.NSError or similar object pointer
			return fmt.Sprintf("\t\tif _p%d != nil {\n", errIdx) +
				fmt.Sprintf("\t\t\t%s = purego.NSErrorToError(_p%d.Ptr())\n", target, errIdx) +
				"\t\t}\n"
		}
	}

	// Error-only completion: returns plain error.
	if me.asyncResultGoType == "" {
		closureBody := "\t\t_ch <- nil\n"
		if errIdx >= 0 {
			closureBody = "\t\tvar _err error\n" + errExpr("_err") + "\t\t_ch <- _err\n"
		}
		rawArgs = append(
			rawArgs,
			"func("+strings.Join(closureParams, ", ")+") {\n"+closureBody+"\t}",
		)
		renderTemplate(w, "async_method", asyncMethodView{
			DocComment: commentBlock(me.doc),
			Recv:       recv,
			GoName:     me.goName,
			ParamStr:   paramStr,
			HasResult:  false,
			RawCall:    fmt.Sprintf("%s.%s(%s)", target, me.rawGoName, strings.Join(rawArgs, ", ")),
		})
		return
	}

	// Typed-result completion: returns (R, error). The result block param was
	// already retained and wrapped by the raw block adapter.
	ri := me.asyncResultIdx
	var resultConv string
	switch me.asyncResultMode {
	case plainRetString:
		resultConv = fmt.Sprintf(
			"\t\tif _p%d != nil {\n\t\t\t_o.val = purego.GoString(_p%d.Ptr())\n\t\t}\n",
			ri,
			ri,
		)
	case plainRetTrialWrap:
		resultConv = fmt.Sprintf(
			"\t\tif _p%d != nil {\n\t\t\t_o.val = &%s{inner: _p%d}\n\t\t}\n",
			ri,
			me.asyncResultTrial,
			ri,
		)
	default: // plainRetRaw
		resultConv = fmt.Sprintf("\t\t_o.val = _p%d\n", ri)
	}
	closureBody := "\t\tvar _o _result\n" + errExpr("_o.err") + resultConv + "\t\t_ch <- _o\n"

	rawArgs = append(rawArgs, "func("+strings.Join(closureParams, ", ")+") {\n"+closureBody+"\t}")
	renderTemplate(w, "async_method", asyncMethodView{
		DocComment:   commentBlock(me.doc),
		Recv:         recv,
		GoName:       me.goName,
		ParamStr:     paramStr,
		HasResult:    true,
		ResultGoType: me.asyncResultGoType,
		RawCall:      fmt.Sprintf("%s.%s(%s)", target, me.rawGoName, strings.Join(rawArgs, ", ")),
	})
}

