// Package emit contains the per-construct emitters for the purego code generator.
// All emitted files are pure Go — no CGo, no C headers, no .m files.
package emit

import (
	"fmt"
	"io"
	"sort"
	"strings"

	"github.com/deploymenttheory/go-bindings-macosplatform/internal/codegen/frameworks/meta"
	"github.com/deploymenttheory/go-bindings-macosplatform/internal/codegen/frameworks/naming"
	"github.com/deploymenttheory/go-bindings-macosplatform/internal/codegen/frameworks/typemap"
)

const generatedHeader = "// Code generated by go-bindings-purecg. DO NOT EDIT.\n//go:build darwin\n\n"

// writeFileHeader writes the build tag, package declaration, and imports.
func writeFileHeader(w io.Writer, packageName string, imports typemap.ImportSet, extraImports ...string) {
	fmt.Fprint(w, generatedHeader)
	fmt.Fprintf(w, "package %s\n\n", packageName)

	// Collect all imports.
	all := make(map[string]string)
	for alias, path := range imports {
		all[alias] = path
	}
	for _, imp := range extraImports {
		// Extra imports are specified as "path" or "alias path".
		parts := strings.Fields(imp)
		switch len(parts) {
		case 1:
			// Derive alias from last path component.
			segs := strings.Split(parts[0], "/")
			all[segs[len(segs)-1]] = parts[0]
		case 2:
			all[parts[0]] = parts[1]
		}
	}

	if len(all) == 0 {
		return
	}

	// Group into stdlib, external, internal.
	var stdlib, external, internal_ []string
	for _, path := range all {
		switch {
		case !strings.Contains(path, "."):
			stdlib = append(stdlib, path)
		case strings.HasPrefix(path, "github.com/deploymenttheory"):
			internal_ = append(internal_, path)
		default:
			external = append(external, path)
		}
	}
	sort.Strings(stdlib)
	sort.Strings(external)
	sort.Strings(internal_)

	// Build alias→path map for writing (preserving aliases for cross-fw imports).
	pathToAlias := make(map[string]string)
	for alias, path := range all {
		segs := strings.Split(path, "/")
		defaultAlias := segs[len(segs)-1]
		if alias != defaultAlias {
			pathToAlias[path] = alias
		}
	}

	fmt.Fprint(w, "import (\n")
	writeImportGroup(w, stdlib, pathToAlias)
	if len(stdlib) > 0 && (len(external)+len(internal_)) > 0 {
		fmt.Fprint(w, "\n")
	}
	writeImportGroup(w, external, pathToAlias)
	if len(external) > 0 && len(internal_) > 0 {
		fmt.Fprint(w, "\n")
	}
	writeImportGroup(w, internal_, pathToAlias)
	fmt.Fprint(w, ")\n\n")
}

func writeImportGroup(w io.Writer, paths []string, pathToAlias map[string]string) {
	for _, path := range paths {
		if alias, ok := pathToAlias[path]; ok {
			fmt.Fprintf(w, "\t%s %q\n", alias, path)
		} else {
			fmt.Fprintf(w, "\t%q\n", path)
		}
	}
}

// sortedEnumNames returns enum names in a stable order: named enums first,
// then anonymous, all sorted alphabetically within each group.
func sortedEnumNames(enums map[string]meta.Enum) []string {
	var named, anon []string
	for name, e := range enums {
		if e.IsAnon {
			anon = append(anon, name)
		} else {
			named = append(named, name)
		}
	}
	sort.Strings(named)
	sort.Strings(anon)
	return append(named, anon...)
}

// sortedNames returns sorted keys of any map[string]T.
func sortedStringKeys(m map[string]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// newMapper builds a typemap.Mapper from a registry snapshot.
func newMapper(
	ownerIndex map[string]string,
	genericClasses map[string]bool,
	genericParamIndex map[string][]string,
	enumIndex map[string]string,
	enumGoTypeIndex map[string]string,
	typedefIndex map[string]string,
	structIndex map[string]string,
	protocolIndex map[string]string,
	cfTypeIndex map[string]string,
	blockedImports map[string]map[string]bool,
	modulePrefix string,
) *typemap.Mapper {
	return &typemap.Mapper{
		OwnerIndex:        ownerIndex,
		GenericClasses:    genericClasses,
		GenericParamIndex: genericParamIndex,
		EnumIndex:         enumIndex,
		EnumGoTypeIndex:   enumGoTypeIndex,
		TypedefIndex:      typedefIndex,
		StructIndex:       structIndex,
		ProtocolIndex:     protocolIndex,
		CFTypeIndex:       cfTypeIndex,
		BlockedImports:    blockedImports,
		ModulePrefix:      modulePrefix,
	}
}

// isObjCObject reports whether a Go type string represents an ObjC object
// (i.e. pointer to a generated wrapper type, not a primitive or struct).
func isObjCObjectType(goType string) bool {
	if !strings.HasPrefix(goType, "*") {
		return false
	}
	// Strip pointer and check if it looks like an ObjC class (starts uppercase, no dot for same-package)
	inner := goType[1:]
	if strings.HasPrefix(inner, "unsafe.") {
		return false
	}
	if inner == "bool" || inner == "byte" || inner == "int" || inner == "uint" ||
		inner == "int8" || inner == "int16" || inner == "int32" || inner == "int64" ||
		inner == "uint8" || inner == "uint16" || inner == "uint32" || inner == "uint64" ||
		inner == "float32" || inner == "float64" || inner == "string" {
		return false
	}
	// Check if it starts with uppercase (ObjC class name or cross-package reference)
	last := inner
	if dotIdx := strings.LastIndex(inner, "."); dotIdx >= 0 {
		last = inner[dotIdx+1:]
	}
	if len(last) == 0 {
		return false
	}
	return last[0] >= 'A' && last[0] <= 'Z'
}

// frameworkDylibPath returns the macOS dylib path for an ObjC framework.
// C libraries (link_lib set) use a different path.
func frameworkDylibPath(m *meta.FrameworkMeta) string {
	if m.LinkLib != "" {
		// C library — use /usr/lib path
		return "/usr/lib/lib" + m.LinkLib + ".dylib"
	}
	parent := m.Framework
	if m.ParentFramework != "" {
		parent = m.ParentFramework
	}
	return fmt.Sprintf(
		"/System/Library/Frameworks/%s.framework/%s",
		parent, parent,
	)
}

// goTypeForStructField resolves an ObjC struct field type to a Go type.
// It uses simple heuristics before falling back to the full mapper.
func goTypeForStructField(objcType string, mapper *typemap.Mapper, framework string) string {
	ctx := typemap.Context{Framework: framework}
	imports := make(typemap.ImportSet)
	return mapper.GoType(objcType, ctx, imports)
}

// emitDeprecatedComment writes a deprecation comment if the availability
// indicates the symbol is deprecated.
func emitDeprecatedComment(w io.Writer, avail meta.Availability) {
	if avail.MacOSDeprecated != "" {
		if avail.DeprecationMsg != "" {
			fmt.Fprintf(w, "// Deprecated: %s\n", avail.DeprecationMsg)
		} else {
			fmt.Fprintf(w, "// Deprecated: since macOS %s.\n", avail.MacOSDeprecated)
		}
	}
}

// varSelectorName returns the unexported package-level var name for a selector,
// scoped to a class to avoid collisions.
func varSelectorName(className, selector string) string {
	return "_" + strings.ToLower(className[:1]) + className[1:] + "Sel" + naming.MethodName(selector)
}

// varClassName returns the unexported package-level var name for a class ref.
func varClassName(className string) string {
	return "_cls" + className
}
