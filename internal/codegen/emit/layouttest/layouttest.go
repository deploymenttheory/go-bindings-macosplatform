// Package layouttest generates the per-package ABI layout regression test both
// frameworks emitters (raw and idiomatic) write: a reflect-based check that every
// emitted value/byte-array struct reproduces the authoritative C ABI size clang
// reported. It is the layout gate the name-keyed parity check cannot provide.
package layouttest

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Check is one struct's Go name and the authoritative C size / alignment. Align 0
// skips the alignment assertion (used for clean value structs, where Go may
// legitimately over-align an int64-bearing struct without an ABI consequence).
type Check struct {
	GoName string
	Size   int
	Align  int
}

// Write emits <pkgName>_layout_generated_test.go into outDir asserting each check.
// It writes nothing when there are no checks.
func Write(outDir, pkgName string, checks []Check) error {
	if len(checks) == 0 {
		return nil
	}
	sort.Slice(checks, func(i, j int) bool { return checks[i].GoName < checks[j].GoName })

	var b strings.Builder
	b.WriteString("// Code generated by go-bindings-codegen. DO NOT EDIT.\n\n//go:build darwin\n\n")
	b.WriteString("package " + pkgName + "\n\n")
	b.WriteString("import (\n\t\"reflect\"\n\t\"testing\"\n)\n\n")
	b.WriteString("// TestGeneratedLayout asserts each emitted value struct reproduces the C ABI\n")
	b.WriteString("// size and alignment clang reported (Go alignment caps at 8).\n")
	b.WriteString("func TestGeneratedLayout(t *testing.T) {\n")
	b.WriteString("\tcases := []struct {\n\t\tname        string\n\t\tgot, want   uintptr\n\t\tgotA, wantA uintptr\n\t}{\n")
	for _, c := range checks {
		wantA := c.Align
		if wantA > 8 {
			wantA = 8 // Go has no scalar wider than 8-byte alignment
		}
		fmt.Fprintf(&b, "\t\t{%q, reflect.TypeOf(%s{}).Size(), %d, uintptr(reflect.TypeOf(%s{}).Align()), %d},\n",
			c.GoName, c.GoName, c.Size, c.GoName, wantA)
	}
	b.WriteString("\t}\n")
	b.WriteString("\tfor _, c := range cases {\n")
	b.WriteString("\t\tif c.got != c.want {\n\t\t\tt.Errorf(\"sizeof %s = %d, want %d (C ABI)\", c.name, c.got, c.want)\n\t\t}\n")
	b.WriteString("\t\tif c.wantA != 0 && c.gotA != c.wantA {\n\t\t\tt.Errorf(\"alignof %s = %d, want %d (C ABI)\", c.name, c.gotA, c.wantA)\n\t\t}\n")
	b.WriteString("\t}\n}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		return fmt.Errorf("format layout test for %s: %w", pkgName, err)
	}
	return os.WriteFile(filepath.Join(outDir, pkgName+"_layout_generated_test.go"), src, 0o644)
}
