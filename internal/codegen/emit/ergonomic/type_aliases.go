package ergonomic

import (
	"bytes"
	"fmt"
	"io"
	"sort"
	"strings"

	"github.com/deploymenttheory/go-bindings-macosplatform/internal/codegen/typemap"
	"github.com/deploymenttheory/go-bindings-macosplatform/internal/meta"
)

// ErgonomicTypeAliases emits Go type aliases that strip the "NS" prefix from
// ObjC class names so consumers can write foundation.String instead of
// raw.NSString (matching DarwinKit's package-scoped naming convention).
//
// Generated shape (non-generic):
//
//	type String = raw.NSString
//	type URL    = raw.NSURL
//
// Generated shape (generic):
//
//	type Array[T objc.Object] = raw.NSArray[T]
//
// Only classes whose stripped name (a) differs from the original, (b) is
// unique within the framework, and (c) does not shadow a Go predeclared
// identifier are emitted. The aliases are purely additive — the raw types
// remain accessible via the "raw" import alias.
func EmitTypeAliases(w io.Writer, pkgName, rawImportPath string, framework *meta.FrameworkMeta, m *typemap.Mapper, knownClasses map[string]bool) error {
	type aliasEntry struct {
		alias     string // e.g. "String"
		rawName   string // e.g. "NSString"
		typeParams string // e.g. "[T objc.Object]" or ""
	}

	// stripped → original: detect collisions
	seen := make(map[string]string)
	var entries []aliasEntry

	names := make([]string, 0, len(framework.Classes))
	for k := range framework.Classes {
		names = append(names, k)
	}
	sort.Strings(names)

	for _, name := range names {
		cls := framework.Classes[name]
		if cls.Availability.IsUnavailable {
			continue
		}
		alias := removeNSPrefix(name)
		if alias == name {
			// No prefix to strip.
			continue
		}
		if isGoBuiltin(alias) {
			// Shadowing a predeclared identifier would confuse readers.
			continue
		}
		if prior, exists := seen[alias]; exists {
			// Two classes strip to the same name (e.g. NSSet and NS_Set).
			// Skip both to avoid a duplicate type alias.
			_ = prior
			continue
		}
		seen[alias] = name

		typeParams := ""
		if len(cls.GenericParams) > 0 {
			typeParams = "[T objc.Object]"
		}
		entries = append(entries, aliasEntry{
			alias:     alias,
			rawName:   name,
			typeParams: typeParams,
		})
	}

	if len(entries) == 0 {
		return nil
	}

	needsObjc := false
	for _, e := range entries {
		if e.typeParams != "" {
			needsObjc = true
			break
		}
	}

	var body bytes.Buffer
	for _, e := range entries {
		if e.typeParams != "" {
			fmt.Fprintf(&body, "// %s is an alias for raw.%s with the NS prefix stripped.\n", e.alias, e.rawName)
			fmt.Fprintf(&body, "type %s%s = raw.%s%s\n\n", e.alias, e.typeParams, e.rawName, "[T]")
		} else {
			fmt.Fprintf(&body, "// %s is an alias for raw.%s with the NS prefix stripped.\n", e.alias, e.rawName)
			fmt.Fprintf(&body, "type %s = raw.%s\n\n", e.alias, e.rawName)
		}
	}

	// Write header without "context" — type aliases don't call any methods.
	fmt.Fprintf(w, "// Code generated by go-bindings-codegen. DO NOT EDIT.\n\n")
	fmt.Fprintf(w, "//go:build darwin\n\n")
	fmt.Fprintf(w, "package %s\n\n", pkgName)
	fmt.Fprintf(w, "import (\n")
	fmt.Fprintf(w, "\traw %q\n", rawImportPath)
	if needsObjc {
		fmt.Fprintf(w, "\t%q\n", "github.com/deploymenttheory/go-bindings-macosplatform/internal/objc")
	}
	fmt.Fprintf(w, ")\n\n")

	_, err := w.Write(body.Bytes())
	return err
}

// removeNSPrefix removes a leading "NS" from className when the remaining
// string starts with an uppercase letter (so "NSString" → "String" but
// "NSurl" would stay — which doesn't occur in practice).
func removeNSPrefix(name string) string {
	if strings.HasPrefix(name, "NS") && len(name) > 2 {
		rest := name[2:]
		if len(rest) > 0 && rest[0] >= 'A' && rest[0] <= 'Z' {
			return rest
		}
	}
	return name
}

// isGoBuiltin reports whether name is a Go predeclared identifier that should
// not be shadowed by a generated type alias.
func isGoBuiltin(name string) bool {
	switch name {
	case "bool", "byte", "complex64", "complex128",
		"error", "float32", "float64",
		"int", "int8", "int16", "int32", "int64",
		"rune", "string", "uint", "uint8", "uint16", "uint32", "uint64",
		"uintptr", "true", "false", "nil", "iota",
		"cap", "close", "delete", "imag", "len", "make", "new",
		"panic", "print", "println", "real", "recover",
		"append", "copy":
		return true
	}
	return false
}
