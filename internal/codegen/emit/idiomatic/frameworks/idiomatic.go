// EmitFrameworkWrappers generates one *_generated.go file per ObjC class in
// framework. idio is the framework's parsed idiomatic.json sidecar (curated
// renames, delegate selection, error typedefs); nil when the framework has none.
func EmitFrameworkWrappers(
	outDir, pkgName, rawPkgAlias, rawPkgPath string,
	framework *meta.FrameworkMeta,
	mapper *typemap.Mapper,
	idio *idioconf.File,
	manifest *emitmanifest.Recorder,
) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("mkdir %s: %w", outDir, err)
	}

	// Per-framework derived data lives here for this call only, replacing the
	// former package-level caches (P6: no shared mutable state).
	fc := newFrameworkContext(framework, idio)
	fc.manifest = manifest
	prefix := fc.prefix
	// Build the set of trial type names so we can use them in params.
	trialNames := buildTrialNameMap(framework, prefix)
	// Build abstract base index for provider interface generation.
	abstractBases := buildAbstractBaseIndex(framework, prefix)

	// Scan hand-authored (non-generated) files in this package so the generator
	// never emits a method or constructor that a human has already written — the
	// hand-crafted refinement always wins.
	handMethods, handFuncs, err := scanHandAuthored(outDir)
	if err != nil {
		return fmt.Errorf("scan hand-authored files: %w", err)
	}

	// Resolve the framework's delegate protocols before class emission so
	// delegate-typed property setters can accept the Go interface; the files
	// themselves are written after the class loop.
	delegates := buildDelegates(fc, mapper, rawPkgAlias, trialNames)
	fc.delegates = make(map[string]string, len(delegates))
	for _, delegate := range delegates {
		fc.delegates[delegate.protocolName] = delegate.view.IfaceName
		// The idiomatic layer surfaces an ObjC protocol as a usable Go interface
		// only when it is delegate-shaped; every other protocol is (for now) not
		// re-emitted, which the parity manifest reports as a gap (closed in the
		// protocols phase). Record the delegate-backed ones keyed on the protocol
		// name so they match the raw oracle's protocol entry.
		fc.manifest.Record(emitmanifest.Entry{
			Style:     emitmanifest.StyleIdiomatic,
			Kind:      emitmanifest.KindProtocol,
			Framework: framework.Framework,
			MetaKey: emitmanifest.MetaKey(
				framework.Framework,
				emitmanifest.KindProtocol,
				delegate.protocolName,
				"",
			),
			GoPkg:    pkgName,
			GoSymbol: delegate.view.IfaceName,
		})
	}

	// Clear previously generated files so a regeneration never leaves stale
	// output behind — e.g. when a function moves from one emitted file to
	// another (the generic C-function pass stops emitting a function this CF
	// pass now claims) or a class leaves the metadata.
	if err := removeGeneratedFiles(outDir); err != nil {
		return fmt.Errorf("clean generated files: %w", err)
	}

	// Emit the code that loads this package's macOS framework and looks up
	// Objective-C classes by name, which the constructors and class-level
	// functions call. Written after the clean step because it is itself a
	// _generated.go file.
	if err := emitRuntimeBootstrap(outDir, pkgName, framework); err != nil {
		return fmt.Errorf("emit runtime bootstrap: %w", err)
	}

	// File names whose only difference is letter case (e.g. Apple's compatibility
	// pair MTRClusterWakeOnLAN / MTRClusterWakeOnLan) collide on a case-insensitive
	// filesystem, where the second class would silently overwrite the first and
	// leave its type undefined. The Go type names stay case-distinct (and valid);
	// we only disambiguate the file name so both classes land in separate files.
	fileBaseCounts := map[string]int{}

	for _, className := range sortedKeys(framework.Classes) {
		class := framework.Classes[className]
		if class.Availability.IsUnavailable {
			continue
		}
		goTypeName := trialTypeName(className, prefix)

		var buf bytes.Buffer
		if err := emitClassFile(&buf, pkgName, rawPkgAlias, rawPkgPath,
			className, goTypeName, class, fc, mapper, trialNames, prefix, abstractBases,
			handFuncs, handMethods[goTypeName]); err != nil {
			return fmt.Errorf("emit %s: %w", className, err)
		}
		if buf.Len() == 0 {
			continue
		}
		fc.manifest.Record(emitmanifest.Entry{
			Style:     emitmanifest.StyleIdiomatic,
			Kind:      emitmanifest.KindClass,
			Framework: framework.Framework,
			MetaKey: emitmanifest.MetaKey(
				framework.Framework,
				emitmanifest.KindClass,
				className,
				"",
			),
			GoPkg:    pkgName,
			GoSymbol: goTypeName,
		})

		fname := className + "_generated.go"
		if n := fileBaseCounts[strings.ToLower(className)]; n > 0 {
			fname = fmt.Sprintf("%s_case%d_generated.go", className, n)
		}
		fileBaseCounts[strings.ToLower(className)]++
		if err := rawfw.WriteGoFile(filepath.Join(outDir, fname), buf.Bytes()); err != nil {
			return err
		}
	}
	if err := emitProvidersFile(
		outDir,
		pkgName,
		rawPkgAlias,
		rawPkgPath,
		abstractBases,
		framework,
		mapper,
	); err != nil {
		return fmt.Errorf("emit providers: %w", err)
	}
	if err := emitDelegateFiles(outDir, pkgName, delegates); err != nil {
		return fmt.Errorf("emit delegates: %w", err)
	}
	cfErrorWrapperNames, err := emitFunctionWrappers(
		outDir,
		pkgName,
		rawPkgAlias,
		rawPkgPath,
		fc,
		mapper,
		trialNames,
	)
	if err != nil {
		return fmt.Errorf("emit function wrappers: %w", err)
	}
	takenNames := buildTakenNames(framework, trialNames, abstractBases, cfErrorWrapperNames)
	// Reserve the de-prefixed names of every enum so a package-level function
	// (a class method or C function) never claims a name an enum type uses; the
	// enum keeps the short name and the function is qualified or omitted instead.
	for key, enum := range framework.Enums {
		if enum.Availability.IsUnavailable || enum.IsAnon {
			continue
		}
		goType := naming.GoTypeName(key)
		if isExportedGoIdent(goType) {
			takenNames[fc.localEnumTypeName(goType)] = true
		}
	}
	// Reserve the delegate interface names so a package-level function never
	// claims one.
	for _, delegate := range delegates {
		takenNames[delegate.view.IfaceName] = true
		for _, optional := range delegate.view.Optional {
			takenNames[optional.OptIfaceName] = true
		}
	}
	if err := emitClassMethodFunctions(
		outDir,
		pkgName,
		rawPkgAlias,
		rawPkgPath,
		fc,
		mapper,
		trialNames,
		handFuncs,
		takenNames,
		abstractBases,
	); err != nil {
		return fmt.Errorf("emit class method functions: %w", err)
	}
	if err := emitConstants(
		outDir,
		pkgName,
		rawPkgAlias,
		rawPkgPath,
		framework,
		mapper,
		handFuncs,
		takenNames,
		trialNames,
		fc.manifest,
	); err != nil {
		return fmt.Errorf("emit constants: %w", err)
	}
	if err := emitCFFunctionWrappers(
		outDir, pkgName, rawPkgAlias, rawPkgPath, fc, mapper, trialNames, takenNames,
	); err != nil {
		return fmt.Errorf("emit CF function wrappers: %w", err)
	}
	if err := emitGenericFunctionWrappers(
		outDir, pkgName, rawPkgAlias, rawPkgPath, fc, mapper, trialNames, takenNames,
	); err != nil {
		return fmt.Errorf("emit generic function wrappers: %w", err)
	}
	// A locally re-declared value struct may have enum-typed fields; mark those
	// enums referenced before emitEnums so they get a local definition (keeping the
	// struct's field types hermetic).
	registerLocalStructEnumRefs(fc, mapper, takenNames)
	// Re-export raw enum types/constants referenced by the generated package so
	// callers never need the raw import to name an enum or use its constants.
	// Runs last: it scans the files written above.
	if err := emitEnums(
		outDir, pkgName, rawPkgAlias, rawPkgPath, fc, takenNames,
	); err != nil {
		return fmt.Errorf("emit enums: %w", err)
	}
	// Re-declare the framework's value-type structs (CGSize, CGRect, NSRange, …
	// and every opaque or degraded-field struct) so callers never need the raw
	// import to name them. Runs after emitEnums so takenNames is complete.
	if err := emitStructs(
		outDir, pkgName, rawPkgAlias, rawPkgPath, fc, mapper, takenNames,
	); err != nil {
		return fmt.Errorf("emit structs: %w", err)
	}
	// Go interfaces for the framework's Objective-C protocols not already surfaced
	// as delegates. Runs after every other construct so takenNames is complete.
	if err := emitProtocols(
		outDir,
		pkgName,
		rawPkgAlias,
		fc,
		mapper,
		trialNames,
		takenNames,
	); err != nil {
		return fmt.Errorf("emit protocols: %w", err)
	}
	// Named error values for errors.Is, derived from the framework's error-code
	// enum and matching error domain.
	if err := emitErrorSentinels(outDir, pkgName, fc, takenNames); err != nil {
		return fmt.Errorf("emit error sentinels: %w", err)
	}
	if err := emitDocGo(outDir, pkgName, fc, abstractBases, prefix); err != nil {
		return err
	}
	// Enforce the core guarantee: the generated idiomatic package must not depend
	// on the raw bindings. A violation is a generation failure, not a build-time
	// surprise.
	return verifyHermetic(outDir)
}

// buildTakenNames collects the package-level identifiers already produced in
// the idiomatic package so generic C-function wrapper names cannot collide:
// trial type names and their New* constructors, provider interfaces, and the
// CFError wrapper functions.
func buildTakenNames(
	framework *meta.FrameworkMeta,
	trialNames trialNameMap,
	abstractBases abstractBaseIndex,
	cfErrorWrapperNames map[string]bool,
) map[string]bool {
	taken := make(map[string]bool, len(trialNames)*2+len(cfErrorWrapperNames))
	for _, trialName := range trialNames {
		taken[trialName] = true
		taken["New"+trialName] = true
	}
	for _, goTypeName := range abstractBases {
		taken[providerInterfaceName(goTypeName)] = true
	}
	for name := range cfErrorWrapperNames {
		taken[name] = true
	}
	return taken
}

