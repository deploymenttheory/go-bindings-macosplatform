package idiolib

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// EmitAliases re-exports every exported top-level type, constant, and variable
// the raw C-library package declares as an idiomatic alias (`type X = raw.X`,
// `const X = raw.X`, `var X = raw.X`), so callers reach the library's enums,
// structs, protocols, and global values through the idiomatic package without
// importing the raw bindings. Free functions are intentionally not re-exported:
// the idiomatic layer surfaces them as handle methods and ergonomic wrappers.
//
// The re-export list is read from the raw package's own emitted source (rawSrcDir)
// rather than re-derived from metadata, so it always matches exactly what the raw
// layer exports — names, dedup, and skips included. Nothing is written when the
// raw package has no re-exportable declarations.
func EmitAliases(w *bytes.Buffer, pkgName, rawImportPath, rawSrcDir string, skip map[string]bool) error {
	types, consts, vars, err := collectRawExports(rawSrcDir)
	if err != nil {
		return err
	}
	types = filterOut(types, skip)
	consts = filterOut(consts, skip)
	vars = filterOut(vars, skip)
	if len(types)+len(consts)+len(vars) == 0 {
		return nil
	}

	var body bytes.Buffer
	emitAliasGroup(&body, "type", types)
	emitAliasGroup(&body, "const", consts)
	emitAliasGroup(&body, "var", vars)

	fmt.Fprintf(w, "// Code generated by go-bindings-codegen. DO NOT EDIT.\n\n")
	fmt.Fprintf(w, "//go:build darwin\n\n")
	fmt.Fprintf(w, "package %s\n\n", pkgName)
	fmt.Fprintf(w, "import raw %q\n\n", rawImportPath)
	fmt.Fprintf(w, "// These aliases re-export the raw %s bindings' exported\n", pkgName)
	fmt.Fprintf(w, "// types and values so callers name them through this package.\n\n")
	w.Write(body.Bytes())
	return nil
}

// emitAliasGroup writes one `<kw> ( Name = raw.Name … )` block, or nothing when
// the set is empty. A `type` group uses `Name = raw.Name`; const/var groups use
// the same right-hand side.
func emitAliasGroup(w *bytes.Buffer, keyword string, names []string) {
	if len(names) == 0 {
		return
	}
	fmt.Fprintf(w, "%s (\n", keyword)
	for _, name := range names {
		fmt.Fprintf(w, "\t%s = raw.%s\n", name, name)
	}
	fmt.Fprintf(w, ")\n\n")
}

// filterOut drops names present in skip (identifiers another idiomatic emitter in
// the same package already declares, which a re-export would redeclare).
func filterOut(names []string, skip map[string]bool) []string {
	if len(skip) == 0 {
		return names
	}
	out := names[:0:0]
	for _, n := range names {
		if !skip[n] {
			out = append(out, n)
		}
	}
	return out
}

// CollectDeclaredNames parses Go source and returns the exported top-level
// identifiers it declares (types, consts, vars, and funcs). The library pipeline
// uses it to gather the names the ergonomic emitters produce so the alias
// re-export never collides with them.
func CollectDeclaredNames(src []byte) (map[string]bool, error) {
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, "", src, parser.SkipObjectResolution)
	if err != nil {
		return nil, err
	}
	names := map[string]bool{}
	for _, decl := range file.Decls {
		switch d := decl.(type) {
		case *ast.FuncDecl:
			if d.Recv == nil && d.Name.IsExported() {
				names[d.Name.Name] = true
			}
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					if s.Name.IsExported() {
						names[s.Name.Name] = true
					}
				case *ast.ValueSpec:
					for _, ident := range s.Names {
						if ident.IsExported() {
							names[ident.Name] = true
						}
					}
				}
			}
		}
	}
	return names, nil
}

// ReExportableExports returns the raw package's exported type, const, and var
// identifiers — the constructs the alias re-export covers — as a set. It is the
// oracle side of the library parity check (functions are excluded: the idiomatic
// layer surfaces them as methods, not package-level names).
func ReExportableExports(rawSrcDir string) (map[string]bool, error) {
	types, consts, vars, err := collectRawExports(rawSrcDir)
	if err != nil {
		return nil, err
	}
	out := make(map[string]bool, len(types)+len(consts)+len(vars))
	for _, group := range [][]string{types, consts, vars} {
		for _, name := range group {
			out[name] = true
		}
	}
	return out, nil
}

// PackageExports returns every exported top-level identifier a package's non-cgo
// Go files declare (types, consts, vars, and funcs). It is the idiomatic side of
// the library parity check.
func PackageExports(dir string) (map[string]bool, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	out := map[string]bool{}
	for _, ent := range entries {
		name := ent.Name()
		if ent.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		if name == "cgo.go" || name == "doc.go" {
			continue
		}
		src, rerr := os.ReadFile(filepath.Join(dir, name))
		if rerr != nil {
			return nil, rerr
		}
		names, cerr := CollectDeclaredNames(src)
		if cerr != nil {
			return nil, cerr
		}
		for n := range names {
			out[n] = true
		}
	}
	return out, nil
}

// collectRawExports parses every non-cgo Go file in the raw package directory and
// returns the exported top-level type, const, and var identifiers (sorted,
// deduplicated). Functions and the cgo/doc scaffolding files are skipped.
func collectRawExports(rawSrcDir string) (types, consts, vars []string, err error) {
	entries, err := os.ReadDir(rawSrcDir)
	if err != nil {
		return nil, nil, nil, fmt.Errorf("read raw package %s: %w", rawSrcDir, err)
	}
	typeSet, constSet, varSet := map[string]bool{}, map[string]bool{}, map[string]bool{}
	fset := token.NewFileSet()
	for _, ent := range entries {
		name := ent.Name()
		if ent.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		// cgo.go carries the `import "C"` + linker directives and declares no
		// re-exportable API; doc.go is prose only.
		if name == "cgo.go" || name == "doc.go" {
			continue
		}
		file, perr := parser.ParseFile(fset, filepath.Join(rawSrcDir, name), nil, parser.SkipObjectResolution)
		if perr != nil {
			return nil, nil, nil, fmt.Errorf("parse %s: %w", name, perr)
		}
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok {
				continue // FuncDecl and others are not re-exported here
			}
			for _, spec := range gen.Specs {
				switch s := spec.(type) {
				case *ast.TypeSpec:
					if s.Name.IsExported() {
						typeSet[s.Name.Name] = true
					}
				case *ast.ValueSpec:
					for _, ident := range s.Names {
						if !ident.IsExported() {
							continue
						}
						if gen.Tok == token.CONST {
							constSet[ident.Name] = true
						} else {
							varSet[ident.Name] = true
						}
					}
				}
			}
		}
	}
	return sortedSetKeys(typeSet), sortedSetKeys(constSet), sortedSetKeys(varSet), nil
}

func sortedSetKeys(m map[string]bool) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}
