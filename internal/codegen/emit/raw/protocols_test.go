// newProtoFM builds a minimal FrameworkMeta for protocol tests.
func newProtoFM(framework string, protocols map[string]meta.Protocol, classes map[string]meta.Class) *meta.FrameworkMeta {
	if classes == nil {
		classes = map[string]meta.Class{}
	}
	return &meta.FrameworkMeta{
		Framework: framework,
		Protocols: protocols,
		Classes:   classes,
		Enums:     map[string]meta.Enum{},
		Structs:   map[string]meta.Struct{},
		BlockTypes: map[string]meta.BlockType{},
	}
}

func runProtocols(t *testing.T, framework *meta.FrameworkMeta) string {
	t.Helper()
	return runProtocolsWithKnown(t, framework, map[string]string{})
}

func runProtocolsWithKnown(t *testing.T, framework *meta.FrameworkMeta, knownProtocols map[string]string) string {
	t.Helper()
	m := testMapper()
	var buf bytes.Buffer
	if err := EmitProtocols(&buf, "mypkg", framework, m, map[string]bool{}, knownProtocols, nil); err != nil {
		t.Fatalf("Protocols returned error: %v", err)
	}
	return buf.String()
}

