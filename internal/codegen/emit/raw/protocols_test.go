// --------------------------------------------------------------------------
// Class-name collision
// --------------------------------------------------------------------------

func TestProtocolDisambiguatesClassNameCollision(t *testing.T) {
	// When a protocol shares its name with a class (anywhere in the loaded set)
	// it must be emitted under the disambiguated `<Name>Protocol` form so the
	// class struct and the protocol interface can coexist in the package's
	// identifier namespace. naming.ProtocolGoTypeName drives this rule via the
	// mapper's OwnerIndex registry.
	framework := newProtoFM("Foundation", map[string]meta.Protocol{
		"NSCopying": {
			Methods: []meta.Method{
				{Selector: "copy", Return: meta.ReturnType{}},
			},
		},
	}, map[string]meta.Class{
		// Same name as the protocol → naming layer adds the Protocol suffix.
		"NSCopying": {},
	})
	m := testMapper()
	m.OwnerIndex["NSCopying"] = "Foundation"
	var buf bytes.Buffer
	if err := EmitProtocols(&buf, "mypkg", framework, m, map[string]bool{"NSCopying": true}, map[string]string{}, nil); err != nil {
		t.Fatalf("Protocols returned error: %v", err)
	}
	out := buf.String()

	if strings.Contains(out, "type NSCopying interface") {
		t.Errorf("protocol NSCopying must NOT use the bare name when a class shadows it, got:\n%s", out)
	}
	if !strings.Contains(out, "type NSCopyingProtocol interface") {
		t.Errorf("expected `type NSCopyingProtocol interface` in output, got:\n%s", out)
	}
}

// --------------------------------------------------------------------------
// Embedding parent protocols
// --------------------------------------------------------------------------

func TestProtocolWithParentEmbed(t *testing.T) {
	// Parent protocol in the same framework → embedded in the child interface.
	framework := newProtoFM("Foundation", map[string]meta.Protocol{
		"NSObject": {
			Methods: []meta.Method{
				{Selector: "hash", Return: meta.ReturnType{ObjCType: "NSUInteger"}},
			},
		},
		"NSCopying": {
			InheritedProtocols: []string{"NSObject"},
			Methods:    []meta.Method{},
		},
	}, nil)
	out := runProtocols(t, framework)

	if !strings.Contains(out, "NSObject") {
		t.Errorf("expected NSObject embed in NSCopying interface:\n%s", out)
	}
}

func TestProtocolParentInOtherFrameworkNotEmbedded(t *testing.T) {
	// Parent protocol from a different framework is NOT present in framework.Protocols,
	// so it must not appear as an embed.
	framework := newProtoFM("AppKit", map[string]meta.Protocol{
		"NSChildProtocol": {
			// "NSObject" is listed as a parent but is not in THIS framework's Protocols map.
			InheritedProtocols: []string{"NSObject"},
			Methods:    []meta.Method{},
		},
	}, nil)
	out := runProtocols(t, framework)

	// The interface body should not contain "NSObject" as an embedded type line.
	// Find the interface block and inspect it.
	ifaceStart := strings.Index(out, "type NSChildProtocol interface {")
	if ifaceStart < 0 {
		t.Fatalf("expected NSChildProtocol interface:\n%s", out)
	}
	ifaceEnd := strings.Index(out[ifaceStart:], "}")
	ifaceBody := out[ifaceStart : ifaceStart+ifaceEnd+1]

	// The embed would appear as a bare "NSObject" line inside the braces.
	if strings.Contains(ifaceBody, "\tNSObject\n") {
		t.Errorf("NSObject should not be embedded (it is in a different framework):\n%s", ifaceBody)
	}
}

func TestProtocolParentCrossFrameworkEmbed(t *testing.T) {
	// Parent protocol from a known different framework → qualified embed.
	framework := newProtoFM("AppKit", map[string]meta.Protocol{
		"NSChildProtocol": {
			InheritedProtocols: []string{"NSCopying"},
			Methods:    []meta.Method{},
		},
	}, nil)
	knownProtocols := map[string]string{"NSCopying": "Foundation"}
	out := runProtocolsWithKnown(t, framework, knownProtocols)

	ifaceStart := strings.Index(out, "type NSChildProtocol interface {")
	if ifaceStart < 0 {
		t.Fatalf("expected NSChildProtocol interface:\n%s", out)
	}
	ifaceEnd := strings.Index(out[ifaceStart:], "}")
	ifaceBody := out[ifaceStart : ifaceStart+ifaceEnd+1]

	if !strings.Contains(ifaceBody, "foundation.NSCopying") {
		t.Errorf("expected 'foundation.NSCopying' embed in cross-framework case:\n%s", ifaceBody)
	}
}

func TestProtocolParentCrossFrameworkBlocked(t *testing.T) {
	// Parent protocol from a known but import-blocked framework → comment, no embed.
	framework := newProtoFM("AppKit", map[string]meta.Protocol{
		"NSChildProtocol": {
			InheritedProtocols: []string{"NSCopying"},
			Methods:    []meta.Method{},
		},
	}, nil)
	knownProtocols := map[string]string{"NSCopying": "Foundation"}
	m := testMapper()
	// Simulate a blocked import: AppKit cannot import Foundation (cycle).
	m.BlockedImports = map[string]map[string]bool{
		"AppKit": {"Foundation": true},
	}
	var buf bytes.Buffer
	if err := EmitProtocols(&buf, "mypkg", framework, m, map[string]bool{}, knownProtocols, nil); err != nil {
		t.Fatalf("Protocols returned error: %v", err)
	}
	out := buf.String()

	ifaceStart := strings.Index(out, "type NSChildProtocol interface {")
	if ifaceStart < 0 {
		t.Fatalf("expected NSChildProtocol interface:\n%s", out)
	}
	ifaceEnd := strings.Index(out[ifaceStart:], "}")
	ifaceBody := out[ifaceStart : ifaceStart+ifaceEnd+1]

	if strings.Contains(ifaceBody, "\tfoundation.NSCopying\n") {
		t.Errorf("foundation.NSCopying should not appear as a Go embed line when blocked:\n%s", ifaceBody)
	}
	if !strings.Contains(ifaceBody, "// implements foundation.NSCopying (import blocked") {
		t.Errorf("expected blocked-import comment for foundation.NSCopying:\n%s", ifaceBody)
	}
}

