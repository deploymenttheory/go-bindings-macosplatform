// --------------------------------------------------------------------------
// Variadic skip
// --------------------------------------------------------------------------

func TestProtocolSkipsNilSentinelVariadic(t *testing.T) {
	framework := newProtoFM("Foundation", map[string]meta.Protocol{
		"NSLogging": {
			Methods: []meta.Method{
				{Selector: "log", Return: meta.ReturnType{}},
				// nil-sentinel variadic — should be skipped
				{Selector: "logItems:", IsVariadic: true, Return: meta.ReturnType{}},
				// format-string variadic — should appear
				{Selector: "logWithFormat:", IsVariadic: true, Params: []meta.Param{{Name: "format", ObjCType: "NSString *"}}, Return: meta.ReturnType{}},
			},
		},
	}, nil)
	out := runProtocols(t, framework)

	if strings.Contains(out, "LogItems(") {
		t.Errorf("nil-sentinel variadic method LogItems should have been skipped:\n%s", out)
	}
	// Non-variadic should still appear.
	if !strings.Contains(out, "Log(ctx context.Context)") {
		t.Errorf("expected non-variadic method Log(ctx context.Context):\n%s", out)
	}
	// Format-string variadic should appear.
	if !strings.Contains(out, "LogWithFormat(") {
		t.Errorf("expected format-string variadic method LogWithFormat:\n%s", out)
	}
}

// --------------------------------------------------------------------------
// Deduplication
// --------------------------------------------------------------------------

func TestProtocolDedupsMethods(t *testing.T) {
	// Two methods with identical Go names (same selector repeated) → only one emitted.
	framework := newProtoFM("Foundation", map[string]meta.Protocol{
		"NSDup": {
			Methods: []meta.Method{
				{Selector: "count", Return: meta.ReturnType{ObjCType: "NSUInteger"}},
				{Selector: "count", Return: meta.ReturnType{ObjCType: "NSUInteger"}},
			},
		},
	}, nil)
	out := runProtocols(t, framework)

	// "Count(ctx context.Context)" should appear exactly once inside the interface body.
	first := strings.Index(out, "Count(ctx context.Context)")
	if first < 0 {
		t.Fatalf("expected at least one Count(ctx context.Context) method:\n%s", out)
	}
	second := strings.Index(out[first+1:], "Count(ctx context.Context)")
	if second >= 0 {
		t.Errorf("Count(ctx context.Context) appears more than once (dedup failed):\n%s", out)
	}
}

// --------------------------------------------------------------------------
// Sort order
// --------------------------------------------------------------------------

func TestProtocolSortOrder(t *testing.T) {
	framework := newProtoFM("Foundation", map[string]meta.Protocol{
		"ZProtocol": {Methods: []meta.Method{}},
		"AProtocol": {Methods: []meta.Method{}},
		"MProtocol": {Methods: []meta.Method{}},
	}, nil)
	out := runProtocols(t, framework)

	aIdx := strings.Index(out, "AProtocol")
	mIdx := strings.Index(out, "MProtocol")
	zIdx := strings.Index(out, "ZProtocol")
	if aIdx < 0 || mIdx < 0 || zIdx < 0 {
		t.Fatalf("one or more protocols not found in output:\n%s", out)
	}
	if !(aIdx < mIdx && mIdx < zIdx) {
		t.Errorf("protocols not in alphabetical order: A@%d M@%d Z@%d", aIdx, mIdx, zIdx)
	}
}

