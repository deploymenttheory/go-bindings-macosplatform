// sortedEnumNames returns enum names in a stable order: named enums first,
// then anonymous, all sorted alphabetically within each group.
func sortedEnumNames(enums map[string]meta.Enum) []string {
	var named, anon []string
	for name, e := range enums {
		if e.IsAnon {
			anon = append(anon, name)
		} else {
			named = append(named, name)
		}
	}
	sort.Strings(named)
	sort.Strings(anon)
	return append(named, anon...)
}

// isObjCObject reports whether a Go type string represents an ObjC object
// (i.e. pointer to a generated wrapper type, not a primitive or struct).
func isObjCObjectType(goType string) bool {
	if !strings.HasPrefix(goType, "*") {
		return false
	}
	// Strip pointer and check if it looks like an ObjC class (starts uppercase, no dot for same-package)
	inner := goType[1:]
	if strings.HasPrefix(inner, "unsafe.") {
		return false
	}
	if inner == "bool" || inner == "byte" || inner == "int" || inner == "uint" ||
		inner == "int8" || inner == "int16" || inner == "int32" || inner == "int64" ||
		inner == "uint8" || inner == "uint16" || inner == "uint32" || inner == "uint64" ||
		inner == "float32" || inner == "float64" || inner == "string" {
		return false
	}
	// Check if it starts with uppercase (ObjC class name or cross-package reference)
	last := inner
	if dotIdx := strings.LastIndex(inner, "."); dotIdx >= 0 {
		last = inner[dotIdx+1:]
	}
	if len(last) == 0 {
		return false
	}
	return last[0] >= 'A' && last[0] <= 'Z'
}

// deprecatedComment returns the deprecation comment line for a deprecated
// symbol, or "" when the symbol is not deprecated. It is used by the
// view-building (gather) phase to assemble comment blocks.
func deprecatedComment(avail meta.Availability) string {
	if avail.MacOSDeprecated == "" {
		return ""
	}
	if avail.DeprecationMsg != "" {
		return fmt.Sprintf("// Deprecated: %s\n", avail.DeprecationMsg)
	}
	return fmt.Sprintf("// Deprecated: since macOS %s.\n", avail.MacOSDeprecated)
}

// varSelectorName returns the unexported package-level var name for a selector,
// scoped to a class to avoid collisions.
func varSelectorName(className, selector string) string {
	return "_" + strings.ToLower(className[:1]) + className[1:] + "Sel" + naming.MethodName(selector)
}

// varClassName returns the unexported package-level var name for a class ref.
func varClassName(className string) string {
	return "_cls" + className
}
