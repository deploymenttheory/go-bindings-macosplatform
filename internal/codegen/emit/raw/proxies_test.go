// TestBuildIDProtocolCGOCallArgsWithBlockArg verifies block arg generates MakeBlock preamble.
func TestBuildIDProtocolCGOCallArgsWithBlockArg(t *testing.T) {
	m := proxyTestMapper()
	ctx := m.BaseContext("Virtualization", map[string]bool{})
	args := []meta.Param{{Name: "handler", ObjCType: "void (^)(void)", IsBlock: true}}
	var preambles, ka []string
	got := buildIDProtocolCGOCallArgs(args, false, ctx, m, &preambles, &ka, nil)
	// When block sig is found, a MakeBlock_ preamble is added; when not found (no
	// registered sig), unsafe.Pointer(nil) is used.
	if !strings.Contains(got, "handler") && !strings.Contains(got, "nil") {
		t.Errorf("block arg should produce handler or nil in call; got %q", got)
	}
}

