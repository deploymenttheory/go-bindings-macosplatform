func proxyTestMapper() *typemap.Mapper {
	return &typemap.Mapper{
		GenericClasses: map[string]bool{},
		OwnerIndex: map[string]string{
			"NSObject": "Foundation",
		},
		ModulePrefix:   "github.com/example/fw",
		BlockedImports: map[string]map[string]bool{},
		TypedefIndex:  map[string]string{},
		StructIndex:   map[string]string{},
		ProtocolIndex: map[string]string{},
		ProtocolProxyIndex: map[string]string{
			"VZFoo": "Virtualization",
		},
	}
}

// TestProtocolProxiesEmpty verifies no output when no protocols match ProtocolProxyIndex.
func TestProtocolProxiesEmpty(t *testing.T) {
	m := proxyTestMapper()
	framework := &meta.FrameworkMeta{
		Framework: "Foundation",
		Protocols: map[string]meta.Protocol{
			"NSBar": {}, // not in ProtocolProxyIndex
		},
	}
	var buf bytes.Buffer
	if err := EmitProtocolProxies(&buf, "foundation", "foundation", framework, m, map[string]bool{}, map[string]meta.Class{}); err != nil {
		t.Fatal(err)
	}
	if buf.Len() != 0 {
		t.Errorf("expected empty output when no proxy protocols; got:\n%s", buf.String())
	}
}

