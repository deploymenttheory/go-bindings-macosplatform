// newFuncFM builds a minimal FrameworkMeta for function tests.
func newFuncFM(framework string, functions []macosplatformmetadata.Function) *macosplatformmetadata.FrameworkMeta {
	return &macosplatformmetadata.FrameworkMeta{
		Framework:  framework,
		Functions:  functions,
		Classes:    map[string]macosplatformmetadata.Class{},
		Protocols:  map[string]macosplatformmetadata.Protocol{},
		Enums:      map[string]macosplatformmetadata.Enum{},
		Structs:    map[string]macosplatformmetadata.Struct{},
		BlockTypes: map[string]macosplatformmetadata.BlockType{},
		Typedefs:   map[string]string{},
	}
}

func runFunctions(t *testing.T, framework *macosplatformmetadata.FrameworkMeta) string {
	t.Helper()
	m := testMapper()
	var buf bytes.Buffer
	if err := EmitFunctions(&buf, "mypkg", strings.ToLower(framework.Framework), framework, m, map[string]bool{}); err != nil {
		t.Fatalf("Functions returned error: %v", err)
	}
	return buf.String()
}

// --------------------------------------------------------------------------
// File header
// --------------------------------------------------------------------------

func TestFunctionFileHeader(t *testing.T) {
	framework := newFuncFM("Foundation", nil)
	out := runFunctions(t, framework)

	for _, want := range []string{
		"// Code generated by go-bindings-codegen. DO NOT EDIT.",
		"//go:build darwin",
		"package mypkg",
		`// #include "bridge/foundation_bridge.h"`,
		`import "C"`,
		`"unsafe"`,
		"var _ unsafe.Pointer",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("missing %q in output:\n%s", want, out)
		}
	}
}

