// --------------------------------------------------------------------------
// Deduplication
// --------------------------------------------------------------------------

func TestFunctionDeduplicate(t *testing.T) {
	// Two functions whose names produce the same Go identifier → only first emitted.
	framework := newFuncFM("Foundation", []macosplatformmetadata.Function{
		{Name: "NSOpen", Return: macosplatformmetadata.ReturnType{}},
		{Name: "NSOpen", Return: macosplatformmetadata.ReturnType{}},
	})
	out := runFunctions(t, framework)

	// "func NSOpen()" should appear exactly once.
	first := strings.Index(out, "func NSOpen()")
	if first < 0 {
		t.Fatalf("expected at least one NSOpen function:\n%s", out)
	}
	second := strings.Index(out[first+1:], "func NSOpen()")
	if second >= 0 {
		t.Errorf("NSOpen emitted more than once (dedup failed):\n%s", out)
	}
}

