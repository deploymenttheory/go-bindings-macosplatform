// TestGenerateFrameworkCleansStaleFiles verifies that generating into a directory
// that already contains .go files removes them before writing new ones.
func TestGenerateFrameworkCleansStaleFiles(t *testing.T) {
	dir := t.TempDir()
	reg := buildMinimalRegistry("Foundation", map[string]meta.Class{"NSObject": {}})
	cfg := makeBindingsCfg(t, reg, dir)
	// First generation
	if err := GenerateBindings(cfg); err != nil {
		t.Fatal(err)
	}
	// Inject a stale file that should be removed on second run.
	stale := filepath.Join(dir, "foundation", "OldClass.go")
	if err := os.WriteFile(stale, []byte("package foundation\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	// Second generation on same dir — should remove OldClass.go.
	if err := GenerateBindings(cfg); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(stale); err == nil {
		t.Error("stale OldClass.go should have been removed by second generation")
	}
}

// TestWriteFileErrorFromFn verifies writeFile propagates an error returned by fn.
func TestWriteFileErrorFromFn(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "test.go")
	sentinelErr := fmt.Errorf("sentinel error")
	err := writeFile(path, func(buf *bytes.Buffer) error {
		return sentinelErr
	})
	if err == nil {
		t.Error("writeFile should propagate fn error")
	}
	if _, statErr := os.Stat(path); statErr == nil {
		t.Error("writeFile should not create file when fn errors")
	}
}

