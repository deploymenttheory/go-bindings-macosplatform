func buildMinimalRegistry(frameworkName string, cls map[string]meta.Class) *Registry {
	framework := &meta.FrameworkMeta{
		Framework: frameworkName,
		Classes:   cls,
	}
	reg := &Registry{
		Frameworks:     []*meta.FrameworkMeta{framework},
		ClassNameIndex:   make(map[string]bool),
		GenericClasses: make(map[string]bool),
		OwnerIndex: make(map[string]string),
		ClassIndex:     make(map[string]meta.Class),
		ModulePrefix:   "github.com/example/fw",
	}
	for name := range cls {
		reg.ClassNameIndex[name] = true
		reg.OwnerIndex[name] = frameworkName
		reg.ClassIndex[name] = cls[name]
	}
	return reg
}

// makeBindingsCfg returns a BindingsConfig with BlocksDir and CallbacksDir
// set to temporary subdirectories so tests never write to the real repo paths.
func makeBindingsCfg(t *testing.T, reg *Registry, frameworksOutDir string) BindingsConfig {
	t.Helper()
	bd := t.TempDir()
	cd := t.TempDir()
	return BindingsConfig{
		Registry:         reg,
		FrameworksOutDir: frameworksOutDir,
		BlocksDir:        bd,
		CallbacksDir:     cd,
	}
}

