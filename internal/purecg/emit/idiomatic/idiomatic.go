//go:build darwin

// Package idiomatic emits fluent Go wrapper types for ObjC frameworks.
//
// For each ObjC class the emitter generates a Go wrapper struct exposing:
//
//   - A constructor that bundles alloc+init (or +new) into a single call,
//     converting NSURL/NSString parameters to Go string at the boundary.
//   - Fluent With<Prop>(value) *Self methods for every settable property,
//     returning the receiver so calls can be chained.
//   - NSArray setters exposed as variadic With<Prop>(items...*T) *Self,
//     building the NSArray from a Go slice internally.
//   - Async completion handler methods as (ctx context.Context) error,
//     extracting NSError from unsafe.Pointer via ObjC metadata.
//   - NSArray-returning getter methods as typed Go slices ([]T).
//   - BoolNSError pairs simplified to plain error returns.
package idiomatic

import (
	"bytes"
	"fmt"
	"io"
	"maps"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"sort"
	"strings"

	"github.com/deploymenttheory/go-bindings-macosplatform/internal/purecg/emit"
	"github.com/deploymenttheory/go-bindings-macosplatform/internal/purecg/meta"
	"github.com/deploymenttheory/go-bindings-macosplatform/internal/purecg/naming"
	"github.com/deploymenttheory/go-bindings-macosplatform/internal/purecg/typemap"
)

const (
	generatedHeader      = "// Code generated by go-bindings-codegen. DO NOT EDIT.\n"
	buildTag             = "//go:build darwin\n"
	pureobjcImportPath   = "github.com/deploymenttheory/go-bindings-macosplatform/internal/pureobjc"
	objcImportPath       = "github.com/ebitengine/purego/objc"
	foundationImportPath = "github.com/deploymenttheory/go-bindings-macosplatform/bindings/frameworks/foundation"
)

// EmitFrameworkWrappers generates one *_generated.go file per ObjC class in fw.
func EmitFrameworkWrappers(
	outDir, pkgName, rawPkgAlias, rawPkgPath string,
	fw *meta.FrameworkMeta,
	m *typemap.Mapper,
) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return fmt.Errorf("mkdir %s: %w", outDir, err)
	}

	prefix := detectClassPrefix(fw)
	// Build the set of trial type names so we can use them in params.
	trialNames := buildTrialNameMap(fw, prefix)
	// Build abstract base index for provider interface generation.
	abstractBases := buildAbstractBaseIndex(fw, prefix)

	for _, className := range sortedKeys(fw.Classes) {
		cls := fw.Classes[className]
		if cls.Availability.IsUnavailable {
			continue
		}
		goTypeName := trialTypeName(className, prefix)

		var buf bytes.Buffer
		if err := emitClassFile(&buf, pkgName, rawPkgAlias, rawPkgPath,
			className, goTypeName, cls, fw, m, trialNames, prefix, abstractBases); err != nil {
			return fmt.Errorf("emit %s: %w", className, err)
		}
		if buf.Len() == 0 {
			continue
		}

		fname := className + "_generated.go"
		if err := os.WriteFile(filepath.Join(outDir, fname), buf.Bytes(), 0o600); err != nil {
			return fmt.Errorf("write %s: %w", fname, err)
		}
	}
	if err := emitProvidersFile(
		outDir,
		pkgName,
		rawPkgAlias,
		rawPkgPath,
		abstractBases,
		fw,
		m,
	); err != nil {
		return fmt.Errorf("emit providers: %w", err)
	}
	cfErrorWrapperNames, err := emitFunctionWrappers(
		outDir,
		pkgName,
		rawPkgAlias,
		rawPkgPath,
		fw,
		m,
	)
	if err != nil {
		return fmt.Errorf("emit function wrappers: %w", err)
	}
	takenNames := buildTakenNames(fw, trialNames, abstractBases, cfErrorWrapperNames)
	if err := emitGenericFunctionWrappers(
		outDir, pkgName, rawPkgAlias, rawPkgPath, fw, m, takenNames,
	); err != nil {
		return fmt.Errorf("emit generic function wrappers: %w", err)
	}
	return emitDocGo(outDir, pkgName, fw)
}

// buildTakenNames collects the package-level identifiers already produced in
// the idiomatic package so generic C-function wrapper names cannot collide:
// trial type names and their New* constructors, provider interfaces, and the
// CFError wrapper functions.
func buildTakenNames(
	fw *meta.FrameworkMeta,
	trialNames trialNameMap,
	abstractBases abstractBaseIndex,
	cfErrorWrapperNames map[string]bool,
) map[string]bool {
	taken := make(map[string]bool, len(trialNames)*2+len(cfErrorWrapperNames))
	for _, trialName := range trialNames {
		taken[trialName] = true
		taken["New"+trialName] = true
	}
	for _, goTypeName := range abstractBases {
		taken[providerInterfaceName(goTypeName)] = true
	}
	for name := range cfErrorWrapperNames {
		taken[name] = true
	}
	return taken
}

// trialNameMap maps raw ObjC class names to their trial Go type names.
// Used to substitute trial types for raw types in method signatures.
type trialNameMap map[string]string // rawClassName → trialTypeName

func buildTrialNameMap(fw *meta.FrameworkMeta, prefix string) trialNameMap {
	m := make(trialNameMap, len(fw.Classes))
	for className := range fw.Classes {
		m[className] = trialTypeName(className, prefix)
	}
	return m
}

// abstractBaseIndex maps ObjC raw class names (that have at least one direct subclass
// in the same framework) to their trial Go type name.
type abstractBaseIndex map[string]string // rawClassName → trialGoTypeName

// buildAbstractBaseIndex returns a map from ObjC class name to trial Go type name for
// every class in fw that has at least one direct subclass also in fw.
func buildAbstractBaseIndex(fw *meta.FrameworkMeta, prefix string) abstractBaseIndex {
	bases := make(abstractBaseIndex)
	for _, cls := range fw.Classes {
		if cls.Availability.IsUnavailable || cls.Super == "" {
			continue
		}
		if superCls, ok := fw.Classes[cls.Super]; ok && !superCls.Availability.IsUnavailable {
			bases[cls.Super] = trialTypeName(cls.Super, prefix)
		}
	}
	return bases
}

// ancestorEmbedChain returns the sequence of embedded field names required to access
// targetBase from startClass's inner raw type. E.g.:
//
//	("VZLinuxBootLoader", "VZBootLoader") → ["VZBootLoader"]
//	("VZLinuxRosettaUnixSocketCachingOptions", "VZLinuxRosettaCachingOptions")
//	    → ["VZLinuxRosettaAbstractSocketCachingOptions", "VZLinuxRosettaCachingOptions"]
//
// Returns nil if startClass == targetBase or the chain cannot be found.
func ancestorEmbedChain(startClass, targetBase string, fw *meta.FrameworkMeta) []string {
	if startClass == targetBase {
		return nil
	}
	var chain []string
	current := startClass
	for {
		cls, ok := fw.Classes[current]
		if !ok || cls.Super == "" {
			return nil
		}
		chain = append(chain, cls.Super)
		if cls.Super == targetBase {
			return chain
		}
		current = cls.Super
	}
}

// allAbstractBaseAncestors returns all ObjC class names that are abstract bases
// (present in abstractBases) and are proper ancestors of className.
func allAbstractBaseAncestors(
	className string,
	fw *meta.FrameworkMeta,
	abstractBases abstractBaseIndex,
) []string {
	var bases []string
	seen := map[string]bool{}
	current := className
	for {
		cls, ok := fw.Classes[current]
		if !ok || cls.Super == "" {
			break
		}
		if _, isBase := abstractBases[cls.Super]; isBase && !seen[cls.Super] {
			bases = append(bases, cls.Super)
			seen[cls.Super] = true
		}
		current = cls.Super
	}
	return bases
}

// providerInterfaceName returns the provider interface name for a trial Go type, e.g.
// "BootLoader" → "BootLoaderProvider".
func providerInterfaceName(trialGoTypeName string) string {
	return trialGoTypeName + "Provider"
}

// providerMethodName returns the package-private provider method name for a trial Go type, e.g.
// "BootLoader" → "asBootLoader".
func providerMethodName(trialGoTypeName string) string {
	return "as" + trialGoTypeName
}

// providerMethodEntry describes a provider method to be emitted on a trial wrapper type.
type providerMethodEntry struct {
	methodName string // e.g. "asBootLoader"
	rawType    string // e.g. "*raw.VZBootLoader" (full pointer type, owner-qualified)
	bodyExpr   string // e.g. "x.inner" or "&x.inner.VZBootLoader"
}

// providerRawType resolves the Go pointer type of a base class as embedded in the
// raw bindings, qualified by its owning package (which may differ from the current
// framework for umbrella sub-frameworks, e.g. MPSKernel lives in mpscore). Returns
// "" when the class does not resolve to a usable pointer type.
func providerRawType(
	baseClassName string,
	fw *meta.FrameworkMeta,
	m *typemap.Mapper,
	rawPkgAlias string,
	imports typemap.ImportSet,
) string {
	ctx := typemap.Context{Framework: fw.Framework}
	resolved := m.GoType(baseClassName+" *", ctx, imports)
	if !strings.HasPrefix(resolved, "*") {
		return ""
	}
	return qualifyRaw(resolved, fw, rawPkgAlias, nil)
}

// ── File emission ──────────────────────────────────────────────────────────────

func emitClassFile(
	w io.Writer,
	pkgName, rawPkgAlias, rawPkgPath string,
	className, goTypeName string,
	cls meta.Class,
	fw *meta.FrameworkMeta,
	m *typemap.Mapper,
	trialNames trialNameMap,
	prefix string,
	abstractBases abstractBaseIndex,
) error {
	ctx := typemap.Context{
		ClassName:     className,
		Framework:     fw.Framework,
		GenericParams: cls.GenericParams,
	}

	ctors := buildConstructors(cls, className, goTypeName, fw, ctx, m, rawPkgAlias, trialNames)
	withMethods := buildWithSetters(
		cls,
		goTypeName,
		fw,
		ctx,
		m,
		rawPkgAlias,
		trialNames,
		prefix,
		abstractBases,
	)
	methods := buildMethods(cls, fw, ctx, m, rawPkgAlias)
	providerMethods, providerImports := buildProviderMethods(
		cls, className, goTypeName, fw, m, rawPkgAlias, abstractBases)

	// Ensure a +new constructor exists for provider-only classes (no other content).
	if len(ctors) == 0 && len(providerMethods) > 0 {
		ctors = []ctorEntry{buildNewConstructor(className, goTypeName, rawPkgAlias)}
	}

	// Skip classes that have nothing useful to emit.
	if len(ctors) == 0 && len(withMethods) == 0 && len(methods) == 0 && len(providerMethods) == 0 {
		return nil
	}

	// ── Render body, then derive imports from what the code actually uses ──────

	var body bytes.Buffer

	rawType := rawPkgAlias + "." + className
	if len(cls.GenericParams) > 0 {
		rawType += genericInstantiation(len(cls.GenericParams))
	}

	fmt.Fprintf(
		&body,
		"// %s wraps [%s.%s] with a fluent Go API.\n",
		goTypeName,
		rawPkgAlias,
		className,
	)
	fmt.Fprintf(&body, "type %s struct {\n\tinner *%s\n}\n\n", goTypeName, rawType)
	fmt.Fprintf(&body, "// Unwrap returns the underlying [%s.%s].\n", rawPkgAlias, className)
	fmt.Fprintf(&body, "func (x *%s) Unwrap() *%s { return x.inner }\n\n", goTypeName, rawType)

	for _, c := range ctors {
		writeConstructor(
			&body,
			goTypeName,
			rawPkgAlias,
			className,
			genericInstantiation(len(cls.GenericParams)),
			c,
		)
	}
	for _, we := range withMethods {
		writeWithMethod(&body, goTypeName, we)
	}
	for _, me := range methods {
		writeMethod(&body, goTypeName, me)
	}
	for _, pm := range providerMethods {
		fmt.Fprintf(
			&body,
			"func (x *%s) %s() %s { return %s }\n\n",
			goTypeName,
			pm.methodName,
			pm.rawType,
			pm.bodyExpr,
		)
	}

	candidates := map[string]string{
		rawPkgAlias:  rawPkgPath,
		"context":    "context",
		"unsafe":     "unsafe",
		"pureobjc":   pureobjcImportPath,
		"foundation": foundationImportPath,
		"objc":       objcImportPath,
	}
	for _, c := range ctors {
		maps.Copy(candidates, c.extraImports)
	}
	for _, we := range withMethods {
		maps.Copy(candidates, we.extraImports)
	}
	for _, me := range methods {
		maps.Copy(candidates, me.extraImports)
	}
	maps.Copy(candidates, providerImports)
	imports := usedImports(body.Bytes(), candidates)

	// ── Write output ───────────────────────────────────────────────────────────

	fmt.Fprint(w, generatedHeader+"\n")
	fmt.Fprint(w, buildTag+"\n")
	fmt.Fprintf(w, "package %s\n\n", pkgName)
	writeImportBlock(w, imports)
	if _, err := w.Write(body.Bytes()); err != nil {
		return fmt.Errorf("write class body: %w", err)
	}

	return nil
}

// buildConstructors assembles the constructor entries for a class: one per
// parameterised init, plus a plain +new constructor when appropriate.
func buildConstructors(
	cls meta.Class,
	className, goTypeName string,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
	trialNames trialNameMap,
) []ctorEntry {
	var ctors []ctorEntry
	hasExplicitParamInit := false

	for _, method := range cls.Methods {
		if method.Availability.IsUnavailable || method.IsClassMethod || !method.IsInit {
			continue
		}
		if len(method.Params) == 0 {
			continue // plain init handled below as +new fallback
		}
		e := buildParamConstructor(method, goTypeName, cls, fw, ctx, m, rawPkgAlias, trialNames)
		if e != nil {
			ctors = append(ctors, *e)
			hasExplicitParamInit = true
		}
	}

	// Every class gets a plain +new constructor unless it has a param-init that
	// already covers the no-arg case.
	if !hasExplicitParamInit {
		return append(
			[]ctorEntry{buildNewConstructor(className, goTypeName, rawPkgAlias)},
			ctors...)
	}
	// Still provide a plain constructor if there is a class-specific plain init too.
	for _, method := range cls.Methods {
		if method.IsInit && len(method.Params) == 0 && !method.Availability.IsUnavailable {
			return append(
				[]ctorEntry{buildNewConstructor(className, goTypeName, rawPkgAlias)},
				ctors...)
		}
	}
	return ctors
}

// buildWithSetters assembles the fluent With* setter entries for a class's
// settable properties, deduplicated by Go method name.
func buildWithSetters(
	cls meta.Class,
	goTypeName string,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
	trialNames trialNameMap,
	prefix string,
	abstractBases abstractBaseIndex,
) []withEntry {
	var withMethods []withEntry
	seenWithName := map[string]bool{}
	for _, prop := range cls.Properties {
		if prop.IsReadOnly || prop.Availability.IsUnavailable {
			continue
		}
		we := buildWithSetter(
			prop,
			goTypeName,
			cls,
			fw,
			ctx,
			m,
			rawPkgAlias,
			trialNames,
			prefix,
			abstractBases,
		)
		if we == nil || seenWithName[we.goName] {
			continue
		}
		seenWithName[we.goName] = true
		withMethods = append(withMethods, *we)
	}
	return withMethods
}

// buildMethods assembles the instance method entries (async, slice getters,
// BoolNSError) for a class, deduplicated by Go method name.
func buildMethods(
	cls meta.Class,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
) []methodEntry {
	var methods []methodEntry
	seenMethod := map[string]bool{}
	for _, method := range cls.Methods {
		if method.Availability.IsUnavailable || method.IsClassMethod || method.IsInit {
			continue
		}
		e := buildMethod(method, "", cls, fw, ctx, m, rawPkgAlias)
		if e == nil || seenMethod[e.goName] {
			continue
		}
		seenMethod[e.goName] = true
		methods = append(methods, *e)
	}
	return methods
}

// buildProviderMethods assembles the provider interface implementations for a
// class: one for itself when it is an abstract base, and one per abstract base
// ancestor (returning the embedded raw superclass field).
func buildProviderMethods(
	cls meta.Class,
	className, goTypeName string,
	fw *meta.FrameworkMeta,
	m *typemap.Mapper,
	rawPkgAlias string,
	abstractBases abstractBaseIndex,
) ([]providerMethodEntry, typemap.ImportSet) {
	var providerMethods []providerMethodEntry
	providerImports := make(typemap.ImportSet)

	// Self-provider: this class is an abstract base, so it implements its own
	// interface. Skip when the class is owned by a different package (umbrella
	// sub-frameworks): x.inner is the local duplicate type, not the owner's, and
	// the owner's own trial package provides the interface implementation.
	if _, isBase := abstractBases[className]; isBase {
		rawType := providerRawType(className, fw, m, rawPkgAlias, providerImports)
		localType := "*" + rawPkgAlias + "." + className + genericInstantiation(
			len(cls.GenericParams),
		)
		if rawType == localType {
			providerMethods = append(providerMethods, providerMethodEntry{
				methodName: providerMethodName(goTypeName),
				rawType:    rawType,
				bodyExpr:   "x.inner",
			})
		}
	}
	// Ancestor providers: implement provider interface for each abstract base ancestor.
	for _, baseClassName := range allAbstractBaseAncestors(className, fw, abstractBases) {
		baseGoTypeName := abstractBases[baseClassName]
		chain := ancestorEmbedChain(className, baseClassName, fw)
		if len(chain) == 0 {
			continue
		}
		rawType := providerRawType(baseClassName, fw, m, rawPkgAlias, providerImports)
		if rawType == "" {
			continue
		}
		providerMethods = append(providerMethods, providerMethodEntry{
			methodName: providerMethodName(baseGoTypeName),
			rawType:    rawType,
			bodyExpr:   "&x.inner." + strings.Join(chain, "."),
		})
	}
	return providerMethods, providerImports
}

// usedImports filters candidates down to the aliases the rendered body actually
// references as a package qualifier ("<alias>." preceded by a non-identifier byte).
func usedImports(body []byte, candidates map[string]string) map[string]string {
	imports := map[string]string{}
	for alias, path := range candidates {
		pattern := regexp.MustCompile(`(^|[^A-Za-z0-9_.])` + regexp.QuoteMeta(alias) + `\.`)
		if pattern.Match(body) {
			imports[alias] = path
		}
	}
	return imports
}

// genericInstantiation returns the type-argument list used to instantiate a
// generic raw class in trial code, e.g. "[objc.ID]" or "[objc.ID, objc.ID]".
// objc.ID matches the raw emitter's own degradation default for generics.
func genericInstantiation(n int) string {
	if n == 0 {
		return ""
	}
	args := make([]string, n)
	for i := range args {
		args[i] = "objc.ID"
	}
	return "[" + strings.Join(args, ", ") + "]"
}

// ── Constructor generation ─────────────────────────────────────────────────────

type ctorEntry struct {
	goName          string
	rawInitGoName   string // "" = use +new
	rawInitSelector string // ObjC selector, e.g. "initWithURL:readOnly:error:"
	params          []ctorParam
	hasNSError      bool
	needsFoundation bool
	extraImports    map[string]string
}

type ctorParam struct {
	goName   string
	goType   string
	rawExpr  string // expression passed to the raw init method
	isObject bool   // true when the param is an ObjC object (send .Ptr())
}

// buildNewConstructor generates a plain +new constructor: New<Type>() *Type.
func buildNewConstructor(_, goTypeName, _ string) ctorEntry {
	return ctorEntry{
		goName:        "New" + goTypeName,
		rawInitGoName: "", // signals +new
	}
}

// buildParamConstructor generates a constructor from an init method with parameters.
func buildParamConstructor(
	method meta.Method,
	goTypeName string,
	_ meta.Class,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
	_ trialNameMap,
) *ctorEntry {
	rawInit := naming.MethodName(method.Selector)
	needsFoundation := false
	extraImports := map[string]string{}

	var params []ctorParam
	for i, p := range method.Params {
		pName := naming.ParamName(p.Name)
		if pName == "" {
			pName = fmt.Sprintf("arg%d", i)
		}
		norm := normaliseObjC(p.ObjCType)

		switch {
		case isNSURLType(norm):
			needsFoundation = true
			params = append(params, ctorParam{
				goName: pName,
				goType: "string",
				rawExpr: fmt.Sprintf(
					"foundation.NSURLFileURLWithPath(foundation.NSStringStringWithUTF8String(%s))",
					pName,
				),
				isObject: true,
			})
		case isNSStringType(norm):
			needsFoundation = true
			params = append(params, ctorParam{
				goName:   pName,
				goType:   "string",
				rawExpr:  fmt.Sprintf("foundation.NSStringStringWithUTF8String(%s)", pName),
				isObject: true,
			})
		default:
			impSet := make(typemap.ImportSet)
			resolved := rawParamGoType(p.ObjCType, ctx, m, impSet)
			goType := qualifyRaw(resolved, fw, rawPkgAlias, ctx.GenericParams)
			maps.Copy(extraImports, impSet)
			params = append(params, ctorParam{
				goName:   pName,
				goType:   goType,
				rawExpr:  pName,
				isObject: isObjectPointerType(goType, m),
			})
		}
	}

	return &ctorEntry{
		goName:          "New" + goTypeName + strings.TrimPrefix(rawInit, "Init"),
		rawInitGoName:   rawInit,
		rawInitSelector: method.Selector,
		params:          params,
		hasNSError:      method.IsNSError,
		needsFoundation: needsFoundation,
		extraImports:    extraImports,
	}
}

func writeConstructor(
	w io.Writer,
	goTypeName, rawPkgAlias, className, genericArgs string,
	c ctorEntry,
) {
	fromIDFn := rawPkgAlias + "." + className + "FromID" + genericArgs

	paramParts := make([]string, 0, len(c.params))
	for _, p := range c.params {
		paramParts = append(paramParts, p.goName+" "+p.goType)
	}
	paramStr := strings.Join(paramParts, ", ")

	retStr := "*" + goTypeName
	if c.hasNSError {
		retStr = "(*" + goTypeName + ", error)"
	}

	fmt.Fprintf(w, "// %s creates a new [%s].\n", c.goName, goTypeName)
	fmt.Fprintf(w, "func %s(%s) %s {\n", c.goName, paramStr, retStr)

	if c.rawInitGoName == "" {
		// Plain +new.
		fmt.Fprintf(
			w,
			"\t_id := objc.Send[objc.ID](objc.ID(objc.GetClass(%q)), objc.RegisterName(\"new\"))\n",
			className,
		)
		fmt.Fprintf(w, "\treturn &%s{inner: %s(_id)}\n", goTypeName, fromIDFn)
	} else {
		// alloc + send init selector directly via objc.Send[objc.ID], bypassing the raw
		// init method's return type which may be objc.ID or *T depending on the emitter.
		fmt.Fprintf(
			w,
			"\t_alloc := objc.Send[objc.ID](objc.ID(objc.GetClass(%q)), objc.RegisterName(\"alloc\"))\n",
			className,
		)

		sendArgs := make([]string, 0, len(c.params))
		for _, p := range c.params {
			sendArgs = append(sendArgs, ctorParamSendExpr(p))
		}

		if c.hasNSError {
			fmt.Fprintf(w, "\tvar _nsErr uintptr\n")
			allArgs := append(
				append(
					[]string{"_alloc", fmt.Sprintf("objc.RegisterName(%q)", c.rawInitSelector)},
					sendArgs...),
				"unsafe.Pointer(&_nsErr)",
			)
			fmt.Fprintf(w, "\t_id := objc.Send[objc.ID](%s)\n", strings.Join(allArgs, ", "))
			fmt.Fprintf(
				w,
				"\tif _nsErr != 0 {\n\t\treturn nil, pureobjc.NSErrorToError(objc.ID(_nsErr))\n\t}\n",
			)
			fmt.Fprintf(w, "\treturn &%s{inner: %s(_id)}, nil\n", goTypeName, fromIDFn)
		} else {
			allArgs := append(
				[]string{"_alloc", fmt.Sprintf("objc.RegisterName(%q)", c.rawInitSelector)},
				sendArgs...)
			fmt.Fprintf(w, "\t_id := objc.Send[objc.ID](%s)\n", strings.Join(allArgs, ", "))
			fmt.Fprintf(w, "\treturn &%s{inner: %s(_id)}\n", goTypeName, fromIDFn)
		}
	}
	fmt.Fprintf(w, "}\n\n")
}

// ctorParamSendExpr returns the expression for passing a constructor parameter to
// objc.Send[objc.ID]. ObjC object types need .Ptr() to extract the raw objc.ID;
// primitives, plain C pointers, and struct pointers are passed directly.
func ctorParamSendExpr(p ctorParam) string {
	if p.isObject {
		return p.rawExpr + ".Ptr()"
	}
	return p.rawExpr
}

// isObjectPointerType reports whether a resolved Go type is a single pointer to
// an ObjC class (and therefore has a Ptr() method). Pointers to primitives or C
// structs (e.g. *uint8, *raw.IOUSBHostCIMessage) are not objects.
func isObjectPointerType(goType string, m *typemap.Mapper) bool {
	if !strings.HasPrefix(goType, "*") {
		return false
	}
	base := strings.TrimPrefix(goType, "*")
	if strings.HasPrefix(base, "*") {
		return false // double pointer (out-param)
	}
	if idx := strings.IndexByte(base, '['); idx >= 0 {
		base = base[:idx]
	}
	if idx := strings.LastIndexByte(base, '.'); idx >= 0 {
		base = base[idx+1:]
	}
	_, ok := m.OwnerIndex[base]
	return ok
}

// ── Fluent With* setter generation ────────────────────────────────────────────

type withEntry struct {
	goName             string // e.g. "WithVariableStore"
	rawSetterGoName    string // e.g. "SetVariableStore"
	param              withParam
	isNSArray          bool   // true: variadic slice → NSArray
	sliceElemType      string // parameter elem type (interface for provider, raw ptr otherwise)
	arrayFromID        string // FromID call matching the raw setter param, e.g. "foundation.NSArrayFromID[objc.ID]"
	arrayClass         string // ObjC class to instantiate: "NSArray" or "NSMutableArray"
	providerMethodName string // non-empty when elem is an abstract base; e.g. "asNetworkDeviceConfiguration"
	extraImports       map[string]string
}

type withParam struct {
	goName  string // variable name in the generated func
	goType  string // Go type (string for NSURL/NSString, *raw.T or ProviderIface for objects, uint64 etc.)
	rawExpr string // expression passed to the raw setter (may differ from param name)
}

func buildWithSetter(
	prop meta.Property,
	_ string,
	cls meta.Class,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
	_ trialNameMap,
	_ string,
	abstractBases abstractBaseIndex,
) *withEntry {
	// Derive the raw setter Go method name from the selector.
	setterSel := prop.Setter
	if setterSel == "" {
		if len(prop.Name) == 0 {
			return nil
		}
		setterSel = "set" + strings.ToUpper(prop.Name[:1]) + prop.Name[1:] + ":"
	}
	rawSetterGoName := naming.MethodName(setterSel)

	// Verify the setter method actually exists in the raw bindings.
	setterExists := false
	for _, method := range cls.Methods {
		if method.Selector == setterSel && !method.IsClassMethod {
			setterExists = true
			break
		}
	}
	if !setterExists {
		return nil
	}

	// Derive With* Go name from the property name.
	goWithName := "With" + strings.ToUpper(prop.Name[:1]) + prop.Name[1:]

	norm := normaliseObjC(prop.ObjCType)

	extraImports := map[string]string{}

	// NSArray property → variadic With*(items ...*T).
	if looksLikeNSArray(prop.ObjCType) {
		elemObjC := extractNSArrayElem(prop.ObjCType)
		if elemObjC == "" {
			return nil
		}
		impSet := make(typemap.ImportSet)
		goElem := m.GoType(elemObjC, ctx, impSet)
		if goElem == "" || goElem == "unsafe.Pointer" {
			return nil
		}
		goElem = qualifyRaw(goElem, fw, rawPkgAlias, ctx.GenericParams)
		if !isObjectPointerType(goElem, m) {
			return nil
		}
		// Resolve the raw setter's actual param type — nested generics may have
		// been degraded there (e.g. NSArray[objc.ID]) — so the built array
		// matches it exactly.
		rawProp := qualifyRaw(
			m.GoType(prop.ObjCType, ctx, impSet),
			fw,
			rawPkgAlias,
			ctx.GenericParams,
		)
		alias, container, rawElem, ok := parseArrayGoType(rawProp)
		if !ok {
			return nil
		}
		arrayFromID := fmt.Sprintf("%s.%sFromID[%s]", alias, container, rawElem)
		maps.Copy(extraImports, impSet)
		// Check whether the element type is an abstract base class — use provider interface.
		rawElemClass := strings.TrimPrefix(strings.TrimPrefix(goElem, "*"), rawPkgAlias+".")
		if goTypeName, isBase := abstractBases[rawElemClass]; isBase {
			ifaceName := providerInterfaceName(goTypeName)
			methName := providerMethodName(goTypeName)
			return &withEntry{
				goName:             goWithName,
				rawSetterGoName:    rawSetterGoName,
				isNSArray:          true,
				sliceElemType:      ifaceName,
				arrayFromID:        arrayFromID,
				arrayClass:         container,
				providerMethodName: methName,
				extraImports:       extraImports,
			}
		}
		return &withEntry{
			goName:          goWithName,
			rawSetterGoName: rawSetterGoName,
			isNSArray:       true,
			sliceElemType:   goElem,
			arrayFromID:     arrayFromID,
			arrayClass:      container,
			extraImports:    extraImports,
		}
	}

	// NSURL → string.
	if isNSURLType(norm) {
		pName := naming.ParamName(prop.Name)
		return &withEntry{
			goName:          goWithName,
			rawSetterGoName: rawSetterGoName,
			param: withParam{
				goName: pName,
				goType: "string",
				rawExpr: fmt.Sprintf(
					"foundation.NSURLFileURLWithPath(foundation.NSStringStringWithUTF8String(%s))",
					pName,
				),
			},
			extraImports: extraImports,
		}
	}

	// NSString → string.
	if isNSStringType(norm) {
		pName := naming.ParamName(prop.Name)
		return &withEntry{
			goName:          goWithName,
			rawSetterGoName: rawSetterGoName,
			param: withParam{
				goName:  pName,
				goType:  "string",
				rawExpr: fmt.Sprintf("foundation.NSStringStringWithUTF8String(%s)", pName),
			},
			extraImports: extraImports,
		}
	}

	// All other types: resolve via typemap. Block-typed properties go through
	// the shared adapter model so the setter param matches the raw signature.
	impSet := make(typemap.ImportSet)
	resolved := rawParamGoType(prop.ObjCType, ctx, m, impSet)
	if resolved == "" || resolved == "unsafe.Pointer" {
		return nil
	}
	goType := qualifyRaw(resolved, fw, rawPkgAlias, ctx.GenericParams)
	// Skip protocol/interface types — setters that take protocols need delegate machinery.
	if strings.HasPrefix(goType, "interface {") ||
		strings.HasPrefix(strings.TrimPrefix(goType, "*"), "interface {") {
		return nil
	}
	maps.Copy(extraImports, impSet)

	pName := naming.ParamName(prop.Name)

	// Check whether the scalar type is an abstract base class — use provider interface.
	rawClass := strings.TrimPrefix(strings.TrimPrefix(goType, "*"), rawPkgAlias+".")
	if goTypeName, isBase := abstractBases[rawClass]; isBase {
		ifaceName := providerInterfaceName(goTypeName)
		methName := providerMethodName(goTypeName)
		return &withEntry{
			goName:          goWithName,
			rawSetterGoName: rawSetterGoName,
			param: withParam{
				goName:  pName,
				goType:  ifaceName,
				rawExpr: pName + "." + methName + "()",
			},
			extraImports: extraImports,
		}
	}

	return &withEntry{
		goName:          goWithName,
		rawSetterGoName: rawSetterGoName,
		param: withParam{
			goName:  pName,
			goType:  goType,
			rawExpr: pName,
		},
		extraImports: extraImports,
	}
}

func writeWithMethod(w io.Writer, typeName string, we withEntry) {
	if we.isNSArray {
		// Variadic signature.
		loopExpr := "_v.Ptr()"
		if we.providerMethodName != "" {
			loopExpr = "_v." + we.providerMethodName + "().Ptr()"
		}
		fmt.Fprintf(
			w,
			"// %s sets the collection, converting the Go slice to an %s.\n",
			we.goName,
			we.arrayClass,
		)
		fmt.Fprintf(
			w,
			"func (x *%s) %s(items ...%s) *%s {\n",
			typeName,
			we.goName,
			we.sliceElemType,
			typeName,
		)
		fmt.Fprintf(
			w,
			"\tif len(items) == 0 {\n\t\tx.inner.%s(nil)\n\t\treturn x\n\t}\n",
			we.rawSetterGoName,
		)
		fmt.Fprintf(w, "\t_ptrs := make([]objc.ID, len(items))\n")
		fmt.Fprintf(w, "\tfor _i, _v := range items { _ptrs[_i] = %s }\n", loopExpr)
		fmt.Fprintf(w, "\t_arr := %s(\n", we.arrayFromID)
		fmt.Fprintf(w, "\t\tobjc.Send[objc.ID](objc.ID(objc.GetClass(%q)),\n", we.arrayClass)
		fmt.Fprintf(w, "\t\t\tobjc.RegisterName(\"arrayWithObjects:count:\"),\n")
		fmt.Fprintf(w, "\t\t\tunsafe.Pointer(&_ptrs[0]), uint(len(_ptrs))))\n")
		fmt.Fprintf(w, "\tx.inner.%s(_arr)\n", we.rawSetterGoName)
		fmt.Fprintf(w, "\treturn x\n}\n\n")
		return
	}

	// Scalar / object setter.
	pn := we.param.goName
	pt := we.param.goType
	fmt.Fprintf(
		w,
		"// %s sets the %s property and returns the receiver for chaining.\n",
		we.goName,
		pn,
	)
	fmt.Fprintf(w, "func (x *%s) %s(%s %s) *%s {\n", typeName, we.goName, pn, pt, typeName)
	fmt.Fprintf(w, "\tx.inner.%s(%s)\n", we.rawSetterGoName, we.param.rawExpr)
	fmt.Fprintf(w, "\treturn x\n}\n\n")
}

// ── Method generation (async, slice getters, BoolNSError) ─────────────────────

type methodKind int

const (
	kindAsync       methodKind = iota
	kindBoolNSError            // (bool, error) → error
	kindSlice                  // NSArray return → []T
)

type methodEntry struct {
	kind         methodKind
	goName       string
	rawGoName    string
	extraImports map[string]string

	blockObjCParams     []string
	blockGoParamTypes   []string // Go types of the raw completion block's params
	asyncNonBlockParams []asyncParam

	sliceElemGoType string
	sliceFromID     string // FromID call converting objc.ID elements; "" = direct assignment
	sliceHasError   bool   // raw getter returns (NSArray, error)
}

type asyncParam struct {
	goName          string
	goType          string
	rawExpr         string
	needsFoundation bool
}

// buildAsyncMethod assembles the entry for a completion-handler method whose
// block only reports an optional NSError. The generated wrapper blocks on a
// channel and converts the NSError to a Go error.
func buildAsyncMethod(
	method meta.Method,
	rawGoName string,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
) *methodEntry {
	lastParam := method.Params[len(method.Params)-1]
	blockParams := parseBlockObjCParams(lastParam.ObjCType)
	// Skip blocks with non-NSError result params — typed result channels
	// require knowing the raw closure signature.
	for _, bp := range blockParams {
		if !isNSErrorType(normaliseObjC(bp)) {
			return nil
		}
	}
	// Resolve the block's Go signature exactly as the raw emitter did, so the
	// generated closure matches the raw method's parameter type. Degraded
	// blocks come back as objc.Block and are rejected below.
	blockImpSet := make(typemap.ImportSet)
	blockGoType := emit.BlockGoFuncType(lastParam.ObjCType, ctx, m, blockImpSet, m.OwnerIndex)
	if !strings.HasPrefix(blockGoType, "func(") || !strings.HasSuffix(blockGoType, ")") {
		return nil
	}
	var blockGoParamTypes []string
	if csv := strings.TrimSuffix(
		strings.TrimPrefix(blockGoType, "func("),
		")",
	); strings.TrimSpace(
		csv,
	) != "" {
		for t := range strings.SplitSeq(csv, ",") {
			blockGoParamTypes = append(
				blockGoParamTypes,
				qualifyRaw(strings.TrimSpace(t), fw, rawPkgAlias, ctx.GenericParams),
			)
		}
	}
	if len(blockGoParamTypes) != len(blockParams) {
		return nil
	}
	for _, t := range blockGoParamTypes {
		// The NSError param must be expressible as an objc.ID for conversion.
		if t != "unsafe.Pointer" && t != "objc.ID" && !strings.HasPrefix(t, "*") {
			return nil
		}
	}

	var nonBlockParams []asyncParam
	needsFoundation := false
	extraImports := map[string]string{}
	for _, p := range method.Params[:len(method.Params)-1] {
		pName := naming.ParamName(p.Name)
		if pName == "" {
			pName = fmt.Sprintf("arg%d", len(nonBlockParams))
		}
		norm := normaliseObjC(p.ObjCType)
		switch {
		case isNSURLType(norm):
			needsFoundation = true
			nonBlockParams = append(nonBlockParams, asyncParam{
				goName: pName,
				goType: "string",
				rawExpr: fmt.Sprintf(
					"foundation.NSURLFileURLWithPath(foundation.NSStringStringWithUTF8String(%s))",
					pName,
				),
				needsFoundation: true,
			})
		case isNSStringType(norm):
			needsFoundation = true
			nonBlockParams = append(nonBlockParams, asyncParam{
				goName:          pName,
				goType:          "string",
				rawExpr:         fmt.Sprintf("foundation.NSStringStringWithUTF8String(%s)", pName),
				needsFoundation: true,
			})
		default:
			impSet := make(typemap.ImportSet)
			resolved := rawParamGoType(p.ObjCType, ctx, m, impSet)
			maps.Copy(extraImports, impSet)
			nonBlockParams = append(nonBlockParams, asyncParam{
				goName:  pName,
				goType:  qualifyRaw(resolved, fw, rawPkgAlias, ctx.GenericParams),
				rawExpr: pName,
			})
		}
	}
	if needsFoundation {
		extraImports["foundation"] = foundationImportPath
	}
	maps.Copy(extraImports, blockImpSet)
	return &methodEntry{
		kind:                kindAsync,
		goName:              asyncGoMethodName(method.Selector),
		rawGoName:           rawGoName,
		blockObjCParams:     blockParams,
		blockGoParamTypes:   blockGoParamTypes,
		asyncNonBlockParams: nonBlockParams,
		extraImports:        extraImports,
	}
}

func buildMethod(
	method meta.Method,
	_ string,
	_ meta.Class,
	fw *meta.FrameworkMeta,
	ctx typemap.Context,
	m *typemap.Mapper,
	rawPkgAlias string,
) *methodEntry {
	rawGoName := naming.MethodName(method.Selector)

	// Async completion.
	if isAsyncCompletion(method) {
		return buildAsyncMethod(method, rawGoName, fw, ctx, m, rawPkgAlias)
	}

	// BoolNSError — only when no explicit non-error params.
	if method.IsNSError && strings.TrimSpace(method.Return.ObjCType) == "BOOL" &&
		len(method.Params) == 0 {
		return &methodEntry{
			kind:      kindBoolNSError,
			goName:    boolNSErrorGoMethodName(method.Selector),
			rawGoName: rawGoName,
		}
	}

	// NSArray → slice (no params, getter only).
	if looksLikeNSArray(method.Return.ObjCType) && len(method.Params) == 0 {
		elemObjC := extractNSArrayElem(method.Return.ObjCType)
		if elemObjC == "" {
			return nil
		}
		impSet := make(typemap.ImportSet)
		goElem := m.GoType(elemObjC, ctx, impSet)
		if goElem == "" || goElem == "unsafe.Pointer" {
			return nil
		}
		goElem = qualifyRaw(goElem, fw, rawPkgAlias, ctx.GenericParams)
		if !isPointerType(goElem) {
			return nil
		}
		// Resolve the raw getter's actual return type — nested generics may have
		// been degraded there (e.g. NSArray[objc.ID]) — and convert elements back
		// to the typed form via FromID when needed.
		rawRet := qualifyRaw(
			m.GoReturnType(method.Return.ObjCType, ctx, impSet),
			fw,
			rawPkgAlias,
			ctx.GenericParams,
		)
		_, _, rawElem, ok := parseArrayGoType(rawRet)
		if !ok {
			return nil
		}
		sliceFromID := ""
		switch rawElem {
		case goElem:
			// element types already match; assign directly
		case "objc.ID":
			sliceFromID = fromIDCallPrefix(goElem)
			if sliceFromID == "" {
				return nil
			}
		default:
			goElem = rawElem // trust the raw signature
		}
		goName := rawGoName
		if method.IsNSError {
			goName = strings.TrimSuffix(goName, "AndReturnError")
		}
		extraImports := map[string]string{}
		maps.Copy(extraImports, impSet)
		return &methodEntry{
			kind:            kindSlice,
			goName:          goName,
			rawGoName:       rawGoName,
			sliceElemGoType: goElem,
			sliceFromID:     sliceFromID,
			sliceHasError:   method.IsNSError,
			extraImports:    extraImports,
		}
	}

	return nil
}

func writeMethod(w io.Writer, typeName string, me methodEntry) {
	switch me.kind {
	case kindAsync:
		writeAsyncMethod(w, typeName, me)
	case kindBoolNSError:
		writeBoolNSErrorMethod(w, typeName, me)
	case kindSlice:
		writeSliceMethod(w, typeName, me)
	}
}

func writeAsyncMethod(w io.Writer, typeName string, me methodEntry) {
	paramParts := make([]string, 0, 1+len(me.asyncNonBlockParams))
	paramParts = append(paramParts, "ctx context.Context")
	for _, p := range me.asyncNonBlockParams {
		paramParts = append(paramParts, p.goName+" "+p.goType)
	}
	paramStr := strings.Join(paramParts, ", ")

	rawArgs := make([]string, 0, len(me.asyncNonBlockParams)+1)
	for _, p := range me.asyncNonBlockParams {
		rawArgs = append(rawArgs, p.rawExpr)
	}

	// The closure signature mirrors the raw method's block param exactly. The
	// first NSError param (if any) is converted to a Go error.
	closureParams := make([]string, 0, len(me.blockGoParamTypes))
	errIdx := -1
	errGoType := ""
	for i, goType := range me.blockGoParamTypes {
		closureParams = append(closureParams, fmt.Sprintf("_p%d %s", i, goType))
		if errIdx < 0 && isNSErrorType(normaliseObjC(me.blockObjCParams[i])) {
			errIdx = i
			errGoType = goType
		}
	}

	closureBody := "\t\t_ch <- nil\n"
	switch {
	case errIdx < 0:
		// no error param — completion only signals
	case errGoType == "unsafe.Pointer":
		closureBody = fmt.Sprintf("\t\tif uintptr(_p%d) != 0 {\n", errIdx) +
			fmt.Sprintf("\t\t\t_ch <- pureobjc.NSErrorToError(objc.ID(uintptr(_p%d)))\n", errIdx) +
			"\t\t} else {\n\t\t\t_ch <- nil\n\t\t}\n"
	case errGoType == "objc.ID":
		closureBody = fmt.Sprintf("\t\tif _p%d != 0 {\n", errIdx) +
			fmt.Sprintf("\t\t\t_ch <- pureobjc.NSErrorToError(_p%d)\n", errIdx) +
			"\t\t} else {\n\t\t\t_ch <- nil\n\t\t}\n"
	default: // *foundation.NSError or similar object pointer
		closureBody = fmt.Sprintf("\t\tif _p%d != nil {\n", errIdx) +
			fmt.Sprintf("\t\t\t_ch <- pureobjc.NSErrorToError(_p%d.Ptr())\n", errIdx) +
			"\t\t} else {\n\t\t\t_ch <- nil\n\t\t}\n"
	}

	fmt.Fprintf(w, "// %s blocks until the operation completes or ctx is cancelled.\n", me.goName)
	fmt.Fprintf(w, "func (x *%s) %s(%s) error {\n", typeName, me.goName, paramStr)
	fmt.Fprintf(w, "\t_ch := make(chan error, 1)\n")

	rawArgs = append(rawArgs, "func("+strings.Join(closureParams, ", ")+") {\n"+closureBody+"\t}")
	fmt.Fprintf(w, "\tx.inner.%s(%s)\n", me.rawGoName, strings.Join(rawArgs, ", "))
	fmt.Fprintf(w, "\tselect {\n")
	fmt.Fprintf(w, "\tcase err := <-_ch:\n\t\treturn err\n")
	fmt.Fprintf(w, "\tcase <-ctx.Done():\n\t\treturn ctx.Err()\n")
	fmt.Fprintf(w, "\t}\n}\n\n")
}

func writeBoolNSErrorMethod(w io.Writer, typeName string, me methodEntry) {
	fmt.Fprintf(w, "// %s returns any validation error.\n", me.goName)
	fmt.Fprintf(w, "func (x *%s) %s() error {\n", typeName, me.goName)
	fmt.Fprintf(w, "\t_, err := x.inner.%s()\n", me.rawGoName)
	fmt.Fprintf(w, "\treturn err\n}\n\n")
}

func writeSliceMethod(w io.Writer, typeName string, me methodEntry) {
	elemExpr := "arr.ObjectAtIndex(uint(i))"
	if me.sliceFromID != "" {
		elemExpr = me.sliceFromID + "(" + elemExpr + ")"
	}

	fmt.Fprintf(w, "// %s returns the collection as a Go slice.\n", me.goName)
	if me.sliceHasError {
		fmt.Fprintf(
			w,
			"func (x *%s) %s() ([]%s, error) {\n",
			typeName,
			me.goName,
			me.sliceElemGoType,
		)
		fmt.Fprintf(w, "\tarr, err := x.inner.%s()\n", me.rawGoName)
		fmt.Fprintf(w, "\tif err != nil {\n\t\treturn nil, err\n\t}\n")
		fmt.Fprintf(w, "\tif arr == nil {\n\t\treturn nil, nil\n\t}\n")
		fmt.Fprintf(w, "\tout := make([]%s, arr.Count())\n", me.sliceElemGoType)
		fmt.Fprintf(w, "\tfor i := range out {\n\t\tout[i] = %s\n\t}\n", elemExpr)
		fmt.Fprintf(w, "\treturn out, nil\n}\n\n")
		return
	}
	fmt.Fprintf(w, "func (x *%s) %s() []%s {\n", typeName, me.goName, me.sliceElemGoType)
	fmt.Fprintf(w, "\tarr := x.inner.%s()\n", me.rawGoName)
	fmt.Fprintf(w, "\tif arr == nil {\n\t\treturn nil\n\t}\n")
	fmt.Fprintf(w, "\tout := make([]%s, arr.Count())\n", me.sliceElemGoType)
	fmt.Fprintf(w, "\tfor i := range out {\n\t\tout[i] = %s\n\t}\n", elemExpr)
	fmt.Fprintf(w, "\treturn out\n}\n\n")
}

// rawParamGoType resolves a raw method/function parameter type exactly as the
// raw emitter does: block params go through the shared adapter model in
// package emit so the idiomatic layer's closures keep matching the raw
// signatures; everything else uses the type mapper directly.
func rawParamGoType(
	objcType string,
	ctx typemap.Context,
	m *typemap.Mapper,
	impSet typemap.ImportSet,
) string {
	if _, isBlock := m.ResolveBlockSignature(objcType); isBlock {
		return emit.BlockGoFuncType(objcType, ctx, m, impSet, m.OwnerIndex)
	}
	resolved := m.GoType(objcType, ctx, impSet)
	if resolved == "" {
		resolved = "unsafe.Pointer"
	}
	return resolved
}

// ── ObjC pattern detection ─────────────────────────────────────────────────────

func isAsyncCompletion(m meta.Method) bool {
	if strings.TrimSpace(m.Return.ObjCType) != "void" || len(m.Params) == 0 {
		return false
	}
	last := m.Params[len(m.Params)-1]
	if !last.IsBlock {
		return false
	}
	t := strings.TrimSpace(last.ObjCType)
	return strings.HasPrefix(t, "void (^") && !strings.Contains(t, "BOOL *")
}

func parseBlockObjCParams(blockObjCType string) []string {
	idx := strings.Index(blockObjCType, ")(")
	if idx < 0 {
		return nil
	}
	after := blockObjCType[idx+2:]
	end := strings.LastIndex(after, ")")
	if end < 0 {
		return nil
	}
	inner := strings.TrimSpace(after[:end])
	if inner == "" || inner == "void" {
		return nil
	}
	var parts []string
	depth, start := 0, 0
	for i, r := range inner {
		switch r {
		case '<':
			depth++
		case '>':
			depth--
		case ',':
			if depth == 0 {
				parts = append(parts, strings.TrimSpace(inner[start:i]))
				start = i + 1
			}
		}
	}
	if tail := strings.TrimSpace(inner[start:]); tail != "" {
		parts = append(parts, tail)
	}
	return parts
}

func looksLikeNSArray(objcType string) bool {
	if strings.Contains(objcType, "(^") {
		return false
	}
	t := normaliseObjC(objcType)
	return strings.HasPrefix(t, "NSArray") || strings.HasPrefix(t, "NSMutableArray")
}

func extractNSArrayElem(objcType string) string {
	_, after, ok := strings.Cut(objcType, "<")
	if !ok {
		return ""
	}
	end := strings.LastIndex(after, ">")
	if end < 0 {
		return ""
	}
	return strings.TrimSpace(after[:end])
}

// parseArrayGoType splits a resolved NSArray pointer type into its parts, e.g.
// "*foundation.NSMutableArray[*raw.MDLSubmesh]" → ("foundation", "NSMutableArray",
// "*raw.MDLSubmesh", true). ok is false for anything that is not a package-qualified
// generic NSArray/NSMutableArray pointer.
func parseArrayGoType(goType string) (alias, container, elem string, ok bool) {
	if !strings.HasPrefix(goType, "*") || !strings.HasSuffix(goType, "]") {
		return "", "", "", false
	}
	rest := strings.TrimPrefix(goType, "*")
	open := strings.IndexByte(rest, '[')
	if open < 0 {
		return "", "", "", false
	}
	qualified := rest[:open]
	elem = strings.TrimSpace(rest[open+1 : len(rest)-1])
	dot := strings.LastIndexByte(qualified, '.')
	if dot < 0 || elem == "" {
		return "", "", "", false
	}
	alias, container = qualified[:dot], qualified[dot+1:]
	if container != "NSArray" && container != "NSMutableArray" {
		return "", "", "", false
	}
	return alias, container, elem, true
}

// fromIDCallPrefix derives the FromID constructor call for a typed element, e.g.
// "*raw.CNLabeledValue[*foundation.NSString]" → "raw.CNLabeledValueFromID[*foundation.NSString]".
// Returns "" when the element type has no derivable FromID constructor.
func fromIDCallPrefix(goElem string) string {
	if !strings.HasPrefix(goElem, "*") {
		return ""
	}
	base := strings.TrimPrefix(goElem, "*")
	args := ""
	if idx := strings.IndexByte(base, '['); idx >= 0 {
		args = base[idx:]
		base = base[:idx]
	}
	if !strings.Contains(base, ".") {
		return ""
	}
	return base + "FromID" + args
}

func isNSErrorType(objcType string) bool {
	t := normaliseObjC(objcType)
	return strings.HasPrefix(t, "NSError") && strings.Contains(t, "*")
}

func isNSURLType(objcType string) bool {
	if strings.Contains(objcType, "(^") || strings.Contains(objcType, "(*") {
		return false // block or C function pointer returning NSURL, not an NSURL value
	}
	t := normaliseObjC(objcType)
	return t == "NSURL *" || strings.HasPrefix(t, "NSURL *") || t == "NSURL"
}

func isNSStringType(objcType string) bool {
	if strings.Contains(objcType, "(^") || strings.Contains(objcType, "(*") {
		return false // block or C function pointer returning NSString, not an NSString value
	}
	t := normaliseObjC(objcType)
	return strings.HasPrefix(t, "NSString") && strings.Contains(t, "*")
}

func isPointerType(goType string) bool {
	return strings.HasPrefix(strings.TrimSpace(goType), "*")
}

func normaliseObjC(t string) string {
	t = strings.TrimSpace(t)
	for _, q := range []string{
		"_Nullable ", "_Nonnull ", "_Null_unspecified ", "__kindof ",
		"__unsafe_unretained ", "__autoreleasing ", "__strong ", "__weak ",
	} {
		t = strings.TrimPrefix(t, q)
	}
	for _, q := range []string{" _Nullable", " _Nonnull", " _Null_unspecified"} {
		t = strings.TrimSuffix(t, q)
	}
	return strings.TrimSpace(t)
}

// ── Naming ─────────────────────────────────────────────────────────────────────

func detectClassPrefix(fw *meta.FrameworkMeta) string {
	names := sortedKeys(fw.Classes)
	if len(names) == 0 {
		return ""
	}
	prefix := names[0]
	for _, name := range names[1:] {
		i := 0
		for i < len(prefix) && i < len(name) && prefix[i] == name[i] {
			i++
		}
		prefix = prefix[:i]
		if prefix == "" {
			return ""
		}
	}
	trimAt := len(prefix)
	for i, r := range prefix {
		if r >= 'a' && r <= 'z' {
			trimAt = i
			break
		}
	}
	// When the common prefix was cut at a lowercase letter, the preceding
	// uppercase letter starts the first word of the class name proper
	// (e.g. "CHHaptic" → trim at 'a' gives "CHH"; the final 'H' belongs to
	// "Haptic"), so drop it from the prefix.
	if trimAt < len(prefix) && trimAt > 0 {
		trimAt--
	}
	prefix = prefix[:trimAt]
	if len(prefix) < 2 {
		return ""
	}
	return prefix
}

func trialTypeName(className, prefix string) string {
	if prefix != "" && strings.HasPrefix(className, prefix) {
		stripped := className[len(prefix):]
		// A stripped name starting with a digit is an invalid Go identifier,
		// and one starting lowercase would be unexported. Keep the full class
		// name in those cases (e.g. AVB17221ACMPInterface stays as-is).
		if len(stripped) > 0 &&
			(stripped[0] >= '0' && stripped[0] <= '9' || stripped[0] >= 'a' && stripped[0] <= 'z') {
			return className
		}
		return stripped
	}
	return className
}

func asyncGoMethodName(selector string) string {
	base := naming.MethodName(selector)
	if strings.HasSuffix(base, "WithCompletionHandler") {
		return base[:len(base)-len("WithCompletionHandler")]
	}
	if strings.HasSuffix(base, "CompletionHandler") {
		return base[:len(base)-len("CompletionHandler")]
	}
	return base
}

func boolNSErrorGoMethodName(selector string) string {
	base := naming.MethodName(selector)
	if strings.HasSuffix(base, "WithError") {
		return base[:len(base)-len("WithError")]
	}
	return base
}

// qualifyRaw rewrites a mapper-resolved Go type for use inside a trial package:
//   - package references to the current framework become the raw alias
//   - bare same-framework identifiers (classes, enums, structs, protocols) get
//     the raw alias prefix, wherever they appear (generic brackets, func types)
//   - leaked generic param names (e.g. ObjectType) become objc.ID, matching the
//     instantiation trial uses for generic raw classes
func qualifyRaw(
	goType string,
	fw *meta.FrameworkMeta,
	rawPkgAlias string,
	genericParams []string,
) string {
	fwPkg := strings.ToLower(fw.Framework)

	var sb strings.Builder
	for i := 0; i < len(goType); {
		if !isIdentByte(goType[i], true) {
			sb.WriteByte(goType[i])
			i++
			continue
		}
		j := i + 1
		for j < len(goType) && isIdentByte(goType[j], false) {
			j++
		}
		word := goType[i:j]
		prevIsDot := i > 0 && goType[i-1] == '.'
		nextIsDot := j < len(goType) && goType[j] == '.'
		switch {
		case nextIsDot && !prevIsDot && word == fwPkg:
			// The mapper qualified a type with the framework's own package
			// name — rewrite to the raw alias. Token-scoped so substring
			// packages (corefoundation vs foundation) are untouched.
			sb.WriteString(rawPkgAlias)
		case prevIsDot || nextIsDot:
			sb.WriteString(word)
		case identInList(word, genericParams):
			sb.WriteString("objc.ID")
		case isFrameworkOwnType(word, fw):
			sb.WriteString(rawPkgAlias)
			sb.WriteByte('.')
			sb.WriteString(word)
		default:
			sb.WriteString(word)
		}
		i = j
	}
	return sb.String()
}

func isIdentByte(c byte, start bool) bool {
	if c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || c == '_' {
		return true
	}
	return !start && c >= '0' && c <= '9'
}

func identInList(word string, list []string) bool {
	return slices.Contains(list, word)
}

// isFrameworkOwnType reports whether name is a type the current framework's raw
// package defines (class, enum, struct, or protocol interface). Names are
// matched in the form the raw emitter exports them (e.g. struct vmpktdesc is
// emitted as Vmpktdesc, enum vmnet_return_t as Vmnet_return_t).
func isFrameworkOwnType(name string, fw *meta.FrameworkMeta) bool {
	return frameworkOwnTypeNames(fw)[name]
}

// ownTypeNameCache memoises the per-framework exported type-name set.
// Generation is sequential (GenerateIdiomatic loops frameworks one at a time)
// so a plain map is safe.
var ownTypeNameCache = map[*meta.FrameworkMeta]map[string]bool{}

// frameworkOwnTypeNames builds the set of Go type names the raw package
// exports for fw, in both their metadata and exported spellings.
func frameworkOwnTypeNames(fw *meta.FrameworkMeta) map[string]bool {
	if set, ok := ownTypeNameCache[fw]; ok {
		return set
	}
	set := make(map[string]bool)
	for className := range fw.Classes {
		set[className] = true
	}
	for enumName := range fw.Enums {
		set[enumName] = true
		set[naming.GoTypeName(enumName)] = true
	}
	// Protocols that share a name with a class are emitted with a "Protocol"
	// suffix (e.g. protocol NSObject → type NSObjectProtocol interface).
	for protocolName := range fw.Protocols {
		goName := naming.GoTypeName(protocolName)
		set[goName] = true
		set[goName+"Protocol"] = true
	}
	for structName := range fw.Structs {
		set[structName] = true
		set[naming.ExportedTypeName(structName)] = true
	}
	// Struct typedefs (e.g. NSRange → struct _NSRange) are emitted as Go type
	// aliases in the raw package.
	for typedefName, target := range fw.Typedefs {
		if !strings.HasPrefix(target, "struct ") {
			continue
		}
		bare := strings.TrimSpace(strings.TrimSuffix(strings.TrimPrefix(target, "struct "), "*"))
		if _, ok := fw.Structs[bare]; ok {
			set[naming.ExportedTypeName(typedefName)] = true
		}
	}
	ownTypeNameCache[fw] = set
	return set
}

// ── File utilities ─────────────────────────────────────────────────────────────

func sortedKeys(m map[string]meta.Class) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func writeImportBlock(w io.Writer, imports map[string]string) {
	type imp struct{ alias, path string }
	list := make([]imp, 0, len(imports))
	for alias, path := range imports {
		list = append(list, imp{alias, path})
	}
	sort.Slice(list, func(i, j int) bool {
		// Tie-break on alias: the same path can be imported under two aliases
		// (e.g. raw and foundation in the trial foundation package).
		if list[i].path != list[j].path {
			return list[i].path < list[j].path
		}
		return list[i].alias < list[j].alias
	})
	fmt.Fprint(w, "import (\n")
	for _, i := range list {
		segs := strings.Split(i.path, "/")
		defaultAlias := segs[len(segs)-1]
		if i.alias == defaultAlias || i.alias == i.path {
			fmt.Fprintf(w, "\t%q\n", i.path)
		} else {
			fmt.Fprintf(w, "\t%s %q\n", i.alias, i.path)
		}
	}
	fmt.Fprint(w, ")\n\n")
}

