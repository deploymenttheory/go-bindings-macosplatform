// emitProvidersFile writes <pkgname>_providers_generated.go containing one provider
// interface per abstract base class in the framework.
func emitProvidersFile(
	outDir, pkgName, rawPkgAlias, rawPkgPath string,
	abstractBases abstractBaseIndex,
	fw *meta.FrameworkMeta,
	m *typemap.Mapper,
) error {
	if len(abstractBases) == 0 {
		return nil
	}

	baseNames := make([]string, 0, len(abstractBases))
	for name := range abstractBases {
		baseNames = append(baseNames, name)
	}
	sort.Strings(baseNames)

	providerImports := make(typemap.ImportSet)
	var body bytes.Buffer
	for _, baseName := range baseNames {
		goTypeName := abstractBases[baseName]
		ifaceName := providerInterfaceName(goTypeName)
		methName := providerMethodName(goTypeName)
		rawType := providerRawType(baseName, fw, m, rawPkgAlias, providerImports)
		if rawType == "" {
			continue
		}
		fmt.Fprintf(
			&body,
			"// %s is implemented by %s and any idiomatic type wrapping a %s subclass.\n",
			ifaceName,
			goTypeName,
			baseName,
		)
		fmt.Fprintf(&body, "type %s interface {\n\t%s() %s\n}\n\n", ifaceName, methName, rawType)
	}
	if body.Len() == 0 {
		return nil
	}

	candidates := map[string]string{rawPkgAlias: rawPkgPath, "objc": objcImportPath}
	maps.Copy(candidates, providerImports)

	var buf bytes.Buffer
	fmt.Fprint(&buf, generatedHeader+"\n")
	fmt.Fprint(&buf, buildTag+"\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkgName)
	writeImportBlock(&buf, usedImports(body.Bytes(), candidates))
	buf.Write(body.Bytes())

	fname := pkgName + "_providers_generated.go"
	if err := os.WriteFile(filepath.Join(outDir, fname), buf.Bytes(), 0o600); err != nil {
		return fmt.Errorf("write %s: %w", fname, err)
	}
	return nil
}

// ── C function wrappers (CFErrorRef * / NSError ** out-parameters) ────────────

const objcerrorsImportPath = "github.com/deploymenttheory/go-bindings-macosplatform/internal/pureobjc/objcerrors"

// isCFErrorOutParam returns true when the ObjC type is a CFErrorRef out-parameter.
func isCFErrorOutParam(objcType string) bool {
	t := normaliseObjC(objcType)
	return t == "CFErrorRef *" || t == "CFErrorRef **"
}

// emitFunctionWrappers writes <pkgname>_functions_generated.go for any functions
// in fw whose last parameter is a CFErrorRef * out-parameter. Each wrapper:
//   - Omits the error out-parameter from its Go signature
//   - Passes unsafe.Pointer(&_cfErr) internally to the raw function
//   - Returns error on failure, converting the CFErrorRef via toll-free bridge
//
// bool-returning functions become func(...) error.
// Pointer-returning functions become func(...) (unsafe.Pointer, error).
//
// Returns the set of exported wrapper names it emitted so the generic
// C-function pass can avoid redeclaring them.
func emitFunctionWrappers(
	outDir, pkgName, rawPkgAlias, rawPkgPath string,
	fw *meta.FrameworkMeta,
	m *typemap.Mapper,
) (map[string]bool, error) {
	ctx := typemap.Context{Framework: fw.Framework}

	type wrapParam struct {
		goName string
		goType string
	}
	type wrapEntry struct {
		rawFnName string
		params    []wrapParam
		retIsBool bool   // true → wrapper returns error; false → returns (unsafe.Pointer, error)
		goRetType string // Go return type when retIsBool=true ("bool" → use !, others → use == 0)
	}

	var entries []wrapEntry
	emittedNames := make(map[string]bool)
	needsFoundation := false

	for _, fn := range emit.EmittableFunctions(fw, nil) {
		if len(fn.Params) == 0 {
			continue
		}
		if !isCFErrorOutParam(fn.Params[len(fn.Params)-1].ObjCType) {
			continue
		}

		var params []wrapParam
		for _, p := range fn.Params[:len(fn.Params)-1] {
			pName := naming.ParamName(p.Name)
			if pName == "" {
				pName = fmt.Sprintf("arg%d", len(params))
			}
			impSet := make(typemap.ImportSet)
			goType := m.GoType(p.ObjCType, ctx, impSet)
			if goType == "" || goType == "unsafe.Pointer" {
				goType = "unsafe.Pointer"
			} else {
				goType = qualifyRaw(goType, fw, rawPkgAlias, ctx.GenericParams)
			}
			if strings.Contains(goType, "foundation.") {
				needsFoundation = true
			}
			params = append(params, wrapParam{goName: pName, goType: goType})
		}

		retObjC := strings.TrimSpace(fn.Return.ObjCType)

		// Resolve the actual Go return type to decide on comparison operator and
		// whether this function is eligible for wrapping at all.
		retImpSet := make(typemap.ImportSet)
		goRet := m.GoType(fn.Return.ObjCType, ctx, retImpSet)
		if goRet == "" {
			goRet = "unsafe.Pointer"
		}

		retIsBool := retObjC == "bool" || retObjC == "BOOL" || retObjC == "_Bool" ||
			retObjC == "Boolean" ||
			goRet == "bool"

		if !retIsBool {
			// For pointer-returning functions, confirm the Go type is a pointer.
			// Non-pointer, non-bool returns (e.g. CFIndex→int64) cannot be compared
			// to nil so skip them rather than generating invalid code.
			if goRet != "unsafe.Pointer" && !isPointerType(goRet) {
				continue
			}
		}

		entries = append(entries, wrapEntry{
			rawFnName: fn.Name,
			params:    params,
			retIsBool: retIsBool,
			goRetType: goRet,
		})
		emittedNames[naming.ExportedFunctionName(fn.Name)] = true
	}

	if len(entries) == 0 {
		return emittedNames, nil
	}

	var buf bytes.Buffer
	fmt.Fprint(&buf, generatedHeader+"\n")
	fmt.Fprint(&buf, buildTag+"\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkgName)

	imports := map[string]string{
		rawPkgAlias:  rawPkgPath,
		"fmt":        "fmt",
		"unsafe":     "unsafe",
		"objcerrors": objcerrorsImportPath,
	}
	if needsFoundation {
		imports["foundation"] = foundationImportPath
	}
	writeImportBlock(&buf, imports)

	for _, e := range entries {
		var sigParts, callArgs []string
		for _, p := range e.params {
			sigParts = append(sigParts, p.goName+" "+p.goType)
			callArgs = append(callArgs, p.goName)
		}
		callArgs = append(callArgs, "unsafe.Pointer(&_cfErr)")

		// The raw layer exports C functions under their Go names
		// (snake_case → PascalCase; already-exported names unchanged).
		goFnName := naming.ExportedFunctionName(e.rawFnName)
		rawCall := fmt.Sprintf("%s.%s(%s)", rawPkgAlias, goFnName, strings.Join(callArgs, ", "))
		sig := strings.Join(sigParts, ", ")

		fmt.Fprintf(
			&buf,
			"// %s calls [%s.%s], converting the CFErrorRef out-parameter to a structured Go error on failure.\n",
			goFnName,
			rawPkgAlias,
			goFnName,
		)

		if e.retIsBool {
			fmt.Fprintf(&buf, "func %s(%s) error {\n", goFnName, sig)
			fmt.Fprintf(&buf, "\tvar _cfErr unsafe.Pointer\n")
			if e.goRetType == "bool" {
				// pure Go bool: use !
				fmt.Fprintf(&buf, "\tif !%s {\n", rawCall)
			} else {
				// CF Boolean / BOOL → uint8 or similar: 0 means failure
				fmt.Fprintf(&buf, "\t_ok := %s\n", rawCall)
				fmt.Fprintf(&buf, "\tif _ok == 0 {\n")
			}
			fmt.Fprintf(&buf, "\t\treturn _cfErrOrMsg(_cfErr, %q)\n", e.rawFnName)
			fmt.Fprintf(&buf, "\t}\n")
			fmt.Fprintf(&buf, "\treturn nil\n}\n\n")
		} else {
			fmt.Fprintf(&buf, "func %s(%s) (unsafe.Pointer, error) {\n", goFnName, sig)
			fmt.Fprintf(&buf, "\tvar _cfErr unsafe.Pointer\n")
			fmt.Fprintf(&buf, "\t_result := %s\n", rawCall)
			fmt.Fprintf(&buf, "\tif _result == nil {\n")
			fmt.Fprintf(&buf, "\t\treturn nil, _cfErrOrMsg(_cfErr, %q)\n", e.rawFnName)
			fmt.Fprintf(&buf, "\t}\n")
			fmt.Fprintf(&buf, "\treturn _result, nil\n}\n\n")
		}
	}

	// Package-private helper emitted once per package.
	fmt.Fprint(
		&buf,
		"// _cfErrOrMsg converts a CFErrorRef to a structured Go error (domain, code,\n",
	)
	fmt.Fprint(
		&buf,
		"// description, failure reason). CFError is toll-free bridged with NSError so\n",
	)
	fmt.Fprint(
		&buf,
		"// no CGo is required. Falls back to a plain message if no error was populated.\n",
	)
	fmt.Fprint(&buf, "func _cfErrOrMsg(ptr unsafe.Pointer, fn string) error {\n")
	fmt.Fprint(&buf, "\tif ptr != nil {\n")
	fmt.Fprint(&buf, "\t\treturn objcerrors.CFErrorToError(ptr)\n")
	fmt.Fprint(&buf, "\t}\n")
	fmt.Fprintf(&buf, "\treturn fmt.Errorf(\"[%%s] operation failed\", fn)\n")
	fmt.Fprint(&buf, "}\n")

	fname := pkgName + "_functions_generated.go"
	if err := os.WriteFile(filepath.Join(outDir, fname), buf.Bytes(), 0o600); err != nil {
		return nil, fmt.Errorf("write %s: %w", fname, err)
	}
	return emittedNames, nil
}
